/*
	======================================================================
	  [핵심 개념] 관계 연산자 (비교 연산자)
	======================================================================
	  두 데이터의 크기를 비교하여 "맞다(true)" 혹은 "틀리다(false)"로 
	  대답해주는 연산자입니다.
	
	  [관계 연산자 종류]
	  >   (크다)       : 6 > 2  (맞음 -> true)
	  >=  (크거나 같다)  : 2 >= 5 (틀림 -> false)
	  <   (작다)       : 2 < 3  (맞음 -> true)
	  <=  (작거나 같다)  : 8 <= 3 (틀림 -> false)
	  ==  (같다)       : 8 == 3 (틀림 -> false)  ※ 자바에서 '같다'는 기호 2개(==)를 씁니다!
	  !=  (다르다)     : 8 != 6 (맞음 -> true)
*/
public class Opr02 {

	public static void main(String[] args) {
		int a = 10, b = 4;
		
		boolean test; // <--- 기본으로 저장된 기본값 false
		int c; // <--- 기본으로 저장된 기본값 0 저장
		char n; // <--- 기본으로 저장된 기본값 '' 저장
		
		// 10이 4보다 크냐?
		test = a > b;
		System.out.println(a + " > " + b + " = " + test);
		
		// a가 b보다 작냐?
		test = a < b;
		System.out.println(a + " < " + b + " = " + test);
		
		test = (a+b > a-b);
		System.out.println(a + " + " + b + " > " + a + " - " + b + " = " + test);
	}

}
