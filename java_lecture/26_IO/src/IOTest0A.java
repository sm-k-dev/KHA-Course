/*
	주제 : 바이트 단위의 데이터를 출력 기기에 내보내는 통로인
	       출력스트림 통로 역할을 하는 PrintStream클래스 사용 예제

	■ 이 파일의 목표 : write 메소드의 오버로딩 3종류를 "직접 실행"해서 차이를 확인한다

	   PrintStream 클래스에 만들어져 있는 write 메소드는 오버로딩 되어 있습니다.
	   (오버로딩 = 같은 이름의 메소드를 매개변수 구성만 다르게 여러 개 만드는 것)

		1.  void write(int b)
		   - 모니터 장치에 1바이트의 데이터 하나만 내보내어 출력

		2.  void write(byte[] b)
		   - 매개변수 b로 전달한 byte 배열 전체를 한번에 모니터 장치에 내보내어 출력

		3.  void write(byte[] b, int off, int len)
		   - 매개변수 b로 전달한 전체 byte 배열에 저장된 데이터 중에서
		     b[off] 위치부터 len개의 바이트만 골라서 한번에 모니터 장치에 내보내어 출력

	■ 함께 배우는 것 : flush() 메소드
	   - 출력 통로는 성능을 위해 데이터를 조금씩 모았다가 내보내는 경우가 있다.
	   - flush() = "모아둔 것을 지금 당장 전부 내보내라!"라는 명령.
	   - write만 하고 출력이 화면에 안 보일 때는 flush()를 호출하면 된다.
	     (println은 내부에서 줄바꿈과 함께 자동으로 내보내 주기 때문에 지금까지 몰라도 됐던 것)
*/

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;



public class IOTest0A {

	public static void main(String[] args) {
		
		//1. 키보드로 입력받은  전체 데이터 중에서 1 바이트 크기의 데이터만 
		//   입력 스트림 통로를 통해 읽어 들여 저장할 변수
		int data = 0;
		
		try {
			//2. PrintStream 출력 스트림 통로 역할의 객체 주소 얻기
			//   (OutputStream 부모 추상 클래스 자료형의  참조변수에 저장 - 업캐스팅)
			OutputStream  outputStream = System.out;
			
			//======================================================
			//시연 1.  void write(int b)  :   1 바이트씩 하나하나 내보내기
			//======================================================			
			//'J'=74, 'a'=97, 'v'=118, 'a'=97 (문자는 컴퓨터 안에서 번호로 저장된다)
			outputStream.write(74);  //1 바이트 내보냄 -> 'J'
			outputStream.write(97);  //1 바이트 내보냄 -> 'a'
			outputStream.write(118); //1 바이트 내보냄 -> 'v'
			outputStream.write(97);  //1 바이트 내보냄 -> 'a'
			outputStream.write(10);  //줄바 꿈 문자 \n  (10)도 내보냄 
			outputStream.flush();    //모아둔것을 지금 즉시 화면으로 전부 내보내라! 
			/*
			 [텍스트 모델링] write(int b) : 한 번 호출에 1바이트씩만 통로에 실린다

			   write(74) write(97) write(118) write(97) write(10)
			      │         │         │          │         │
			      ▼         ▼         ▼          ▼         ▼
			   ═══[74]═════[97]═════[118]═══════[97]══════[10]═══\n   모니터 : Java(줄바꿈)
			         출력 스트림 통로 (1바이트씩 다섯 번에 나눠 이동)
			*/			
			
			//==============================================================
			//시연 2. void write(byte[] b)  :  배열 전체를 한번에 내보내기 
			//============================================================
			
			//내보낼 바이트들을 미리 배열에 담아 둔다
			//72='H',  101='e',   108='l',  108='l',  111='o',  33='!'
			byte[]  msg = {72,  101, 108, 108,  111,  33,  10 }; //마지막 10은  줄바꿈 '\n'
			
			outputStream.write(msg);  // msg byte 배열 전체(7바이트)를 한번에 출려스트림 통로에 실어 모니터로 내보냄
			outputStream.flush();     // 즉시! 모니터 화면에 강제로 모두 보내기 
			/*
			 [텍스트 모델링] write(byte[] b) : 배열째로 한 번에 통로에 실린다

			   msg 배열  [ 72 ][ 101 ][ 108 ][ 108 ][ 111 ][ 33 ][ 10 ]
			                0      1      2      3      4     5     6   index
			                └──────────────전부 한 번에──────────────┘
			                                  │
			                                  ▼
			   ═══════[72,101,108,108,111,33,10]═══════\n  모니터 : Hello!(줄바꿈)

			   ★ 시연 1과 비교 : 다섯 번 호출 vs 한 번 호출.
			     내보낼 데이터가 많을수록 배열로 묶어 한번에 보내는 쪽이 효율적이다!
			*/	
			
			//========================================================================
			//시연3. void write(byte[]  b,  int off,  int len) : 배열의 일부 구간만 내보내기 
			//=======================================================================
			
			//msg byte 배열에서  1번 index 부터 (off=1)  4개(len=4)만 골라 모니터 화면에 내보낸다
			outputStream.write(msg, 1, 4); //msg[1] ~ msg[4] : 101,108,108,111 -> "ello"
			outputStream.write(10);        //보기 좋게 \n 한줄 줄바꿈 추가 
			outputStream.flush();
			/*
			 [텍스트 모델링] write(b, off, len) : off 위치부터 len개만 골라 실린다

			   msg 배열  [ 72 ][ 101 ][ 108 ][ 108 ][ 111 ][ 33 ][ 10 ]
			                0      1      2      3      4     5     6   index
			                       └─off=1 부터 len=4 개 ─┘
			                       [101 ][ 108 ][ 108 ][ 111 ]  만 선택됨
			                                  │
			                                  ▼
			   ═══════[101,108,108,111]═══════▶  모니터 : "ello"

			   ★ 나중에 파일/네트워크에서 "읽은 만큼만 내보내기"를 할 때 반드시 쓰는 형태다.
			*/	
			
			//===================================================================================================
			//시연 4. 입력스트림 통로와 연결 : 입력 스트림 통로로 부터 읽은 바이트 단위 데이터 그대로 write메소드로 모니터에 되돌려주기(에코) 
			//====================================================================================================
			
			//3. 입력 스트림 통로 역할의 객체 얻기 
			InputStream inputStream = System.in;
			
			//4. 사용자에게  입력 요청 메세지 출력
			System.out.print("문자를 입력하세요(끝내려면 Ctrl+Z 후 Enter) : ");
			
			//5. 입력 스트림 통로에서 더이상 읽어 들일 데이터가 없을때(read()호출했을때 반환값 -1)까지
			//   입력 스트림 통로에서 계속 반복해서 읽어들여  출력스트림 PrintStream객체의 write()메소드로 모니터에 반복 내보내어 출력
			while(  (data = inputStream.read())   != -1       ) {
				
				//한번씩 읽은 1바이트 크기의 데이터를 모니터에 내보낸다
				outputStream.write(data);
			}
			/*
			 [텍스트 모델링] 에코 구조 - data 변수가 입력과 출력 통로 사이의 1바이트 중계 창구

			 키보드         입력 스트림(System.in)      data       출력 스트림(System.out)      모니터
			 [ hi입력 ] --> ═══[104]═[105]═[10]═══▶  ┌─────┐  ═══════════════════════▶  [ hi 출력 ]
			                       read()로 1바이트   │ 104 │   write()로 1바이트
			                                        └─────┘
			 ※ 입력한 것이 그대로 다시 보이는 프로그램을 "에코(메아리)"라고 부른다.
			 ※ 엔터의 \n(10)까지 읽혀 되돌려지는 것은 IOTest01에서 확인한 그대로다.
			*/	
		
			
		}catch(IOException  e) {
			e.printStackTrace();  //입 출력 예외 발생하면 보여줄 예외 메세지 출력
		}
		

		/*
			결론 1 : write는 오버로딩 3종이 있다.
			         write(int b)           = 1바이트 하나
			         write(byte[] b)        = 배열 전체 한번에
			         write(byte[] b, off, len) = 배열의 off부터 len개만 한번에

			결론 2 : 데이터가 많으면 배열로 묶어 한번에 보내는 쪽이 효율적이다.
			         (호출 5번 vs 1번 - 시연 1과 2의 차이)

			결론 3 : flush() = 통로에 모아둔 데이터를 지금 즉시 전부 내보내는 명령.
			         write 후 화면에 안 보이면 flush()를 호출한다.

			결론 4 : read()가 준 정수를 write(int)에 그대로 넘기면 에코가 된다.
			         data 변수가 입력 통로와 출력 통로를 잇는 1바이트 중계 창구 역할을 한다.
		*/
		

	}

}












