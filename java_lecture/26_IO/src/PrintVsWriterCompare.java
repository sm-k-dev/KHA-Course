

/*
 * ==================================================================
 * [비교 실행 예제] PrintStream vs PrintWriter
 *                 같은 데이터를 두 통로로 출력해 파일 바이트를 비교한다
 * ==================================================================
 *
 * ------------------------------------------------------------------
 * 1. 이 예제로 확인할 두 가지 사실
 * ------------------------------------------------------------------
 *
 *   사실 1. println 계열로 텍스트를 출력하면
 *           두 클래스의 "결과 바이트는 완전히 같다"
 *
 *   사실 2. write(int) 를 호출하면
 *           두 클래스의 "결과 바이트가 완전히 다르다"
 *           여기서 두 클래스의 혈통 차이가 드러난다
 *
 * ------------------------------------------------------------------
 * 2. 상속 계보 모델 - 소속이 다르다
 * ------------------------------------------------------------------
 *
 *   바이트 스트림 집안              문자 스트림 집안
 *   OutputStream (추상)             Writer (추상)
 *     +-- FileOutputStream            +-- FileWriter
 *     +-- BufferedOutputStream        +-- BufferedWriter
 *     +-- PrintStream  <-- 여기       +-- PrintWriter  <-- 여기
 *
 * ------------------------------------------------------------------
 * 3. write(int n) 동작 차이 모델 - 이 예제의 핵심
 * ------------------------------------------------------------------
 *
 *   '가' 의 문자 정수값 = 44032
 *
 *   PrintStream.write(44032)   : "int 를 바이트 1개로 취급한다"
 *
 *     44032 를 2진수로 : 10101100 00000000
 *                        +--------+--------
 *                          위 8비트  아래 8비트
 *     바이트 통로는 1바이트(8비트)만 다루므로
 *     아래 8비트 00000000 만 남기고 나머지를 버린다
 *     --> 파일에 00 (1바이트) 기록. '가' 는 사라지고 깨진 데이터만 남는다
 *
 *   PrintWriter.write(44032)   : "int 를 문자 1개(char)로 취급한다"
 *
 *     44032 --> 문자 '가' 로 해석
 *           --> 내보내는 순간 UTF-8 규칙으로 변환
 *           --> 파일에 EA B0 80 (3바이트) 기록. '가' 가 온전히 저장된다
 *
 *   같은 write(44032) 한 줄이 혈통에 따라 전혀 다른 결과를 만든다.
 * ==================================================================
 */

import java.io.IOException;
import java.io.PrintStream;
import java.io.PrintWriter;
import java.nio.file.Files; //파일 크기 확인(size메소드 제공), 바이트 읽기(readAllBytes메소드 제공) 등
							//검증용으로 사용할 NIO 패키지의 파일 작업 클래스 (전부 static 메소드 제공)

import java.nio.file.Path; //파일 경로 저장 객체 

public class PrintVsWriterCompare {
	public static void main(String[] args) throws IOException {
        //==============================================================
        // [0] 검증에 사용할 파일 경로 2개를 Path 객체로 준비
        //==============================================================
        //
        //   Path.of("ps_out.txt")
        //   - "ps_out.txt" 라는 경로 문자열을 담은 Path 객체를 Heap 에 만들고
        //     그 주소를 반환한다. 이 시점에 디스크에는 아무 변화가 없다
        //
        //   [메모리 모델] 아래 두 줄 실행 직후
        //
        //     [Stack]               [Heap]                        [디스크]
        //     psPath (참조) ---->   Path 객체 "ps_out.txt"        (아직 아무 파일 없음)
        //     pwPath (참조) ---->   Path 객체 "pw_out.txt"
        //	
		Path psPath	 = Path.of("ps_out.txt"); //PrintStream 이 기록할 파일 경로 저장되어 있음
		Path pwPath  = Path.of("pw_out.txt"); //PrintWriter 가 기록할 파일 경로 저장되어 있음
		
		//==============================================
		//[1] 같은 텍스트 데이터 5종을 두 통로로 각각 출력
		//==============================================
		System.out.println("===== [1] 같은 데이터를 두 통로(PrintStream, PrintWriter)로 출력 =======");
		
		//PrintStream 출력 스트림 통로 객체 생성
		//- new PrintStream("파일명")  : 그 파일과 연결된 바이트 계열 출력 통로를 연다
		//- 파일이 없으면 새로 만들고, 이미 있으면 내용을 지우고 덮어쓴다.
		//- 파일을 만들 수 없으면 예외 발생 (IOException 계열)
        //
        //   [메모리 모델] 실행 직후
        //     [Stack]            [Heap]                          [디스크]
        //     ps (참조) ---->    PrintStream 객체 (통로 입구) ==> ps_out.txt 생성 (0바이트)
		PrintStream ps = new PrintStream("ps_out.txt");
		
		//PrintWriter 출력 스트림 통로 객체 생성
		//- new PrintWriter("파일명")  :  그 파일과 연결된 문자 계열 출력 스트림(통로) 연다
		//- 파일 생성/덮어쓰기 규칙은 PrintStream 과 같다.
		//
        //   [메모리 모델] 실행 직후
        //     [Stack]            [Heap]                          [디스크]
        //     pw (참조) ---->    PrintWriter 객체 (통로 입구) ==> pw_out.txt 생성 (0바이트)
		PrintWriter pw = new PrintWriter("pw_out.txt");
		
        //--------------------------------------------------------------
        //같은 데이터 5종을 두 통로에 나란히 출력한다
        //println 공통 동작 : 값을 문자로 변환 --> 기록 --> 줄바꿈(0A) 자동 추가
        //
        //[기록 추적표] 한 줄 실행될 때마다 각 파일에 쌓이는 바이트 (두 파일 동일)
        //
        //  실행 줄            | 변환 결과   | 기록되는 바이트               | 크기 | 누적
        //  -----------------+-----------+---------------------------+------+-----
        //  println(10)      | "10"      | 31 30 0A                  | 3    | 3
        //  println(3.14)    | "3.14"    | 33 2E 31 34 0A            | 5    | 8
        //  println('A')     | "A"       | 41 0A                     | 2    | 10
        //  println("가나")    | "가나"    | EA B0 80 EA B0 98 0A      | 7    | 17
        //  println("Hello") | "Hello"   | 48 65 6C 6C 6F 0A         | 6    | 23
        //
        //  0A = 줄바꿈 1바이트 / 한글 1자 = UTF-8 로 3바이트 / 영문,숫자 1자 = 1바이트
        //--------------------------------------------------------------
		ps.println(10);     pw.println(10);    //int    10  ----> 문자 "10" 으로 변환 후 파일에 기록
		ps.println(3.14);   pw.println(3.14);  //double 3.14 ---> 문자 "3.14"으로 변환 후 파일에 기록
		ps.println('A');    pw.println('A');   //char   'A" ---> 문자 그대로 파일에 기록
		ps.println("가나");  pw.println("가나"); //한글 문자열 ----> UTF-8  3바이트  x 2자 기록
		ps.println("Hello");pw.println("Hello");//영문 문자열 ----> 1바이트  x 5자 기록
		
		//출력 스트림들 통로 닫기
		//- close() : 통로 내부 버퍼에 남아있는 데이터를 전부 파일로 내보내고(확정)
		//            파일과 연결을 끊는다
		ps.close();   //PrintStream 객체 통로 닫기
		pw.close();   //PrintWriter 객체 통로 닫기
						//주의! PrintWriter 는 내부 버퍼를 쓰므로
				        //close(또는 flush) 전에는 파일이 0바이트로 보일 수 있다.
				        //닫지 않고 [2]의 크기 비교를 하면 23 이 아니라 0 이 나온다
		
		//=====================================================
		//[2] 두 파일의 크기와 바이트 내용 비교 ===> 사실 1 증명
		//=======================================================
        // --------------------------------------------------------------
        // [디스크 배치 모델] 이 시점의 두 파일 내부 (완전히 동일한 23바이트)
        //
        //   행  | 내용    | 바이트                    | 크기
        //   ----+---------+---------------------------+------
        //   1   | 10      | 31 30 0A                  | 3
        //   2   | 3.14    | 33 2E 31 34 0A            | 5
        //   3   | A       | 41 0A                     | 2
        //   4   | 가나    | EA B0 80 EA B0 98 0A      | 7
        //   5   | Hello   | 48 65 6C 6C 6F 0A         | 6
        //   ----+---------+---------------------------+------
        //                                        합계   23
        // --------------------------------------------------------------
		
		//Files.size(Path객체)  :  디스크에서 그 파일의 실제 크기를 바이트 단위로 반환
		//- 반환 타입이 long인 이유 :  파일 크기는 int 의 최대값(약 21억)을 넘을수 있으므로 더 큰 정수 long으로 받는다
		long psSize = Files.size(psPath);  //ps_out.txt 의 크기를 psSize에 저장
		long pwSize = Files.size(pwPath);  //pw_out.txt 의 크기를 pwSize에 저장
		
		System.out.println("PrintStream 파일 크기 = " + psSize);  //예상 출력 : PrintStream통로 사용후 파일의 크기 : 23
		System.out.println("PrintWriter 파일 크기 = " + pwSize);  //예상 출력 : PrintWriter통로 사용후 파일의 크기 : 23
		
		//Files.readAllBytes(Path객체) 
		//- 파일 전체를 처음부터 끝까지 읽어 byte[] 배열로 만들어 반환한다
        //
        //   [메모리 모델] 실행 직후
        //     [Stack]               [Heap]
        //     psBytes (참조) ---->  byte[] 23칸 { 31, 30, 0A, 33, ... }
        //     pwBytes (참조) ---->  byte[] 23칸 { 31, 30, 0A, 33, ... }  (별개의 배열 객체)
		byte[]  psBytes = Files.readAllBytes(psPath);   //ps_out.txt 전체 바이트
		byte[]  pwBytes = Files.readAllBytes(pwPath);   //pw_out.txt 전체 바이트
		
		//java.util.Arrays.equals(배열1, 배열2) 
		//-  두 배열을 비교해서 (1) 길이가 같고  (2) 모든 칸의 값이 같으면 true 반환
        //- 주의! psBytes == pwBytes 로 비교하면 "같은 객체인가" 를 묻는 것이라
        //  내용이 같아도 false 가 나온다. 내용 비교는 반드시 equals 계열을 쓴다 
		boolean same = java.util.Arrays.equals(psBytes, pwBytes);
		
		System.out.println("두 파일의 바이트 정수값이 완전히 같은가? = " + same);
		//                 "두 파일의 바이트 정수값이 완전히 같은가? =    true
		
        //--> 사실 1 증명 완료 : println 텍스트 출력 결과는 두 클래스가 동일하다		
		System.out.println(); //빈 줄 1개 출력 
		
		//================================================================
		//[3] write(int) 차이 실증 ---> 사실 2 증명.  여기서 결과가 갈린다
		//===============================================================
		System.out.println("====== [3] write(44032) 실증 =======");
		
		//실증 용 통로 2개를 새 파일로 다시 연다
		PrintStream  ps2 = new PrintStream("ps_w.txt");   //바이트 계열 스트림 통로
		PrintWriter  pw2 = new PrintWriter("pw_w.txt");   //문자 계열 스트림 통로
		
		//같은 정수 44032 를  같은 이름의 메소드 write 의 매개변수로 전달한다
        //
        //   ps2.write(44032) 의 처리 과정 (OutputStream 의 규칙)
        //     44032 = 2진수 10101100 00000000
        //     --> 아래 8비트 00000000 만 남김 (위 8비트는 버려짐)
        //     --> 파일에 00 (1바이트) 기록
        //
        //   pw2.write(44032) 의 처리 과정 (Writer 의 규칙)
        //     44032 --> 유니코드 44032번 문자 '가' 로 해석
        //     --> UTF-8 변환 : EA B0 80
        //     --> 파일에 3바이트 기록		
		ps2.write(44032); // 바이트 계열  : 아래 8비트만 --> 00기록  (1바이트)
		pw2.write(44032); // 문자 계열   :  '가' 로 해석 --> EA B0 B0 기록 (3바이트)
		
		ps2.close(); //실증룔 통로도 반드시 닫는다 (버퍼 확정)
		pw2.close();
		// --------------------------------------------------------------
        // [실증 결과 모델] 같은 write(44032) 의 디스크 결과
        //
        //   ps_w.txt : | 00 |                1바이트. '가' 정보 대부분 소실
        //   pw_w.txt : | EA | B0 | 80 |      3바이트. '가' 온전히 저장
        //
        //   원인은 단 하나, 부모(소속)가 다르기 때문이다.
        //     PrintStream 의 write(int) = OutputStream 의 규칙 (1바이트 취급)
        //     PrintWriter 의 write(int) = Writer 의 규칙 (문자 1개 취급)
        // --------------------------------------------------------------
		
        //Path.of(...) 를 변수에 담지 않고 메소드 호출 자리에 바로 쓸 수도 있다
		System.out.println("PrintStream write메소드 사용 결과 파일 크기  : " +  Files.size(Path.of("ps_w.txt")));
        //예상 출력: PrintStream write 결과 크기 = 1

		System.out.println("PrintWrter  write메소드 사용 결과 파일 크기  : " +  Files.size(Path.of("pw_w.txt")));
        //예상 출력: PrintWriter write 결과 크기 = 3

		//아래 보조 메소드를 호출해서 두 파일의 바이트 정수들을 16진수로 직접 확인한다.
		printHex("ps_w.txt");    //예상 출력: ps_w.txt 바이트 : 00
		printHex("pw_w.txt");   //예상 출력: pw_w.txt 바이트 : EA B0 80
		
	}//main 메소드 끝

	//======================================================================
	//[보조 메소드] printHex
	// - 매개변수로 전달 받은 파일의 모든 바이트 값들을 16진수 두자리씩 화면에 출력 하는 기능 
	//======================================================================
	public  static  void  printHex(String fileName) throws IOException {
		
		//파일 전체를 byte[] 배열에 담아 반환해 옵니다.
		//- Path.of(fileName);  ->  매개변수로 전달한 파일이름 경로를 보관한 Path 객체로 만들어 반환 
		byte[] bytes = Files.readAllBytes(Path.of(fileName));
		
		System.out.print(fileName + " 바이트 : ");
		
		//향상된 for문  : bytes 배열의 칸을 앞에서부터 하나씩 꺼내 b 변수에 담아 반복
		for(byte b  :  bytes ) {
            //----------------------------------------------------------
            //b & 0xFF 가 필요한 이유 (byte 의 음수 저장 원리)
            //
            //  byte 타입은 -128 ~ 127 범위만 담을 수 있다.
            //  그래서 128 이상의 바이트 값은 음수로 바뀌어 저장되어 있다.
            //    예) EA(=234) 는 byte 에 -22 로 저장되어 있다
            //  & 0xFF 는 아래 8비트만 남기는 계산으로,
            //  음수로 보이던 값을 원래의 0 ~ 255 값으로 되돌려 준다.
            //
            //  [복원 회차표] pw_w.txt (EA B0 80) 를 처리할 때
            //
            //    회차 | b (byte 값) | b & 0xFF | %02X 결과
            //    -----+-------------+----------+-----------
            //    1    | -22         | 234      | EA
            //    2    | -80         | 176      | B0
            //    3    | -128        | 128      | 80
            //----------------------------------------------------------
            //			
            //String.format("%02X", 값) 형식 문자열 분해
            //  %  : 여기부터 형식 지정이라는 표시
            //  0  : 자리가 남으면 빈칸 대신 0 으로 채움
            //  2  : 최소 두 자리로 맞춤
            //  X  : 16진수 대문자로 변환 (x 소문자, d 는 10진수)
            //  예) 0 --> "00" / 234 --> "EA"
			System.out.print(" " + String.format("%02X", b & 0xFF));
		} //for 반복문
		
		System.out.println(); //바이트 를 다 출력 한 뒤 한 줄 줄바꿈 출력 	
	
	} //printHex 메소드 끝
	
} // class
