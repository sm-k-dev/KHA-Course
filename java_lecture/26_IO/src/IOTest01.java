/*
	주제 : 키보드로 부터 입력된 데이터의 바이트 총 갯수 세기

	■ 이 파일에서 새로 배우는 것 3가지
	   ① OutputStream의 write(int b) : 1바이트를 출력 통로에 실어 모니터로 내보내는 메소드
	   ② while( (data = read()) != -1 ) : 읽기와 검사를 한 줄로 쓰는 관용구(공식)
	   ③ ★함정 체험 : "abc"를 입력했는데 갯수가 3이 아니다?! (엔터 바이트의 정체)

	■ ② 관용구 미리 해설 : while( (data = myIn.read()) != -1 )

	   괄호가 실행되는 순서를 분해하면 다음과 같다.

	     1순위 : myIn.read()          -> 통로에서 1바이트를 읽는다 (예: 97)
	     2순위 : data = 97            -> 읽은 값을 data에 저장한다 (안쪽 괄호)
	     3순위 : (97) != -1           -> 대입식 전체는 "저장된 값"이 되므로, 그 값을 -1과 비교
	     4순위 : 참이면 반복 실행, 거짓(-1, 통로 끝)이면 반복 종료

	   즉 IOTest00에서 두 줄로 썼던
	       data = inputStream.read();   +   while(data != -1)
	   을 한 줄로 합친 것이다. 입출력 코드의 표준 공식이므로 눈에 익혀 둘 것!

	■ ①의 참고 : write(97) 과 print(97) 은 완전히 다르다!
	     myOut.write(97)  -> 97번 바이트를 그대로 내보냄  -> 화면에 'a' 가 찍힌다
	     System.out.print(97) -> 정수 97을 문자열 "97"로 바꿔 내보냄 -> 화면에 97 이 찍힌다
*/

import java.io.IOException;
import java.io.InputStream; // 바이트 단위로 데이터를 읽어 들이기 위한 입력 스트림 통로 역할을 하는 추상클래스로
							// InputStream 추상클래스를 구현한 자식 클래스의 객체를 입력스트림 통로로 사용 

import java.io.OutputStream; //바이트 단위로 데이터를 출력 장치에 내보내기 위한 출력 스트림 통로 역할을 하는 추상클래스로
							//OutputStream 추상클래스를 구현한 자식 PrintStream클래스의 객체를 출력 스트림 통로로 사용

public class IOTest01 {

	public static void main(String[] args) {
		
		//키보드 장치에서 입력받은 전체 데이터 중에서 1바이트 크기의 데이터만 읽어들여 저장시킬 변수 
		//(read() 의 반환값 : 읽은 바이트의 정수 0 ~ 255, 입력스트림통로 끝이면 -1을 반환)
		int data = 0;
		
		//읽어 들인 바이트의 총갯수를 계산해서 저장할 변수 (입력스트림으로 부터 데이터를 1번씩 읽어들일때마다 1씩 증가시킬 예정)
		int cnt = 0;
		
		//1. 키보드로 부터 입력한 전체 데이터 중에서 1 바이트 단위로 읽어 들일 입력스트림 통로 역할을 하는
		//   InputStream 추상 부모클래스를 구현한 자식클래스의 객체 주소 얻기 (업캐스팅)
		InputStream   myIn = System.in; //<- 바이트 단위로 읽어 들일 입력스트림 통로 
		/*
		키보드 기기                      입력 스트림 통로 객체
		[          ]   abc 입력  -->   ------------------------------------------------------------
		                               읽어들인 데이터가 흘러가는 통로 방향  ->  ->
		                               1 바이트 단위로 읽어 들임
		                            ------------------------------------------------------------
		*/
		//2. 입력스트림 통로를 통해 읽어들인 바이트를 모니터 출력 장치 화면에 보내어 출력하기 위한 출력 스트림 통로 객체(PrintStream)주소 얻기
		//   (업캐스팅 : 부모 OutputStream 추상클래스자료형의 myOut참조변수에 저장 )
		OutputStream myOut = System.out;
/*
 [텍스트 모델링] 이 프로그램의 전체 배관도 - 입력 통로와 출력 통로를 data 변수가 연결한다

 키보드 기기                입력 스트림 (System.in)          data 변수        출력 스트림 (System.out)       모니터 기기
 [          ] abc 입력 --> ---------------------------  ┌─────────┐   ================================  [          ]
                            1바이트 -> 1바이트 -> read() ─▶│  97     │──▶ write() >>> 바이트 그대로 내보냄     abc 출력
                           ---------------------------  └─────────┘   ================================
                                                        (1바이트 중계 창구 역할)
*/		
		System.out.println("문자를 입력하세요. IOTest01.class 프로그램을 끝내려면 x 혹은 X나  ctrl + z 단축키를 누르세요");
		
		try {
			
			//위 입력 스트림 통로를 통해 1 바이트 씩 읽어 들이는데
			//입력스트림 통로 끝(-1)을 만나기 전까지 반복해서 계속 읽어들여 data변수에 저장 하자.
			//참고. 실행 순서 :  read() 로 읽기  ->  data 변수에 저장 -> 저장된 값을 -1과 비교
			while(  (data =  myIn.read() )  != -1  ) {
				
				//소문자 x나 대문자 X 를 입력하면
				//더이상 입력스트림 통로를 통해서 읽어 들이지 못하게 while 반복문 종료
				//★ data에는 정수(예: 120)가 들어 있는데 어떻게 'x'와 비교가 되나?
				//   -> 문자 'x'도 컴퓨터 안에서는 번호 120이다. int와 char를 비교하면
				//      char가 자동으로 정수로 변환되어 120 == 120 으로 비교된다.
				if(data == 'x'  ||  data == 'X') {
					break;  //break가 cnt++ 보다 앞에 있으므로 x 자신은 갯수에 세어지지 않고 화면에 출력되지도 않은 채로 while반복 종료 
				}
				
				
				//1 바이트 씩 읽어들일때 마다 읽어들인 바이트 수 저장
				cnt++;
				
				//1 바이트 씩 읽어들인 데이터를 출력스트림 통로(PrintStream객체)를 통해 모니터에 읽어들인 바이트 그대로 내보낸다
				myOut.write(data);
			}			
			
		}catch (IOException e) {
			e.printStackTrace();
		}
		
		System.out.println("입력받은 총 문자의 갯수 -> " + cnt);
		
		/*
		 [텍스트 모델링] "abc" + Enter 입력 후 "x" + Enter 로 종료했을 때의 전체 추적

		 통로에 들어온 바이트 (윈도우 기준) : [ 97 │ 98 │ 99 │ 13 │ 10 ]   그리고 이후에 [ 120('x') │ 13 │ 10 ]
		                               'a'   'b'   'c'   \r    \n

		 회차   read()   x인가?   cnt    write() 출력      read() 후 남은 통로
		 ─────────────────────────────────────────────────────────────────────
		  1      97      아니오    1      'a'              [ 98 │ 99 │ 13 │ 10 ]
		  2      98      아니오    2      'b'              [ 99 │ 13 │ 10 ]
		  3      99      아니오    3      'c'              [ 13 │ 10 ]
		  4      13      아니오    4      \r (안 보임)      [ 10 ]
		  5      10      아니오    5      \n (줄바꿈)       (빔 -> 다음 입력 대기)
		  6     120      ★x다!    -      break! (출력도 카운트도 안 하고 탈출)

		 ★★ 함정 체험 : "abc" 3글자를 입력했는데 갯수가 5로 출력된다! ★★
		    이유 : 엔터키의 \r(13), \n(10) 바이트까지 읽혀서 cnt에 세어졌기 때문이다.
		          (맥/리눅스는 엔터가 \n 1바이트라서 4가 나온다 - 운영체제별 차이)
		    -> 이 프로그램이 세는 것은 정확히는 "문자 수"가 아니라 "읽은 바이트 수"다.
		       한글 "가"를 입력하면 글자는 1개인데 3바이트라 3이 세어지는 것도 같은 이유!
		    -> "바이트 단위로는 사람이 생각하는 '글자 수'를 셀 수 없다"
		       => 문자 단위로 읽는 스트림(Reader)이 필요한 두 번째 이유가 된다.

		        [전체 스트림 흐름 요약]

		        키보드 기기
		          |
		          v
		        ------------------------------
		         InputStream (System.in)
		          - 1바이트씩 읽기 (read)
		        ------------------------------
		                   |
		                   v
		                 data 변수  <- 입력과 출력 사이의 1바이트 중계 창구
		                   |
		                   v
		        ------------------------------
		         OutputStream (System.out)
		          - 1바이트씩 출력 (write)
		        ------------------------------
		          |
		          v
		        모니터 기기

			결론 1 : while( (data = read()) != -1 ) 은 "읽고 -> 저장하고 -> 끝인지 검사"를
			         한 줄로 쓰는 입출력 표준 관용구다. (대입식 전체가 저장된 값이 되는 원리)

			결론 2 : write(정수)는 바이트를 그대로 내보내므로 (char) 캐스팅 없이 문자가 출력된다.
			         print(정수)는 숫자를 문자열로 바꿔 출력하므로 결과가 완전히 다르다.

			결론 3 : 문자와 정수는 같은 것의 두 표현이다. 'x'는 곧 120이므로
			         data == 'x' 같은 비교가 가능하다.

			결론 4 : 이 프로그램의 cnt는 "글자 수"가 아니라 "바이트 수"다.
			         엔터(\r\n)도 세어지고 한글은 글자당 3이 세어진다.
			         -> 문자 스트림(Reader)을 배워야 하는 이유.
		*/		
			

	}

}











