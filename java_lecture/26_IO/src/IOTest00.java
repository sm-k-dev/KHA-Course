/*

	스트림(Stream)이란?
	- 키보드 또는 기기를 통해서 입력된 데이터가 바이트 단위의 크기로 흘러가 전송되는 통로

	■ 왜 "통로"가 필요한가?
	   - 키보드, 모니터, 파일, 네트워크 같은 장치들과 자바 프로그램은 서로 떨어져 있다.
	   - 장치와 프로그램 사이에 데이터가 오가려면 데이터가 흘러갈 길이 있어야 하는데
	     그 길 역할을 하는 객체가 스트림이다.
	   - 스트림 속을 흘러가는 데이터의 최소 단위는 1바이트다.
	     (문자든 숫자든 장치를 오갈 때는 전부 바이트로 변환되어 흐른다)

	예)
	키보드 기기                   입력 스트림 (a문자를 읽어 들이기 위한 통로)    출력스트림                           모니터 기기
			[       ] a입력 -->   -----------------------------  |  ============================        [         ]
									1 바이트 ->  1바이트 -> 읽어들임     ->>>>>>>>>>> 바이트 단위로 내보낸다.         a 출력
								----------------------------    |  =============================

	■ ★ 반드시 알아야 하는 사실 1 : 키보드 입력에는 "엔터키"도 포함된다!

	   사용자가 a 를 입력하고 Enter 를 치면, 입력 스트림 통로에는
	   a 한 글자만 들어오는 것이 아니라 엔터키의 바이트까지 함께 들어온다.

	   [텍스트 모델링] "ab" 입력 + Enter 를 쳤을 때 통로 안의 실제 내용 (윈도우 기준)

	   키보드                          입력 스트림 통로 안에 쌓인 바이트들
	   [ ab + Enter ]  ─────▶   ┌────┬────┬────┬────┐
		                            │ 97 │ 98 │ 13 │ 10 │   <- 총 4바이트가 들어와 있다!
		                            └────┴────┴────┴────┘
		                              'a'   'b'   \r    \n
		                                          └─엔터키는 2바이트(\r=13, \n=10)─┘
	   ※ 문자는 컴퓨터 안에서 번호(코드값)로 저장된다 : 'a'=97, 'b'=98 (아스키 코드)

	■ ★ 반드시 알아야 하는 사실 2 : read()가 int(정수)를 반환하는 이유

	   read()는 읽은 바이트를 문자가 아니라 0~255 사이의 "정수"로 반환한다.
	   -> a를 읽으면 'a'가 아니라 97 이 반환된다!
	   -> 그래서 화면에 문자로 출력하려면 (char)97 처럼 char로 강제 캐스팅해야 한다.
	      (char)97 -> 'a'   :  "97번 문자로 바꿔라"라는 뜻

	   왜 처음부터 문자로 안 주는가?
	   -> 통로의 "끝"을 알려 줄 특별한 값이 필요하기 때문이다.
	      데이터는 0~255 를 쓰고, 끝 표시는 그 범위 밖의 -1 을 쓴다.
	      (0~255와 -1을 모두 담으려면 byte로는 부족해서 int로 반환하는 것이다)


입력 스트림 통로 객체 얻기

	System.in
	-> System클래스 내부에 만들어져 있는 in상수에 저장된 InputStream입력스트림 통로 역할을 하는 객체.
	   (부모 InputStream 자료형으로 받지만, 실제로는 그 자식클래스의 객체가 들어 있다 - 업캐스팅 상태)

	InputStream 추상클래스의 read() 메소드
	->  1. InputStream 입력스트림 통로 객체를 통해서 입력한 데이터 전체 크기 중에서 1바이트 크기의 데이터를 한번만 읽어 반환
		2. 읽어들인 바이트 값을 int타입(정수)로 반환합니다.
		   반환값은 읽은 바이트의 정수이며 0부터 255사이의 값입니다.
		   만약 입력스트림 통로 끝에 도달하면 -1을 반환 합니다.
		3. ★통로가 비어 있으면? read()는 사용자가 입력할 때까지 그 자리에서 멈춰서 기다린다!
		   (이것을 "블로킹"이라고 하며, 입력창에서 커서가 깜빡이며 기다리는 상태가 바로 이것)


출력 스트림 통로 객체 얻기

	System.out
	-> System클래스 내부에 만들어져 있는 out상수에 저장된 PrintStream객체(출력스트림 통로 역할을 하는 객체)를 반환해 올수 있다.
	-> PrintStream 객체는 출력장치인 모니터와 연결되어 있는, 바이트 단위로 모니터에 내보내어 출력하는 출력스트림 통로 역할을 하는 객체 메모리입니다.
	-> 사실 우리가 지금까지 매일 쓴 System.out.println()의 out이 바로 이 출력 스트림이었다!

*/

// 주제 :   키보드로 부터 문자를 입력받아  모니터 장치 화면에 출력

import java.io.IOException;
import java.io.InputStream;

public class IOTest00 {

	public static void main(String[] args) {
		
		//입력 스트림 통로에서 1바이트씩 읽어들인 정수값(0~255 또는 끝이면 -1)을 저장할 변수
		int data = 0;
		
		System.out.print("하나의 문자를 입력하세요 : ");
		
		try {
			//1. 키보드와 연결된 입력스트림 통로 객체의 주소를 얻는다.
			//	 (부모 InputStream 추상클래스 자료형의 참조변수에 저장 - 업캐스팅)
			InputStream  inputStream = System.in;
			
			/*
			 [텍스트 모델링 1단계] 통로만 연결된 상태 (아직 아무것도 입력 전)

			 키보드                          입력 스트림 통로 (비어 있음)
			 [        ]  ────연결────▶   ┌────┬────┬────┬────┐
			                                │    │    │    │    │   <- 데이터 없음
			                                └────┴────┴────┴────┘
			 이 상태에서 read()를 부르면? -> 입력이 올 때까지 멈춰서 기다린다 (블로킹)
			*/		
			//1.1. 입력한 전체 데이터 중에서  첫 1바이트만 읽어 들여 data 변수에 저장
			//     (사용자가 아직 입력 전이면 여기서 멈춰 기다리다가,
			//      Enter 를 치는 순간 통로에 바이트들이 들어오고 첫 바이트를 읽는다)
			data = inputStream.read();
			/*
			 [텍스트 모델링 2단계] 사용자가 "ab" + Enter 입력 직후, 첫 read() 실행

			 키보드                          입력 스트림 통로
			 [ ab+Enter ] ──────▶   ┌────┬────┬────┬────┐
			                              │ 97 │ 98 │ 13 │ 10 │
			                              └──┬─┴────┴────┴────┘
			                                 │
			                 read()가 맨 앞 1바이트를 꺼내감
			                           ▼
			                       data = 97           남은 통로 : [ 98 │ 13 │ 10 ]

			 ★ read()는 한 번에 딱 1바이트만 꺼내며, 꺼낸 바이트는 통로에서 사라진다!
			*/
			//1.2. 읽어 들일 데이터가 아직 통로에 존재하면(끝 표시 -1이 아니면)
			//     계속 반복해서 1바이트 단위로 읽어와 data 변수에 저장후 사용
			while(data  != -1) {
				
				//1.3. 읽은 정수값을  (char)로 캐스팅해서 문자로 바꾼 후 
				//     출력 스트림 통로(System.out)를 통해 모니터로 내보낸다.
				//	   예: data 가 97이면 -> (char)97 -> 'a' 가 화면에 출력됨
				System.out.println( (char)data );
				
				//1.4. 입력스트림 통로에서 다음 1바이트를 읽어 저장 (while 조건 검사로 되돌아감)
				data = inputStream.read();
							
			}
			/*
			 [텍스트 모델링 3단계] while문이 도는 동안의 전체 추적 ("ab" + Enter 입력 기준)

			 회차   data 값   -1인가?   (char)data 출력    read() 후 남은 통로
			 ─────────────────────────────────────────────────────────────────
			  1      97       아니오     'a' 출력           [ 98 │ 13 │ 10 ]
			  2      98       아니오     'b' 출력           [ 13 │ 10 ]
			  3      13       아니오     \r 출력(안 보임)    [ 10 ]
			  4      10       아니오     \n 출력(줄바꿈됨)   (비어 있음)
			  5      ...      <- 통로가 비었으므로 read()는 다음 입력을 "기다린다" (블로킹!)

			 ★★ 그래서 이 프로그램은 출력 후에도 끝나지 않는다! ★★
			    콘솔의 키보드 입력 스트림은 "통로가 비었다"와 "통로가 끝났다"를 다르게 취급한다.
			    - 통로가 빈 것     : 또 입력할 수 있으므로 read()는 기다린다 (프로그램 계속)
			    - 통로가 끝난 것   : 사용자가 "입력 끝!" 신호를 보내야 한다
			                        윈도우 : Ctrl + Z 누르고 Enter   /   맥·리눅스 : Ctrl + D
			                        -> 이때 read()가 드디어 -1을 반환하고 while문이 종료된다

			 [텍스트 모델링 4단계] Ctrl+Z 입력 후 종료되는 순간

			 키보드                        입력 스트림 통로
			 [ Ctrl+Z ]  ──────▶      (통로 끝 신호 도착)
			                          read() -> -1 반환 -> while(data != -1) 거짓 -> 반복 종료 -> 프로그램 끝


			 키보드 기기                  입력 스트림 InputStream                     		 출력 스트림  System.out              모니터 기기
			 [          ]   a 입력  -->   --------------------------------------------   |   ==============================   [          ]
			                              1 바이트  ->  1 바이트  ->  읽어들임              		>>>>>>>>>>> 바이트 단위로 내보냄        	a 출력
			                            --------------------------------------------   |   ==============================
			*/			
			
		} catch (IOException e) {
			e.printStackTrace();
		}
		
		/*
		 ⚠ 직접 실험해 볼 것 : 한글을 입력하면 왜 깨질까?

		   "가" 를 입력해 보면 이상한 문자들이 출력된다.
		   이유 : 한글 "가"는 1바이트가 아니라 여러 바이트(UTF-8 기준 3바이트)로 저장되는데,
		          read()는 그것을 1바이트씩 3조각으로 찢어서 읽고
		          (char) 캐스팅도 조각 하나하나에 따로 적용되기 때문에
		          원래 문자로 복원되지 못하고 깨진다.

		   -> "바이트 단위 스트림은 영어는 되지만 한글은 깨진다"
		      이 문제를 해결하는 것이 다음에 배울 "문자 스트림(Reader/Writer)"이다.
		      (문자 스트림은 몇 바이트든 문자 1개 단위로 묶어서 읽어 준다)

		 ─────────────────────────────────────────────────

			결론 1 : 스트림 = 장치와 프로그램 사이에서 데이터가 바이트 단위로 흘러가는 통로.
			         입력 통로는 System.in(InputStream), 출력 통로는 System.out(PrintStream).

			결론 2 : 키보드 입력에는 엔터키 바이트(\r, \n)까지 함께 들어온다.
			         read()는 1바이트씩 꺼내며(꺼낸 것은 통로에서 사라짐),
			         읽은 값을 0~255 정수로 반환하므로 문자 출력엔 (char) 캐스팅이 필요하다.

			결론 3 : 통로가 "빈 것"(read가 기다림/블로킹)과 "끝난 것"(read가 -1 반환)은 다르다.
			         콘솔에서 끝 신호는 윈도우 Ctrl+Z, 맥·리눅스 Ctrl+D 로 보낸다.

			결론 4 : 바이트 스트림으로 한글을 읽으면 여러 바이트가 조각나 깨진다.
			         -> 문자 스트림(Reader)을 배워야 하는 이유.
		*/	
		
		
		

	}

}







