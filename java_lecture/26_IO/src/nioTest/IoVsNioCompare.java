        //   방식 3 : open1 + allocate2 + put3 + flip2
        //            + write1 + position1 + read1
        //            + get3 + hasRemaining4 + close1       = 19회
        //
        //   호출 수가 적다고 좋은 것도, 많다고 나쁜 것도 아니다.
        //   방식 3 은 단계가 많은 대신 위치 제어와 묶음 이동을 얻는다.
