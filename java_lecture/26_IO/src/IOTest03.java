/*
[1]   FileInputStream 클래스란?
   - java.io 패키지에 들어있는 클래스입니다.
   - 컴퓨터에 저장된 파일을 **바이트(byte) 단위로 읽기 위한 도구**입니다.
   - 파일 → 프로그램 쪽으로 데이터가 흘러오도록 만드는 **통로(파이프)** 역할을 합니다.

   쉽게 말해
   - 파일에 있는 내용을 한 글자씩(정확히는 1바이트씩) 꺼내오는 역할을 합니다.



[2]   FileInputStream 객체 만드는 방법

   방법 1. 파일 경로를 문자열로 바로 전달
   - 읽고 싶은 파일의 위치(경로)를 그대로 적어줍니다.

     예)
     FileInputStream fis = new FileInputStream("C:/test/data.txt");

   방법 2. File 객체를 먼저 만든 뒤 전달
   - 파일 정보를 담고 있는 File 객체를 만든 후
   - 그 File 객체를 FileInputStream에 전달합니다.

     예)
     File f = new File("C:/test/data.txt");
     FileInputStream fis = new FileInputStream(f);





[3]   FileInputStream의 주요 메소드 설명

   1. int read()
   - 파일에서 **1바이트만 읽어옵니다**
   - 읽은 데이터는 숫자(int) 형태로 반환됩니다

   왜 문자열(문자)을 읽었는데 숫자(int)로 반환할까?

   이유:
   👉 컴퓨터는 문자를 직접 이해하지 못하고, 오직 숫자만 이해하기 때문입니다.


			   ─────────────────────────────────────────
			   [1] 파일 안에는 사실 "글자"가 없다
			   ─────────────────────────────────────────
			
			   우리가 파일을 열어보면 이렇게 보입니다.
			
			       ABC
			
			   하지만 컴퓨터 내부에서는 이렇게 저장되어 있습니다.
			
			       A → 65
			       B → 66
			       C → 67
			
			   즉,
			   - 파일에는 문자 자체가 저장되는 것이 아니라
			   - 문자를 의미하는 숫자가 저장됩니다
			
			   이 숫자 규칙을
			   - 영어 기준: 아스키 코드(ASCII)
			   - 전 세계 문자 기준: 유니코드(Unicode) 
			     라고 부릅니다.
			
			
			   ─────────────────────────────────────────
			   [2] FileInputStream은 "바이트 단위"로 읽는다
			   ─────────────────────────────────────────
			
			       int data = fis.read();
			
			   FileInputStream의 read() 메소드는
			   - 파일에서 1바이트를 그대로 읽어옵니다
			   - 문자인지, 숫자인지, 한글인지 전혀 신경 쓰지 않습니다
			   - 오직 "숫자 하나"만 읽습니다
			
			   그래서 read()의 결과는
			   - 문자 'A'가 아니라
			   - 숫자 65가 됩니다
			
			
			   ─────────────────────────────────────────
			   [3] 그런데 왜 byte가 아니라 int일까?
			   ─────────────────────────────────────────
			
			   Java의 byte 타입 범위는 다음과 같습니다.
			
			       byte 범위: -128 ~ 127
			
			   하지만 파일에서 읽는 데이터의 범위는
			
			       0 ~ 255 (1바이트)
			
			   문제 발생:
			   - byte 타입에는 128 ~ 255 값을 담을 수 없습니다
			   - 또한 파일의 끝을 의미하는 -1 값을
			     실제 데이터와 구분하기 어렵습니다
			
			
			   ─────────────────────────────────────────
			   [4] 그래서 int를 사용한다
			   ─────────────────────────────────────────
			
			   read() 메소드의 반환 타입이 int인 이유는 다음과 같습니다.
			
			   ✔ 0 ~ 255 범위의 실제 데이터를 안전하게 저장하기 위해
			   ✔ 더 이상 읽을 데이터가 없을 때 -1을 명확히 표현하기 위해
			   ✔ 문자, 이미지, 영상 등 모든 파일을 공통으로 처리하기 위해
			
			   즉,
			   - 0 ~ 255  → 실제 파일 데이터
			   - -1       → 파일의 끝(더 이상 읽을 데이터 없음)
			
			
			   ─────────────────────────────────────────
			   [5] 예제로 보면 더 쉽게 이해됨
			   ─────────────────────────────────────────
			
			   파일 내용:
			       A
			
			   실제 저장된 값:
			       65
			
			   코드 실행 결과:
			       int data = fis.read();
			       System.out.println(data);
			
			   출력:
			       65
			
			   이것은
			   - 문자를 준 것이 아니라
			   - 문자를 의미하는 숫자를 준 것입니다
			
			
			   ─────────────────────────────────────────
			   [6] 문자를 보고 싶다면 직접 변환해야 한다
			   ─────────────────────────────────────────
			
			       char ch = (char) data;
			       System.out.println(ch);
			
			   출력:
			       A
			
			   즉,
			   - read()는 숫자를 읽고
			   - 개발자가 그 숫자를 문자로 해석하는 구조입니다
			
			
			   ─────────────────────────────────────────
			   최종 한 줄 정리
			   ─────────────────────────────────────────
			
			   FileInputStream의 read()가 int를 반환하는 이유는
			   "문자를 반환하기 위해서가 아니라,
			    실제 데이터(0~255)와
			    파일의 끝(-1)을
			    확실하게 구분하기 위해서이다."
			
			      - 더 이상 읽을 데이터가 없으면 **-1을 반환**합니다
			      
			      쉽게 말해
			      - 파일 내용을 한 글자씩 하나하나 읽는 방식입니다


   2. int read(byte[] b)
      - byte 배열 크기만큼 **한 번에 여러 바이트를 읽습니다**
      - 읽은 데이터는 전달한 byte 배열에 저장됩니다
      - 실제로 읽은 바이트 수를 반환합니다
      - 더 이상 읽을 데이터가 없으면 **-1을 반환**합니다

      쉽게 말해
      - 컵으로 물을 한 번에 퍼오듯이
      - 파일 내용을 여러 글자씩 한 번에 읽는 방식입니다


   3. void close()
      - 파일 읽기가 끝나면 반드시 호출해야 합니다
      - 파일과 연결된 통로를 닫아줍니다
      - 사용 중이던 시스템 자원을 반환합니다

      쉽게 말해
      - 사용이 끝난 파이프의 수도꼭지를 잠그는 것과 같습니다
*/


