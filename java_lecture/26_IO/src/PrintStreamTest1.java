import java.io.PrintStream;
import java.io.FileNotFoundException;

public class PrintStreamTest1 {

	public static void main(String[] args) {
		// ====================================
		// 1. PrintStream 객체 생성
		// ====================================
		//	- "ps.txt" 파일과 연결된 출력스트림(데이터가 흘러가는 통로) PrintStream 클래스의 객체를 생성한다.
		//		의미: 자바프로그램에서 만든 데이터를 ps.txt 파일로 보내기 위한 출력 스트림(통로)를 만드는 것.
		//	- 주의!
		//		1. 파일이 존재 하지 않으면 새로 생성됨
		//		2. 파일을 만들 수 없는 상황이면 예외 발생
		
		try {
			PrintStream out2 = System.out; // out상수에 print가 저장되어 있다. 파일이 아니라 모니터에 출력된다.
			
			PrintStream out = new PrintStream("ps.txt");
			// Stream 이 붙은것은 1바이트 단위로 읽거나 쓴다
			
			// =====================================
			// 2. println() 메소드로 데이터 출력
			// =====================================
			// println() 특징
			//	- 데이터를 문자형태로 형변환 하여 출력
			//	- 출력 한 후 자동으로 줄 바꿈(엔터) 처리
			//	- PrintStream 출력 스트림 통로를 통해 연결된"ps.txt"파일로 데이터를 내보내어 기록(출력)한다.
			//
			// --------------------------------------------------------------
			// [통로 변환 모델] out.println(10) 한 줄이 하는 일
			//
			//   [Stack]       [Heap 의 PrintStream 통로]              [디스크 ps.txt]
			//   int 10  --->  1. 정수 10 을 문자 "10" 으로 변환
			//                 2. 문자를 바이트로 변환            ==>  49 48 10 기록
			//                 3. 끝에 줄바꿈을 자동 추가              ('1' '0' 줄바꿈)
			//
			//   숫자 10 이 그대로 가는 것이 아니라 글자 '1' 과 '0' 으로 바뀌어 간다.
			//   DataOutputStream 과의 결정적 차이가 바로 이것이다.
			//     DataOutputStream.writeInt(10) : 이진 4바이트 --> 메모장으로 보면 깨짐
			//     PrintStream.println(10)       : 문자 "10"    --> 메모장으로 읽을 수 있음
			// --------------------------------------------------------------
			
			out.println(10);		// 정수 10을 문자 "10"으로 바꿔서 ps.txt 파일에 기록
			out.println(3.4);		// 실수 3.4를 문자 "3.4"로 바꿔서 ps.txt 파일에 기록
			out.println('A');		// 문자 A를 ps.txt 파일에 기록
			out.println(true);		// 논리값 true를 문자 "true"로 바꿔서 ps.txt 파일에 기록
			out.println("Hello");	// 문자열 Hello를 파일 문자 단위로 ps.txt파일에 기록
			
			// --------------------------------------------------------------
			// [디스크 내용 모델] 5번의 println 이 끝난 ps.txt (메모장으로 열면)
			//
			//   1행 : 10
			//   2행 : 3.4
			//   3행 : A
			//   4행 : true
			//   5행 : Hello
			//
			//   int, double, char, boolean, String 이 전부 "문자" 로 변환되어
			//   행마다 줄바꿈과 함께 저장되었다 (println 의 자동 줄바꿈)
			// --------------------------------------------------------------
			
			// =====================================
			// 3. 스트림 통로 닫기(중요)
			//
			// close() 메소드를 호출하면
			//	- 남아 있는 데이터가 파일로 완전히 내보내어 져서 출력(기록) 되고
			//		파일과의 연결이 종료 된다.
			//
			// close() 메소드를 호출하지 않으면
			//	- 파일에 데이터가 안 써지거나
			//		일부 데이터만 저장될 수 있다.
			// =====================================
			out.close();
			
		} catch ( FileNotFoundException e ) {
			// 파일을 생성할 수 없거나
			// 파일이 저장된 경로가 잘못된 경우 발생하는 FileNotFoundException 예외 메세지 및 처리
			e.printStackTrace();
		}
	}

}
