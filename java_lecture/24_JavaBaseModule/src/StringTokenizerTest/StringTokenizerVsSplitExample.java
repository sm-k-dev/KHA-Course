package StringTokenizerTest;


// java.util 패키지에 만들어져 있는 StringTokenizer 클래스를 현재 파일에서 불러와 사용하기 위해 import 구문 작성
import java.util.StringTokenizer;

public class StringTokenizerVsSplitExample {

	public static void main(String[] args) {

		//-----------------------------------------
		//[1] 잘라낼 전체 원본 문자열 
		//---------------------------------------
		//실무 상황 예 : 사용자 주소, 이름, 데이터 입력시 여러기호가 섞여 들어왔을 때
		//            "보기엔 한 줄이지만 사실 내부적으로 '정리가 필요함'"
		String data = "홍길동/이수홍,박연수-김재배|최영훈";
		
		//-----------------------------------------------
		//[2] StringTokenizer클래스 방식
		//------------------------------------------------
		System.out.println("================= 1) StringTokenizer 클래스 사용 =================");
        /*
         * ================================================
         * 📌 StringTokenizer 문법 + 역할 + 작성 규칙 정리
         * ================================================
         *
         * ▶ 클래스 불러오기(문법)
         * import java.util.StringTokenizer;
         *
         * ▶ 객체 생성 문법 (기본 형태)
         *   StringTokenizer 변수명 = new StringTokenizer(잘라낼 원본 전체 문자열, 구분자);
         *
         *
         * ================================================
         * 📌 문법 구성
         * StringTokenizer st = new StringTokenizer(data, "/,-|");
         *
         * | 구분 			 | 의미 
         * |-----------------|----------------------------
         * | StringTokenizer | 사용할 클래스(문자열 자르는 도구) 
         * | st              | 변수 이름(우리가 부를 이름) 
         * | new             | 메모리에 새 객체 생성 키워드 
         * | data            | 잘라낼 원본 문자열 변수 
         * | "/,-|"          | '구분자(Delimiter)' → 기준 문자들 
         *
         * "/,-|" 의미:
         *  ▶ "/" 또는 "," 또는 "-" 또는 "|"  구분자 기호가 등장하면 자르기
         *
         * ※ 단일 문자가 아닌 문자열도 가능하지만 보통 '문자 단위' 기준이 많음
         *
         * ================================================
         * 📌 왜 이걸 쓰는가?
         *  - 사용자가 입력한 데이터에 여러 기호가 뒤섞여 있을 때
         *  - 한 번에 “규칙적으로” 분리해서 꺼내오기 좋음
         *
         * 예) "홍길동/이수홍,박연수-김재배|최영훈"
         *     → / , - | 기준으로 분리
         *
         * ================================================
 */		
						  //"홍길동/이수홍,박연수-김재배|최영훈", 전체문자열에서 가를 기준이 되는 구분자 문자열 
		StringTokenizer  st  = new StringTokenizer(data, "/,-|");
		
						  //st.countTokens() -> "현재 몇개의 문자열로 나눠지는지 숫자로 반환"
						  //                    "분리될 문자열의 총 갯수를 숫자로 반환"
		int totalCount	 =  st.countTokens();  
		System.out.println("분리될 문자열 총 갯수 : " + totalCount); // 5
		
		System.out.println("------------------------------------");
		
		//st.hasMoreTokens()
		//-> StringTokenizer 객체 메모리에 저장된 전체 원본 문자열에서 분리하여 잘라낼 문자열이 남아 있는지 물어보는메소드로
		//   자를 문자열이 남아 있으면 true 반환 하고, 없으면 false 반환 하는 메소드
		while(  st.hasMoreTokens()    ) {
			 //"홍길동/이수홍,박연수-김재배|최영훈"   <-      /,-| 구분자 기호 하나하나를 기준으로 잘라냄 
			
			//st.nextToken()
			//-> 전체 원본 문자열에서 구분자 기호로 구분해 차례대로 문자열을 잘라서 한번 반환
			String name = st.nextToken(); //"홍길동"
										  //"이수홍"
										  //"박연수"
										  //"김재배"
										  //"최영훈"
			
			//잘라낸 문자열 출력
			System.out.println("전체 문자열에서 구분자기호를 중심으로 잘라낸 문자열 : " + name);
			
		}//while
		
		//-------------------------------------------------
		//[3] String 클래스의  split() 메소드 사용 방식
		//-------------------------------------------------
		System.out.println("=================== 2) String클래스의 split() 메소드 사용 ==========");
        /*
         * split() 특징 정리:
         * ----------------------------------------------------------------
         * 1. 괄호 안에 "정규표현식(Regex)" 필요
         *    - 프로그래밍에서 패턴을 의미하는 표현식
         *    - 초보자가 당황하는 지점: 기호들이 가진 "특별한 의미"
         *
         * 2. | (파이프) 기호는 "또는"의 의미를 가짐
         *    -> 그래서 "\"(역슬래시)로 '일반 문자'로 인식시키기
         *       즉, \\| 로 써야 함
         *
         * 3. "/|,|-|\\|" 이라는 의미
         *    /  또는
         *    ,  또는
         *    -  또는
         *    |  이 나오면 분리
         *
         * 4. 결과는 배열(String[])로 나옴
         *    -> 배열이란? 칸 안에 순서대로 값이 들어간 상자 묶음
         *       예: [0]=홍길동, [1]=이수홍, [2]=박연수 ...
         */	
		
		 //잘라낼 전체 원본 문자열
		 //  String data = "홍길동/이수홍,박연수-김재배|최영훈";
				 // /구분자기호 또는
				 // ,구분자기호 또는
				 // -구분자기호 또는
				 // \구분자기호 또는
				 // |구분자기호   로 분리함		
		String[] names = data.split("/|,|-|\\|");   // 전체 문자열에서 문자열을 모두 잘라서 배열에 담고 배열자체를 반환
								   					//반환-> {"홍길동","이수홍","박연수","김재배","최영훈"} 새로 생성된 배열 
		for(int i=0;  i<names.length;  i++) {
			System.out.println("split() 결과 [" + i + "] : " + names[i]);
		}
		
		System.out.println("\n");
	  	
        // -----------------------------------------------------------------------------------------
        // [4] 종합 결론: 상황에 따라 선택
        // -----------------------------------------------------------------------------------------
        System.out.println("===== 📌 최종 비교 결론 =====");
        System.out.println("✔ 단순하게 / 하나만 자르고 싶다 → StringTokenizer가 간단함");
        System.out.println("✔ 기호가 여러 개, 규칙 다양 → split() + 정규표현식이 유리");
        System.out.println("✔ 실무에서는 데이터 형태에 따라 둘 다 사용됨");
        System.out.println("※ 핵심: 도구 선택 능력 = 개발자의 실력"); 	
		
	}

}





