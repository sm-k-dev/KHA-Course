package WrapperClass;
/*
[수동박싱이란?]
- 박싱(Boxing): 기본자료형 값(int의 10 같은 값)을 포장(래퍼)클래스 객체에 담는 것.
- 수동박싱: 그 담는 작업을 개발자가 코드로 직접 하는 것.

[수동박싱 방법 2가지]
 방법1. new 연산자로 객체를 직접 생성하는 방법            예) new Integer(10);
 방법2. 래퍼클래스가 제공하는 static 메소드를 사용하는 방법  예) Integer.valueOf(10);

이 예제의 목표: ================= 두 수동박싱 방법이 "메모리를 어떻게 다르게 쓰는지" 차이점을 확인한다. =============
*/
public class Ex4 {
	public static void main(String[] args) {
//========================================================================================
// 박싱(수동박싱) 방법1. new 연산자로 객체를 생성해서 기본자료형 값 10을 저장하는 방법
//========================================================================================
		
//		Integer  iValue1 = new Integer(10);
		//위 코드의 의미  : new 가 실행될때 마다  JVM의 heap에  "무조건" 새 Integer 객체를 만든다.
		//그리고 그 객체의 주소를 JVM의 Stack에 있는 참조변수 iValue1에 저장한다.
		/*
		  📍스택(Stack)              📍힙(Heap)
          ┌────────────────┐       ┌──────────────────────┐
          │ iValue1 ───┐   │       │  Integer 객체(10)     │
          └─────────────┘  │       │  ※ 새로 생성됨 (1번째)   │
                           │       └──────────────────────┘
                          └──────────────▶ 이 객체의 주소를 저장
		*/
//       Integer  ivalue2 = new Integer(10);
		//위 코드의 의미 :  저장하려는 값이 똑은 10이어도, new는 또 새 객체를 만든다.
        //결과 :  저장하려는 기본자료형 값 10은 같은데  객체는 2개.  
        //       즉, 같은 값 10이 JVM의 heap에 객체 메모리를 2번 차지 한다.(메모리 낭비)
		/*
		  📍스택(Stack)              📍힙(Heap)
        ┌────────────────┐       ┌──────────────────────┐
        │ iValue2 ───┐   │       │  Integer 객체(10)     │
        └─────────────┘  │       │  ※ 또 새로 생성됨 (2번째) │
                         │       └──────────────────────┘
                        └──────────────▶ 1번째와는 "다른" 객체의 주소를 저장
		*/
		// 참고: new Integer(10) 방식은 이런 낭비 때문에 최신 자바(JDK 9부터)에서
		//      "사용하지 말 것(deprecated)"으로 지정되었다. 그래서 위 두 줄은 주석 처리했다.

//=======================================================================================
//박싱(수동박싱) 방법2. static 메소드 valueOf() 메소드 사용
// -> 핵심 : "이미 같은 값이 저장된 레퍼객체가 있으면, 그 객체를 재활용한다" (이것을 캐싱이라 부른다)
//=======================================================================================
		
		//Integer.valueOf(10); 10이 저장(박싱)된 Integer 객체의 주소를 반환한다.
		//지금은 첫 호출 이므로, JVM의 heap영역에  Integer(10) 객체가 처음으로 1개 만들어진다.
		Integer  iValue1 = Integer.valueOf(10);
	    /*
        [메모리 상태]
        🔹 첫 호출 → 힙(Heap)에 Integer(10) 객체 1개 생성
        🔹 iValue1 은 스택(Stack)에 만들어지고, 그 객체의 주소를 저장한다

             📍스택(Stack)              📍힙(Heap)
          ┌────────────────┐       ┌──────────────────────┐
          │ iValue1 ───┐   │       │  Integer 객체(10)     │
          └─────────────┘  │       │  ※ 최초 생성됨          │
                           │       └──────────────────────┘
                          └──────────────▶ (주소 저장)
	     */
		//다시 valueOf(10); 호출 : 값이 같은 10이므로 새 객체를 만들지 않는다.
		//아까 만들어 둔  Integer(10) 객체의 주소만 그대로 반환합니다.
		Integer  iValue2 = Integer.valueOf(10);
        /*
        [메모리 상태]
        🔹 valueOf(10)의 동작: "이미 10이 저장된 래퍼객체가 있는지 먼저 확인 → 있으면 재사용"
        🔹 그래서 iValue2도 iValue1과 똑같은 객체 주소를 저장한다 → 객체 추가 생성 없음

             📍스택(Stack)               📍힙(Heap)
          ┌──────────────────┐      ┌────────────────────────┐
          │ iValue1 ───┐     │      │ Integer 객체(10)         │
          │ iValue2 ───┼─┐   │      │ (이미 만들어진 것 재사용)     │
          └────────────│ │      	└────────────────────────┘
                       │ │
                        └─┴────────▶ 두 참조변수가 같은 객체 하나를 함께 참조
        */	
		// --------------------------------------------------------------------------------
		// 📌 확인: 두 참조변수(iValue1, iValue2)가 같은 객체(같은 주소)를 참조하는가?
		//    - 참조변수끼리의 == 비교는 "값"이 아니라 "저장된 주소"를 비교한다.
		//    - 주소가 같으면 true → 하나의 객체를 둘이 함께 쓰고 있다는 뜻이다.
		// --------------------------------------------------------------------------------
		if(iValue1 == iValue2) {
			// valueOf() 로 박싱했으므로 Integer 객체 주소가 같다 -> 이문장이 출력된다.
			System.out.println("iValue1참조변수와 iValue2참조변수는 각각 동일한 하나의  래퍼 Integer객체 메모리 사용");
		}else {
			//new로 박생했다면 Integer 객체 주소가 각각 달라서 이쪾이 출력되었을 것이다.
			System.out.println("iValue1참조변수와  iValue2참조변수는 각각 생성된 다른 래퍼 Integer 객체 메모리 사용");
		}
/*
 퀴즈. new 연산자로 객체를 생성해서 박싱하는 방법과
      static 메소드(valueOf)로 래퍼객체를 얻어 박싱하는 방법 중
      어떤 방법이 더 효율적인가? 그 이유도 작성하시오.
      
 [이유]
 1. new 연산자 방식: 값이 같아도 호출할 때마다 매번 새로운 객체 메모리가 만들어진다.
 2. valueOf() 방식: 저장하려는 기본자료형 값이 같으면, 처음 한 번 만들어진
    래퍼객체 메모리를 계속 재활용(캐싱)한다.
 → 같은 값을 여러 번 박싱할수록 valueOf()는 객체를 1개만 쓰고,
   new는 개수만큼 계속 만들어지므로, valueOf()가 메모리를 절약한다.      		
 */     		
        // --------------------------------------------------------
        // 📌 결론 (valueOf가 더 효율적인 이유 한 줄 요약)
        // --------------------------------------------------------
        /*
            🔸 new Integer(10)  → 매번 새로운 객체 생성 (메모리 낭비)
            🔸 valueOf(10)      → 이미 있는 객체 재사용 (캐싱) → 메모리 절약
        */		
		

	}

}





