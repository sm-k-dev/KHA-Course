package WrapperClass;

/*
=====================================================================================
📌 HealthInfoEntity (DB에 저장되는 정보 구조)
- DB 테이블의 한 줄(Row)라고 보면 됨
- 사용자가 입력한 값이 실제 DB 컬럼에 들어가기 전에 이 HealthInfoEntity클래스의 객체에 담김
=====================================================================================
*/
class HealthInfoEntity{  // <- DTO 역할을 하는 클래스 
	
	//-------------------------------------------
	//실제 DB에 컬럼에 저장될 값의 변수들
	//------------------------------------------
	Integer age;     //사용자의 나이 (문자열 -> 숫자로 변환된 최종값 저장)
	Integer height;  //사용자의 키  (cm 단위,  숫자로 변환된 최종값 저장)
	Integer weight;  //사용자의 몸무게 (kg단위, 숫자로 변환된 최종값 저장)
	Double  bmi;     //BMI 계산 결과 (키와 몸무게가 정상일때 계산됨)
	
	//--------------------------------------------------
	//생성자 - 객체를 생성할때 필요한 값들을 한번에 저장(초기화) 가능
	//        new HealthInfoEntity(값들,......) 형태로 사용됨
	//----------------------------------------------------
	public HealthInfoEntity(Integer age, Integer height, Integer weight, Double bmi) {
		super();
		this.age = age;
		this.height = height;
		this.weight = weight;
		this.bmi = bmi;
	}
	//------------------------------------------------------------
	// DB에 저장되어 있다고 가정하고, 데이터를 확인 출력
	//-------------------------------------------------------------
	public void printData() {
		System.out.println("======= DB 저장 데이터 확인 =======");
		System.out.println("나이(age) : " + this.age);
		System.out.println("키(height) : " + this.height);
		System.out.println("몸무게(weight) : " + this.weight);
		System.out.println("BMI지수(bmi) : " + this.bmi);
	}
}

/*
=============================================================================
HealthInfoService (DB 저장 흐름 담당)
- Controller(웹 요청) -> Service(처리) -> Repository(DB) 구조 중  Service 역할
- 여기서는 가짜로 DB에 저장한다고 "시물레이션"만 함 (실무에 가까운 구조 훈련)
===========================================================================
*/
class HealthInfoService{
	
	//---------------------------------------------------------------
	// isNumeric 메소드
	// - 매개변수로 전달 받은 문자열(text)이 "숫자로만 이루어져 있는지" 확인하는 기능
	//-  문자, 한글, 기호, 공백, 단위(km, cm)가 섞이면 숫자가 아니라고 판단
	//-  입력한 검증(유효성 검사) 단계에서 매우 자주 사용됨
	//-----------------------------------------------------------------
	public static boolean isNumeric(String text) {  //<--- "75kg"
		
		//-------------------------------------------------------------------------------------
		//1) 가장 기본적으로 사용자가 아무것도 입력 안했을 경우, 스페이스바(공백)만 입력 했을 경우    오류/예외 처리 
		//-----------------------------------------------------------------------------------
		if(text == null  ||  text.trim().equals("")) {
			return false;
			//text == null   ->   입력 자체가 안됬음
			//text.trim().equals("") ->   "  "같은 공백 제거 후  빈 문자열이면? 숫자가 아님 
		}
		//--------------------------------------------------------------------------------
		//2) 문자열 내부가 전부 숫자로 구성되어 있는지 한 글자씩 검사
		//   예) 사용자가 입력한 데이터 전체 문자열아???  "123" 이면?  String text 매개변수로 전달 받을 것이다.
		//		"123" 을  -> ['1','2','3']
		//		"75KG"을  -> ['7','5','K','G']
		//-----------------------------------------------------------------------------------
		
		//			   :  ['7','5','K','G']
		for(char  c    :  text.trim().toCharArray() ) {
			
			//Character.isDigit(검사할문자)
			//-> 검사할문자가 '0~9' 사이의 숫자인지 체크하는 메소드 
			if(!Character.isDigit(c)) {
				return false;  //숫자로 구성된 문자가 아님이 발견된 즉시 false 반환
							   //예) "25a" 입력받을 경우  -> 'a'문자 검사하면  fasle 반환
							   //예) "75KG" 입력받을 경우 -> 'K' 문자 검사하면 false 반환 
			} //if
		} //for
		
		//3) 숫자로만 구성된 문자열을 입력 받았을 경우 예) "100",  "25",  "003" 입력 받았을 경우 
		return true;
		
	}// <----  isNumeric 메소드 중괄호 닫기 
	
	// ------------------------------------------------------------------------------
	// 📌 toInteger : 문자열(String)을 → 정수(Integer) 타입으로 변환하는 메소드
	// ------------------------------------------------------------------------------
	// 🎯 목적
	// - 웹/앱에서 입력된 값은 항상 문자열(String) 형태로 들어온다.
	// - "100", "25", "3000" 같은 숫자 문자열을 실제 숫자로 바꿔야 계산이 가능하다.
	// - 하지만 사용자가 "20kg", "??", 공백, null 등을 입력할 수도 있으므로
	//   변환 실패 시 오류를 발생시키지 않고 → null로 돌려 안전하게 처리한다.
	// - 이 null은 DB 저장이나 서비스 로직에서 "값이 없음"을 표현할 때 유용하다.
	// ------------------------------------------------------------------------------	
	public static Integer  toInteger(String text) {  //<---- "75kg"
		
		//1) 먼저 매개변수 String text 로 전달 받은 입력받은 문자열이 숫자로 구성되어 있는 문자열인지 검사
		if( isNumeric(text) ) {
			//isNumeric(text)  == true 인 경우에만 다음 코드 진행
			
			//2) 실제 문자열을 숫자로 변환
			// - Integer.parseInt("100");  ->  100 정수로 변환해서 반환
			return Integer.parseInt(text.trim());
		}
		//3) 숫자형태로 구성된 문자열이 아니라면? null 반환
		//	 - 즉 "25kg", "한글", null, ""으로 입력 받았을 경우 
		//   - 오류 (Exception)을 내지 않고 null을 반환 하는 이유
		//		1. DB에 테이블에 값이 비어 있어야 하는 경우 (NULL 저장)
		//      2. 계산할 수 없는 데이터는 제외/무시 하도록 처리 
		//		3. 자바프로그램이 멈추지 않게 안전하게 진행 
		return null;
		//아래와 같은 상황에서 null이 들어갈 수 있음
		// age : "스무살" 입력했을 경우   -> null
		// height : "180cm" 입력했을 경우 -> null
		// weight : "" 입력했을 경우 -> null
		//DB의 테이블에 저장시 "값 없음"으로 처리 됨 (유효성 검증 단계에서 매우 중요)
		
	}// <--- toInteger 메소드 중괄호 닫기 
	
	// ------------------------------------------------------------------------------
	// 📌 calculateBMI : BMI(신체질량지수)를 계산하는 기능
	// ------------------------------------------------------------------------------
	// 🎯 목적 요약
	// - 사용자가 입력한 키(height)와 몸무게(weight)를 이용해 BMI를 계산한다.
	// - BMI 공식 :        BMI = 몸무게(kg) / (키(m) × 키(m))
	// - 단, 입력이 잘못되면 절대 오류가 발생하지 않도록 "null" 처리로 보호한다.
	// - 이 함수는 "실패하지 않는 안전한 계산 메소드"라고 보면 된다.
	// ------------------------------------------------------------------------------
	public static Double calculateBMI(Integer height,  Integer weight) {
		
		//1) 사용자가 키와 몸무게를 입력하지 않았을 경우 검사
		if(height == null  ||  weight == null) {
			return null;  //BMI 계산 불가능 -> 계산을 강제로 시도면 오류가 나기 떄문에 차단해~ null  반환 
		}
		
		//2) ---------------------------------------------------------
		//   BMI 공식에서 키는 "cm"아니라 "미터(m)" 단위가 필요함
		//    - height가 180이라면 -> 180cm -> 1.80m 로 변환
		//    - 그래서 100.0으로 나눠 소수점 계산이 되도록 double 사용
		//-------------------------------------------------------------
		double meter = height / 100.0;
		//			    170   / 100.0  = 1.70
		//              180   / 100.0  = 1.80
		
		//-----------------------------------------------------------
		//3) 비정상적인 입력값 방지 조건
		//   - meter <= 0 : 0m 또는 음수 단위는 존재할 수없음
		//   - weight <= 0 : 몸무게가 0 또는 음수일수  없음
		//   - 이런값이 들어 왔다면 계산 자체가 의미가 없으므로 null 반환
		//---------------------------------------------------------
		if(meter <= 0  ||  weight <= 0) {
			return null; //유효하지 않은 데이터 -> BMI 계산 중단을 위해 null 반환 
		}
		
		//-----------------------------------------------------------
		//4) 정상 입력일 때만 BMI 계산 실시
		//    공식 )  BMI = 몸무게(kg)  /  (키(m) X 키(m))
		//----------------------------------------------------------
		return weight / (meter * meter);
		//예시) weight = 70kg  ,  height = 1.75m 일경우!
		//BMI = 70   /  (1.75  X 1.75);
		//    = 22.86 정상범위 
		
	}// <==== calculateBMI 메소드 중괄호 닫기 
	
	// ------------------------------------------------------------------------------
	//createHealthInfo 메소드 정의 
	//		    ─────────────────────────────────────────────────────────────
	//		    이 메소드는 웹/앱에서 사용자가 입력한 문자열 데이터를 받아서
	//		    1) 입력값 정리(trim, null 처리)
	//		    2) 숫자로 변환(String → Integer)
	//		    3) BMI 계산
	//		    4) DB에 저장될 DTO역할을 하는 (객체) 생성
	//		    5) "DB 저장 완료"라고 가정하고 출력(실무의 insert 역할)
	//		    ─────────────────────────────────────────────────────────────
	//		    → 컨트롤러(Controller)가 가장 먼저 호출하고
	//		      → 서비스(Service)가 처리하고
	//		          → DB(Entity/Repository)에 기록되는 구조의 핵심 흐름 연습 예제
	// ------------------------------------------------------------------------------		
			  //DTO역할을 하는 객체 반환
	public static HealthInfoEntity  createHealthInfo(String ageInput,
													 String heightInput, 
													 String weightInput) {
		//-----------------------------------------------------------
		//1) 입력값 전처리 ( trim + null 체크 )
		//   사용자가 입력한 값이 비어 있거나(null), 공백이 포함될수 있기때문에
		//   null이면 그대로 null, 입력한 값이 있으면 앞뒤 공백 제거(trim())
		//-----------------------------------------------------------
		ageInput    =  (ageInput == null)    ? null : ageInput.trim(); 		//"  27  " -> "27"
		heightInput =  (heightInput == null) ? null : heightInput.trim();	//"180 "   -> "180"
		weightInput =  (weightInput == null) ? null : weightInput.trim();   //"75kg"   -> "75kg"
			
		//-----------------------------------------------------------
		//2) 입력한 문자열 값을 안전하게 숫자로 변환
		//   - "25"   -> 25  ,  "175" -> 175
		//   - "70kg", "abc" , null -> 변환실패 -> null 반환
		//	  -> null 을 반환 하는 이유  : DB에 서 "아예 값이 없다(null)"로 표현 하기 위함
		//------------------------------------------------------------------------
		Integer age = toInteger(ageInput); 			//입력받은 나이 : 문자열 에서 정수 변환 시도 
		Integer height = toInteger(heightInput); 	//입력받은 키 : "180" -> 180 정수로 변환 시도 
		Integer weight = toInteger(weightInput);    //입력받은 몸무게 : "75kg" -> 정수로 변환 불가 -> null 반환 받아 저장
													//입력받은 뭄무게 : "75"   -> 75 정수로 변환 시도 
		
		//--------------------------------------------------------------------
		//3) BMI 계산
		//   - height, weight가 정상적으로 입력 되었을때만 BMI 계산
		//   - 하나라도 입력되어 있지 않다면(null 이면) -> BMI도 null(계산 불가 의미)
		//----------------------------------------------------------------------
		Double bmi = calculateBMI(height, weight);
				
		//----------------------------------------------------------------------------
		//4) DTO 역할을 하는 HealthInfoEntity 클래스의 객체를 생성해서  DB의 테이블에 한줄 추가
		//  - 최종적으로 DB의 테이블에 저장된 구조를 하나의 객체를 생성해서 만든다.
		//  - 만든 하나의 DTO역할을 하는 HealthInfoEntity 객체를 DB의 테이블에 추가(insert) 했다고 가정하고 그정보 출력
		//--------------------------------------------------------------------------------
		HealthInfoEntity dto = new HealthInfoEntity(age, height, weight, bmi); //<- DB의 테이블에 저장된 하나의 레코드정보
		
		//----------------------------------------------------------------------------------
		//5) DB의 테이블에 하나의 레코드 형태로 바로 4)에서 생성한 객체의 정보가 저장됬다고 가정하고 
		//	여기 이자리에 정보들을 얻어서 출력 해보자.
		//-----------------------------------------------------------------------------------
		System.out.println("DB 저장 완료 (가정) -> INSERT INTO 테이블명 VALUES(age, height, weight, bmi);");
		dto.printData(); // 실제 저장된 데이터 확인 용도 ( SELECT * FROM 테이블명  조회 결과를 보는 느낌)
		
	    // --------------------------------------------------------------------------
	    //6) Controller(사장)에 돌려주는 반환 단계
	    //     - 컨트롤러(main메소드)가 다시 웹브라우저 화면(클라이언트가 브라우저로 요청한 화면)으로 응답(출력) 보낼 수 있도록
	    //     - HealthInfoService서비스 클래스가 처리한 결과 DB저장 완료한  HealthInfoEntity객체 정보를 내보낸다
	    // --------------------------------------------------------------------------
		return dto;
		
	} // <===== createHealthInfo 메소드 중괄호 닫기 
	
} // <=========== HealthInfoService 클래스 중괄호 닫기 

