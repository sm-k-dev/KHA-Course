package WrapperClass;

public class Ex5 {

	public static void main(String[] args) {
		/*
		 [자동(오토) 박싱]
		 -> 개발자가 박싱 코드를 직접 작성하지 않아도,
		    컴파일러가 수동박싱 코드( Integer.valueOf(10) )를 자동으로 작성해서 박싱해 주는 기술.

		 [자동(오토) 언박싱]
		 -> 개발자가 언박싱 코드를 직접 작성하지 않아도,
		    컴파일러가 수동언박싱 코드( 참조변수.intValue() )를 자동으로 작성해서 언박싱해 주는 기술.

		 참고1. 자동 박싱과 자동 언박싱은 JDK 5 버전 이상부터 제공되는 기술이다.
		 참고2. "자동"의 의미: 우리가 안 쓴 코드를 컴파일러가 대신 써 준다는 뜻이다.
		        메모리에서 일어나는 일은 수동박싱/수동언박싱과 완전히 동일하다.
		*/
		
		int n1 = 10;   //<- 기본자료형 int 값 10.  Stack 공간에 직접 저장된다.
		
		int n2;        //<- 기본자료형 변수 선언만 함 (아직 값 없음)
		
		Integer num1;  //<- 참조자료형 변수 선언만 함 (아직 객체주소 값 없음)
		
		//박싱(수동박싱)은 이렇게 해야 한다.
		//방법2. Integer 래퍼클래스의 static 메소드 valueOf() 사용
//		num1 = Integer.valueOf(n1); // <- 수동 박싱
		
		//아래 한 줄을 쓰면 자동(오토) 박싱이 일어나 10을  Integer객체의 인스턴스변수에 저장하게 된다.
		num1 = n1;
//			 = 10;
//			 = Integer.valueOf(n1);  // <- 컴파일러가 실제로는 이렇게 자동으로 작성해 준다.
		/*
		 [num1 = n1; 실행 후 메모리 상태 - 자동박싱]

		      📍스택(Stack)              📍힙(Heap)
		   ┌────────────────┐       ┌──────────────────────┐
		   │ n1   =  10     │       │  Integer 객체(10)     │
		   │ num1 ───┐      │       │  ※ 자동박싱으로 생성됨    │
		   └──────────┘     │       └──────────────────────┘
		              │
		               └──────────────▶ 객체의 주소를 저장

		 🔹 n1   : 스택에 값 10이 "직접" 들어있다.        (기본자료형)
		 🔹 num1 : 스택에는 "주소"만 있고, 값 10은 힙의 객체 안에 있다. (참조자료형)
		*/		
		System.out.println("자동(오토) 박싱");
		System.out.println("기본자료형 변수 n1의 값 : " + n1); //10
		//toString() :  Integer 객체 안에 저장된 10을 문자열 "10"으로 만들어 반환한다.
		System.out.println("참조자료형 변수 num1의  Integer레퍼 객체 메모리 내부에 자동으로 박싱된 10 : " + num1.toString());

		// 자동(오토) 박싱
			// 기본자료형 10을 자동(오토) 박싱해서 저장
			Integer  num3 = 10;   // Integer.valueOf(10);
								  // 위와 같이 수동으로 박싱한 것과 같은 의미이다.
			 					  // (선언과 동시에 대입해도 자동박싱은 똑같이 일어난다.)
	    // 자동(오토) 언박싱
			// Integer 객체 메모리 내부에 저장된 기본자료형 10을 자동(오토) 언박싱으로 꺼내서 얻자
			int value = num3;    // num3.intValue();
								 // 위와 같이 수동으로 언박싱한 코드와 같은 의미이다.
			/*
			 [int value = num3; 실행 후 메모리 상태 - 자동언박싱]

			      📍스택(Stack)               📍힙(Heap)
			   ┌──────────────────┐      ┌──────────────────────┐
			   │ num3 ───────────────────▶ Integer 객체(10)     
			   │ value =  10      │      │                      │
			   └──────────────────┘      └──────────────────────┘
			                 ▲
			                 └─ 힙의 객체 안에 있던 10을 "꺼내서(언박싱)"
			                    스택의 기본자료형 변수 value에 값으로 복사 저장

			 🔹 언박싱해도 힙의 객체는 사라지지 않는다. 값을 "복사"해 오는 것이다.
			*/		
			System.out.println("valaue : " + value);  // 10
			
			//---------------------------- 자동(오토) 박싱, 자동(오토) 언박싱 연습 -----------------------
			
			// 정수 10을 Integer 객체 메모리의 인스턴스변수에 저장하기 위해 자동(오토) 박싱하기
			// 참조변수 it 선언 해서 저장
			Integer it = 10;   //<---- 수동박싱 하려면?  Integer.valueOf(10); 을 작성해야 했을 것이다.
			
			// 자동(오토) 박싱된 10을 자동(오토) 언박싱을 통해 얻어 출력!
			System.out.println(it); //10
			// 위 줄을 수동 언박싱으로 작성하면 아래와 같다.
			// System.out.println(it.intValue());
			
			
			// double 자료형의 실수 3.14를 Double 래퍼클래스의 객체 메모리에 저장하기 위해 자동(오토) 박싱하기
			// 참조변수 du 선언 해서 저장
			Double du = 3.14;   //<---- 수동박싱 하려면?  Double.valueOf(3.14); 을 작성해야 했을 것이다.
			
			// 자동(오토) 박싱하여 Double 객체 메모리에 저장된 3.14를 자동(오토) 언박싱해서 얻자
			// double b; 변수 선언 후 저장
			double b = du;		//<---- 수동언박싱 하려면? du.doubleValue(); 을 작성해야 했을 것이다.
			
			System.out.println(b);  //자동 언박싱 후 출력 :  3.14
			
			System.out.println("-----------------------------------------------------------------");
			
			// 주제 : 자동(오토)박싱과 자동(오토)언박싱을 통해서  산술연산( +  -  *  /  등) 해보기 
			
			//10 자동(오토) 박싱
			Integer c1 = 10;   // new Integer(10) 객체 메모리 주소를 참조변수 c1에 저장
			
			//20 자동(오토) 박싱
			Integer c2 = 20;   // new Integer(20) 객체 메모리 주소를 참조변수 c2에 저장
			
			c2 += 3;
		//  c2 = c2 + 3;								<===== += 를 풀어 쓴 형태 
		//  c2 = Integer.valueOf( c2.intValue() + 3 );  <===== 컴파일러가 실제로 작성해주는 코드 형태 
			
		//  순서1. c2.intValue()  -> 자동언박싱이 일어나 객체 안의 20을 꺼내온다.
		//  순서2. 꺼내온 20과 3을 더한다.  20 + 3 = 23
		//  순서3. 23을 다시 참조변수 c2에 저장해야 하는데, c2는 참조자료형이므로
		//         23이 저장된 Integer 객체가 필요하다 -> 자동박싱이 다시 일어난다.
		//  순서4. c2 = (23이 저장된 Integer 객체의 주소);  <- 새 객체의 주소로 교체됨	
			
			System.out.println(c2.intValue()); //수동 언박싱 해서 얻은 23 출력 
			
//10 자동(오토) 박싱
//			Integer c1 = 10;   // new Integer(10) 객체 메모리 주소를 참조변수 c1에 저장	
			
			c1++;
//			c1 = c1 + 1;      <===  ++ 를 풀어쓴 형태 
			
//		순서1.    c1.inValue(); 자동언박싱으로 10을 얻는다.
//		순서2.         10        +    1  을 계산해서  11로 만들어준다.
//		순서3.    c1 =  11;  대입해서 저장하기 위해  Integer.valueOf(11); 자동박싱을 통해 c1 참조변수에 대입해서 저장
//      순서4.    c1 = new Integer(11);    <==== 결과 
			
			
// 현재 c1 참조변수가 사용하고 있는 new Integer(11) 객체의 11과 
// 현재 c2 참조변수가 사용하고 있는 new Integer(23) 객체의 23 을   +  연산 해보자
			
		int addResult = c1 + c2;   // c1,  c2 각각 Integer 객체 내부에 저장된 정수값이
								   // 자동(오토) 언박싱된 후에 + 연산을 하게 된다.
		
//		int addResult = c1.intValue()  +  c2.intValue();
//					  =       11       +      23;
//                    =               34;		
		System.out.println("addResult 변수 값 : " + addResult); //34 
		
		
// 현재 c1 참조변수가 사용하고 있는 new Integer(11) 객체의 11과 
// 현재 c2 참조변수가 사용하고 있는 new Integer(23) 객체의 23 을   -  연산 해보자		
		
		int minResult = c1 - c2;   //c1, c2 각각 Integer 객체 내부에 저장된 정수값이
								   //자동(오토) 언박싱된 후에 - 연산을 하게 된다.
								   //11, 23을 각각 얻은 후   11 - 23 을 하게 되어 결과는 -12가 된다.
		System.out.println("minReulst 변수 값 : " + minResult); //-12
		
// 결론 : 자동으로 발생하는 오토박싱과 오토언박싱 덕분에
//       포장(래퍼) 객체 메모리에 저장된 기본자료형 값을 꺼내거나(언박싱) 저장하는(박싱) 코드를
//       직접 작성하지 않아도, 기본자료형처럼 대입과 산술연산이 가능하다.
//       단, 눈에 안 보일 뿐 내부에서는 언박싱 → 연산 → 박싱 과정이 매번 일어나고 있다.		
		
		
		
	}

}







