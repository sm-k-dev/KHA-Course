package WrapperClass;

public class Ex3 {

	public static void main(String[] args) {
/*		
=============================================================
📌 [기본 개념 정리]

✔ 박싱(Boxing, 수동 박싱)
   - 기본자료형(int, double 같은 값)을
     래퍼(포장) 클래스(Integer, Double 등)의 "래퍼객체" 안에 저장하는 작업
   - 즉, 기본자료형 값 → 객체의 변수에 저장 하는것.
   - 예) int 10 → new Integer(10)

✔ 언박싱(Unboxing, 수동 언박싱)
   - 래퍼 객체 내부에 저장된 기본자료형 값을 다시 꺼내는 작업. 
   - 예) new Integer(10).intValue() → 10
=============================================================		
		
=========================================여기서 부터 실습================================================================	
		
===============  int -> Integer 래퍼(포장) 클래스 이용한 박싱(수동 박싱), 언박싱(수동 언박싱)학습  =======================

=============================================================================	

참고. 박싱(Boxing, 수동 박싱)?
   - 기본자료형(int, double 같은 값)을 래퍼(포장) 클래스(Integer, Double 등)의 "객체" 안에 저장하는 작업
     
📌 [Integer 클래스의  생성자 종류]

1) new Integer(정수값)
   → 숫자를 직접 넣어 객체로 포장(박싱)

2) new Integer("문자열")
   → "20" 같은 문자를 숫자로 해석하여 객체에 저장 (문자 → 숫자)
=============================================================================	
*/		
		
		//기본자료형 정수 데이터 하나 수동 박싱
		Integer num01 = new Integer(10);    //10 수동 박싱
		Integer num02 = new Integer("20");  //문자열 객체 메모리에서 20을 추출해서 Integer객체의 변수에 저장 
		
		
		//래퍼 클래스의 객체 메모리 내부에 저장된 기본자료형값을 꺼내오는 수동 언박싱
		int n01 = num01.intValue(); //수동 언박싱 -> 10
		int n02 = num02.intValue(); //수동 언박싱 -> "20"을 꺼내 올때 정수 20으로 변환후 반환 
		
		int sum = n01 + n02;
		//  30  =  10 +  20;
		
		System.out.println(sum); //30
/*		
=============================================================
		📌 [진법 변환 메소드]

		- Integer.toBinaryString(30)  → 2진수 결과 "11110"
		- Integer.toOctalString(30)   → 8진수 결과 "36"
		- Integer.toHexString(30)     → 16진수 결과 "1e"

		※ 실제 사용 예: 시스템 기초, 메모리, 네트워크, 하드웨어 표현 방식
=============================================================	
*/		
		System.out.println("sum변수값 30을 2진수로 변환 -> " + Integer.toBinaryString(sum)  );
						 //"sum변수값 30을 2진수로 변환 -> " +          "11110"
		
		System.out.println("sum변수값 30을 8진수로 변환 -> " + Integer.toOctalString(sum)  );
						 //"sum변수값 30을 8진수로 변환 -> " +         "36"
		
		System.out.println("sum변수값 30을 16진수로 변환 -> " +  Integer.toHexString(sum) );
		//				 //"sum변수값 30을 16진수로 변환 -> " +       "1e"

/*		
 =============================================================
	모든 래퍼 클래스의 parseXXX 메소드 정리 (문자열 → 기본 자료형 변환)
	
    - 문자열 형태의 숫자 또는 값을 해당 기본자료형 타입으로 변환해주는 메소드들
    - 즉 "글자 형태" → "진짜 계산 가능한 숫자/값"으로 바꾸는 역할

    💡 매개변수로 전달 하는 값은? 문자열 값
    💡 메소드로 반환 받는 자료형의 타입은 기본자료형 타입의 값

 ✔ 정수형 변환
    Integer.parseInt("100")     → 100   (문자열 → 정수)

 ✔ 실수형 변환
    Double.parseDouble("100.0") → 100.0 (문자열 → double 실수)
    Float.parseFloat("100.123") → 100.123 (문자열 → float 실수)

 ✔ 논리형 변환 (true/false)
    Boolean.parseBoolean("true") → true  (문자열 → 논리값)

 📌 왜 필요한가?
    - 사용자 입력, 파일, DB, 서버 요청/응답 데이터는 대부분 "문자열" 형태
    - 프로그램에서 계산, 비교, 저장하려면 숫자나 논리값으로 변환 필수!
 ======================================================================
 */			
		
		//수동박싱 : 기본자료형 데이터를 레퍼클래스의 객체 메모리에 저장
		Integer num03 = new Integer(30);
		
		//수동언박싱 : 위 박싱된 Integer 객체 메모리 내부의 인스턴스변수에 저장된 30을 30.0으로 변환해서 꺼나와 얻는 작업.
		//방법 -> Integer 클래스 내부에 만들어진  double doubleValue() 메소드 사용!
		double result = num03.doubleValue(); //30.0 으로 언박싱됨
		System.out.println(result); //30.0
		
		//중요!--------------------------------------------------------------------------------
		//Integer 클래스 내부에 만들어져 있는 static int parseInt(String s) 메소드 
		//-> 숫자형태의 문자열을 매개변수 String s로 전달하면
		//   숫자형태의 문자열을??????????? 숫자정수로 변환해서 반환 하는 기능의 메소드 
		
		int num = Integer.parseInt("100"); //"100"문자열을   100숫자정수로 변환해서 반환! 받습니다.
		//	100
		
		System.out.println("문자열 '100'을  숫자100으로 변환 후 반환 받자");
		System.out.println(num); //100 <---숫자 
		
		System.out.println(num + 200); //100 + 200
									   //300
		
		//참고.
		// parseXXX메소드들
		//-> 문자열형태의 데이터를 해당 포장(래퍼)클래스의 기본자료형값으로
		//	 변경후 반환하는 메소드들

		//  Double.parseDouble("100.0"); -> 100.0
		
		//  Float.parseFloat("100.123"); -> 100.123
		
		//  Boolean.parseBoolean("true");-> true
		
		//  Integer.parseInt("100"); -> 100			
		
	}

}







