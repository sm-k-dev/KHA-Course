package MathClass;

/*
import 구문
- 다른 사람이 만들어 둔 클래스를 현재 파일에서 사용하기 위해 불러오는 구문.
*/
import java.util.Random;  //Random 클래스  :  난수(랜덤 숫자)를 생성하기 위한 클래스 

import java.util.Arrays;  //Arrays 클래스 : 배열 데이터 정렬, 배열메모리 주소 비교 등 배열 관련 메소드 제공 클래스 

/*
Random 클래스란?
- 난수(랜덤 숫자)를 생성하기 위한 클래스.
- Random클래스는 어떤 공식(알고리즘)으로 어떤 시작값(시드값)을 이용해 랜덤숫자를 발생시킵니다.

참고. 시드값?  난수 계산을 시작하기 위한 "출발 숫자"

    고정된 시드값?  특정한 시드값을 미리 정해 놓고 난수를 생성하는 방식입니다.
    			이렇게 하면 항상 동일한 난수 패턴을 얻을수 있습니다.
    			
- new Random(시드값);
 new Random(시드값);
 -> 항상 두 Randmo객체는 시드값이 같으므로 같은 난수를 발생시킵니다.
 
 new Random();
 -> 컴퓨터 현재 시간을 이용해 랜덤으로 난수를 발생시킵니다.
			

*/
public class RandomTest {

	public static void main(String[] args) {
	// 프로그램의 전체 동작 흐름 
		
		//사람이 로또를 할 때의 생각 순서:
		//1. 로또 번호 6개를 뽑는다.
		//2. 당첨 번호 6개를 확인한다.
		//3. 두 번호를 비교한다.
		//4. 당첨인지 아닌지 확인한다.
		
		//컴퓨터는 이걸 이렇게 처리한다:
		/*
		┌─────────────────────────────────────────────┐
		│  Random으로 숫자 생성                           │
		│        ↓                                    │
		│  배열에 숫자 6개 저장                            │
		│        ↓                                    │
		│  또 다른 배열에 당첨 번호 저장                      │
		│        ↓                                    │
		│  두 배열을 정렬                                 │
		│        ↓                                    │
		│  Arrays.equals()로 비교                       │
		│        ↓                                    │
		│  true / false 결과 출력                        │
		└─────────────────────────────────────────────┘
		*/
		
		//--------------------------------------
		//1.  선택한 로또 번호를 저장할 배열 메모리 생성
		//--------------------------------------
		int[] selectNumber = new int[6];  //{0, 0, 0, 0, 0, 0}
		//숫자 6개를 저장할 6칸의 배열 생성
		
		//----------------------------------------------------
		//2. 랜덤 숫자를 만들어주는 Random 클래스의 객체 생성해서 준비
		//---------------------------------------------------
		//Random random = new Random(시드값);
		  Random random = new Random(3);
		 //랜덤 숫자를 만들어주는 Random객체(로또 기계) 하나 만든다.
		 //시드값 3으로 저장해서 만든다
		 //항상 같은 순서의 랜덤 숫자를 만들어 낸다.
		  
	    //------------------------------------------------
		//3. 화면에 "선택한 번호" 라는 안내 문구 출력
		//-----------------------------------------------
		System.out.println("선택한 번호:");
		
		//----------------------------------------------
		//4. 로또 번호를 6개를 하나씩 랜덤으로 생성해서 배열에 저장
		//  요약 : 로또 번호 6개 랜덤으로 추출
		//---------------------------------------------
		for(int i=0;  i<6;  i++) {
			
			//int[] selectNumber = new int[6];  //{0, 0, 0, 0, 0, 0}
			//									   0  1  2  3  4  5  index
			
			//1 ~ 45 사의 로또 번호 하나를 랜덤한 숫자로 얻어내서
			//위 selectNumber 배열의 각 칸에 순서대로 반복해서 저장
			//===>   랜덤 계산 공식 = random.nextInt(최댓값) + 최솟값;
			
			selectNumber[i] = random.nextInt(45) + 1;
			/*
								random.nextInt(45);
								-> 0이상 44이하 숫자 중 하나 생성
								
								random.nextInt(45) + 1 
							    -> 1이상 45이하 숫자 중 랜덤 숫자 하나 생성해서 반환 
			 */
			System.out.println(selectNumber[i]);
				
		}
		
		System.out.println(); //선택 번호 출력이 끝났으므로 줄을 한칸 띄우자.
		
		//-------------------------------------------------
		//5. 당첨 번호를 저장할 또 다른 배열 메모리 생성
		//--------------------------------------------------
		int[] winningNumber = new int[6];  //{0, 0, 0, 0, 0, 0}
		
		//--------------------------------------------------
		//6. 랜덤 기계 ( new Random(3); 객체 ) 준비
		//--------------------------------------------------
		random = new Random(3);
		//시드값을 이전과 똑같이 3으로 설정함
		//그래서 이전과 완전히 같은 로또 숫자 순서가 다시 랜덤으로 생성됩니다.
		
		//----------------------------------------------------
		//7. 화면에 "당첨번호" 안내 문구 출력
		//----------------------------------------------------
		System.out.println("당첨번호 : ");
		
		//-------------------------------------------------------------------
		//8. 당첨 번호를 반복해서 6개 생성해서 winningNumber 배열의 각 칸에 순서대로 저장
		//------------------------------------------------------------------
		for(int i=0;  i<6;  i++) {
			
			winningNumber[i] = random.nextInt(45) + 1;
			// 1 ~  45 사이의 당첨 번호를 랜덤 숫자로 하나씩 얻어 배열에 각칸에 순서대로 저장
			
			System.out.println(winningNumber[i] + "");
		}
		
		//--------------------------------------------------------------
		//9. 두 배열의 로또번호들을 비교하기 전에 정렬
		//-------------------------------------------------------------
		Arrays.sort(selectNumber);
		//{15, 16, 17, 21, 28, 34 } <- 선택번호들이 작은숫자가 먼저 큰숫자가 그다음에 저장되는 순으로 오름차순정렬
		
		Arrays.sort(winningNumber);
		//{15, 16, 17, 21, 28, 34 } <- 당첨번호들이 작은숫자가 먼저 큰숫자가 그다음에 저장되는 순으로 오름차순정렬
		 
		//-------------------------------------------------------------
		//10. 두 배열에 순서대로 저장된  로또 번호가 같은지 비교 (당첨 여부 확인)
		//-------------------------------------------------------------
		boolean result = Arrays.equals(selectNumber, winningNumber);
		//두 배열의 각칸에 저장된 숫자들을 차례대로 같은지 비교해서 모두 같으면? equals 메소드는 true 반환 하고 틀리면 false 를 반환
		
		//------------------------------------------------------------
		//11. 로또 당첨 여부 결과 출력
		//---------------------------------------------------------
		System.out.println("당첨 여부 : ");
		
		if(result) {
			System.out.println("1등에 당첨되었습니다.");
		}else {
			//선택한 로또번호가 당첨번호와 하나라도 다르면?
			System.out.println("당첨되지 않았습니다.");
		}
		

	}

}

