package ObjectTest1;
/* ============================================================================
 *  주제 : DTO 역할을 하는 클래스 만들기
 * ----------------------------------------------------------------------------
 *  [1] DTO(Data Transfer Object) 란?
 *
 *      여러 개의 데이터를 하나로 묶어서 저장하고 전달하는 용도로만 사용하는
 *      클래스를 말한다.
 *
 *      예를 들어 회원 한 사람의 정보는 아이디, 이름, 나이 세 가지다.
 *      이 세 값을 따로따로 들고 다니면 관리하기 어렵고, 메소드에 넘길 때도
 *      매개변수를 세 개씩 써야 한다.
 *      Member 라는 클래스로 묶어 두면 Member 객체 하나만 주고받으면 된다.
 *
 *      DTO 클래스에는 보통 다음 다섯 가지가 들어간다.
 *          (1) 필드 (데이터를 저장할 변수)
 *          (2) 생성자 (필드값을 초기화)
 *          (3) getter 메소드 (필드값을 읽어 가는 통로)
 *          (4) equals, hashCode (값이 같은 객체인지 판단)
 *          (5) toString (객체가 가진 값을 문자열로 확인)
 *
 *  [2] 이 클래스에서 사용한 두 가지 키워드
 *
 *      private : 이 클래스 밖에서는 직접 접근할 수 없다는 표시다.
 *                다른 클래스에서 member.id 라고 쓰면 컴파일 오류가 발생한다.
 *                값을 읽으려면 아래에 만들어 둔 getter 메소드를 사용해야 한다.
 *
 *      final   : 값을 한 번만 대입할 수 있다는 표시다.
 *                여기서는 생성자에서 한 번 대입하고, 그 뒤로는 바꿀 수 없다.
 *                객체를 만든 뒤에 값이 바뀌지 않는 것이 확실해지므로,
 *                여러 곳에서 같은 객체를 함께 사용해도 안전하다.
 *                필드에 final 을 붙이면 setter 메소드는 만들 수 없다.
 * ========================================================================== */
public class Member2 {  //<- 가입할 회원 한사람의 정보 
	
    // ------------------------------------------------------------------
    // 1. 필드 선언
    //    private 이므로 외부에서 직접 접근 불가, final 이므로 값 변경 불가.
    //    이런 필드는 생성자에서 반드시 초기화해야 한다.
    //    초기화하지 않으면 컴파일 오류가 발생한다.
    //    -> variable id might not have been initialized
    // ------------------------------------------------------------------					
	private final String id;  //회원 아이디
	private final String name; //회원 이름
	private final int age;     //회원 나이
	
    // ------------------------------------------------------------------
    // 2. 생성자
    //    객체를 만들 때 아이디, 이름, 나이를 전달받아 필드를 초기화한다.
    //    this.id 는 이 객체의 필드, id 는 매개변수를 가리킨다.
    //    이름이 같기 때문에 필드 쪽에 this. 를 반드시 붙여야 한다.
    // ------------------------------------------------------------------
	public Member2(String id, String name, int age) {
		super();
		this.id = id;
		this.name = name;
		this.age = age;
	}	
    // ------------------------------------------------------------------
    // 3. getter 메소드
    //    private 필드의 값을 외부에서 읽을 수 있게 해 주는 메소드다.
    //    이름 규칙 : get + 필드명(첫 글자 대문자).  예) id -> getId
    //    필드가 final 이므로 값을 바꾸는 setter 메소드는 만들지 않는다.
    // ------------------------------------------------------------------
	public String getId() {
		return id;
	}

	public String getName() {
		return name;
	}

	public int getAge() {
		return age;
	}
	
	 /* ------------------------------------------------------------------
     * 4. hashCode 와 equals 재정의
     * ------------------------------------------------------------------
     * Object 가 원래 가지고 있는 equals 는 객체의 주소값만 비교한다.
     * 그래서 필드값이 모두 같아도 new 로 따로 만든 객체라면 false 가 나온다.
     *
     * DTO 는 "값이 같으면 같은 것으로 본다"는 판단이 필요한 경우가 많으므로
     * equals 와 hashCode 를 함께 재정의한다.
     * 두 메소드를 반드시 함께 재정의해야 하는 이유는,
     * HashMap 이나 HashSet 이 값을 찾을 때 hashCode 로 위치를 정한 뒤
     * 그 위치에서 equals 로 최종 확인하는 순서로 동작하기 때문이다.
     *
     * 아래 두 메소드는 현재 내용이 채워져 있지 않은 상태다.
     * 그 결과 다음과 같이 동작한다.
     *     hashCode() -> 어떤 객체든 항상 0 을 반환한다.
     *     equals()   -> 어떤 객체와 비교해도 항상 false 를 반환한다.
     *                   자기 자신과 비교해도 false 가 된다.
     * 실제 프로그램에서는 이 상태로 두면 안 된다.
     *
     * 올바르게 구현하면 아래와 같다. (java.util.Objects 클래스 사용)
     *
     *     @Override
     *     public int hashCode() {
     *         return java.util.Objects.hash(id, name, age);
     *     }
     *
     *     @Override
     *     public boolean equals(Object obj) {
     *         if (this == obj) return true;                  // 같은 객체면 바로 true
     *         if (!(obj instanceof Member target)) return false;  // Member 가 아니면 false
     *         return this.age == target.age
     *                && java.util.Objects.equals(this.id, target.id)
     *                && java.util.Objects.equals(this.name, target.name);
     *     }
     * ------------------------------------------------------------------ */	
	@Override
	public int hashCode() {		
		return 0; // 재구현 부분 생략 (항상 0 을 반환한다)
	}
	@Override
	public boolean equals(Object obj) {
		return false; // 재구현 부분 생략 (항상 false 를 반환한다)
	}
	

    /* ------------------------------------------------------------------
     * 5. toString 재정의
     * ------------------------------------------------------------------
     * 재정의하지 않으면 Object 의 원래 toString 이 실행되어
     * exam04.Member@16진수해시코드 형태의 문자열이 반환된다.
     * 이 문자열로는 회원 정보를 확인할 수 없다.
     *
     * 그래서 필드값을 모아 하나의 문자열로 만들어 반환하도록 다시 작성한다.
     * 문자열과 숫자를 + 로 연결하면 숫자가 문자열로 자동 변환되어 이어 붙는다.
     *
     * 이 메소드는 System.out.println(객체) 처럼 객체를 출력할 때
     * 자바가 자동으로 호출한다.
     * ------------------------------------------------------------------ */	
	@Override
	public String toString() {
		return "Member[id=" + id + ", name=" + name + ", age=" + age + "]";
	}
	

}









