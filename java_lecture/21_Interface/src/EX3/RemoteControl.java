package Ex3;
/*
===============================================================
 RemoteControl 인터페이스
---------------------------------------------------------------
 전원을 켜고 끄는 기능의 추상메소드 "이름과 형태"만 정해 둔 파일이다.
 실행 코드(중괄호 안의 내용)는 없고, 추상메소드 선언만 있다.

 인터페이스에 선언된 추상메소드는 public abstract 를 생략해도
 컴파일할 때 자동으로 붙는다.

 이 인터페이스를 implements 한 클래스는
 turnOn() 과 turnOff() 를 반드시 오버라이딩해야 한다.
 하나라도 빠뜨리면 컴파일 오류가 난다.
===============================================================
*/
public interface RemoteControl {

	//추상메소드 선언 
	/*public abstract*/ void turnOn();  //전원을 켜는 기능 
						void turnOff(); //전원을 끄는 기능 
	
}








