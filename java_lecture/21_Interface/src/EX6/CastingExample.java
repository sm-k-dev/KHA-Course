package EX6;
/*
===============================================================
 업캐스팅(자동 타입 변환) 과 다운캐스팅(강제 타입 변환)
===============================================================

[1] 먼저 알아야 할 것

  객체를 담는 변수를 "참조변수"라고 한다.
  참조변수에는 두 가지가 따로 있다.

    - 참조변수의 자료형 : 왼쪽에 적은 타입. 어떤 메소드를 호출할 수 있는지 결정한다.
    - 실제 객체        : 오른쪽 new 로 만든 것. 어떤 코드가 실행될지 결정한다.

  이 둘이 다를 수 있다는 점이 이 단원의 핵심이다.

[2] 업캐스팅 (자동 타입 변환)

    Vehicle vehicle = new Bus();

  왼쪽은 부모 인터페이스 자료형, 오른쪽은 자식 클래스 객체다.
  부모 자료형에 자식 객체를 넣는 것은 자동으로 되며, 별도 표기가 필요 없다.

    장점 : Vehicle 자료형 변수 하나로 Bus, Taxi, Truck 등
           Vehicle 을 구현한 모든 객체를 담을 수 있다.
    단점 : Vehicle 에 선언된 run() 만 호출할 수 있다.
           Bus 에만 있는 checkFare() 는 호출할 수 없다.

[3] 다운캐스팅 (강제 타입 변환)

    Bus bus = (Bus) vehicle;

  업캐스팅으로 좁아진 호출 범위를 다시 넓히는 작업이다.
  자동으로 되지 않기 때문에 (Bus) 처럼 괄호로 자료형을 직접 적어야 한다.

  주의 : 실제 객체가 Bus 일 때만 성공한다.
        Bus 가 아닌 객체를 (Bus) 로 변환하면 컴파일은 통과하지만
        실행 중에 ClassCastException 오류가 발생한다.

[실행 결과]
Bus가 달립니다.
Bus가 달립니다.
승차요금을 체크합니다.
===============================================================
*/

//부모 인터페이스 
interface Vehicle{
	void run();  //달리는기능의 추상메소드
}

//Vehicle 를 부모인터페이스로 하여 구현한 Bus 자식클래스 만들기
class Bus  implements Vehicle{
	
	// Vehicle 부모인터페이스의 추상메소드를 Bus 에 맞게 오버라이딩한다.
	// 오버라이딩 조건.  인터페이스의 추상메소드는 public 이므로 public 을 반드시 붙인다.
	@Override
	public void run() {
		System.out.println("Bus가 달립니다");
	}
	
	//Bus 클래스에만 추가된 객체메소드
	public void checkFare() {
		System.out.println("승차요금을 체크합니다");
	}
}

public class CastingExample {

	public static void main(String[] args) {
		//------------------------------------------------------------------
		//[1] 업캐스팅 :  부모인터페이스 자료형으로 참조변수를 만들고 자식 객체를 담아 사용
		//-------------------------------------------------------------------
		Vehicle  vehicle  = new Bus();
		/*
						  [ Heap 영역 ]  Bus 객체 1개 생성
						  ┌──────────────────────────────────┐
						  │ Bus 객체                          │
						  │  run()         <- 오버라이딩한 코드  │
						  │  checkFare()                     │
						  └──────────────────────────────────┘
				
						  참조변수 vehicle 의 자료형은 Vehicle 부모인터페이스 이므로
						  이 객체를 Vehicle 부모인터페이스에 선언된 범위(run 만)로 바라본다.
		*/				  
				// run() 은 Vehicle 부모인터페이스 에 선언되어 있으므로 호출할 수 있다.
				vehicle.run();
				//출력 : Bus가 달립니다.
				//
				// 호출 과정
				//  1) 컴파일할 때 : Vehicle 부모인터페이스에 run() 이 있는지 확인한다. 있으므로 통과한다.
				//  2) 실행할 때   : 실제 객체가 Bus 이므로 Bus 의 오버라이딩된 실제 run() 이 실행된다.
				//                  이것을 동적 바인딩이라고 한다.
		
				//checkFare() 메소드는  Bus 클래스에만 만들어 놓았었고, Vehicle부모인터페이스에는 없으므로 호출할수 없다.
		//		vehicle.checkFare();
		
		//-----------------------------------------------------------------------
		//[2] 다운캐스팅 :  메소드나 변수 호출 범위를 자식 클래스 기준으로 되돌린다.
		//-----------------------------------------------------------------------		
		//다운캐스팅 작성 방법
			//자식클래스자료형  변수명 = (자식클래스자료형)부모자료형참조변수명;
				  Bus       bus  =  (Bus)vehicle;
				  		    bus.run();  		//출력 :  Bus가 달립니다.
				  		    bus.checkFare();	//출력 :  승차요금을 체크합니다.
		/*
		  객체는 새로 만들어지지 않는다.
		  참조변수 vehicle 과 bus 는 같은 Bus 객체 하나를 가리킨다.
		  달라진 것은 참조변수의 자료형뿐이다.

		  변수      자료형      호출 가능한 메소드
		  vehicle  Vehicle    run()
		  bus      Bus        run(), checkFare()
		*/
		//-------------------------------------------------------
		// [3] 잘못된 다운캐스팅을 막는 방법
		//-------------------------------------------------------
		// instanceof 로 실제 객체의 타입을 먼저 확인하면 안전하다.
		//
		//   if (vehicle instanceof Bus) {
		//       Bus b = (Bus) vehicle;
		//       b.checkFare();
		//   }
		//
		// 확인하지 않고 다른 타입으로 변환하면 실행 중에 다음 오류가 발생한다.
		//   Exception in thread "main" java.lang.ClassCastException:
		//   class Bus cannot be cast to class Taxi
	}

}









