package EX5;
/*
===============================================================
 업캐스팅(자동 타입 변환)이 가능한 관계 확인하기
===============================================================

[1] 이 파일의 목적

  이 예제에는 출력문이 없다. 실행해도 화면에 아무것도 나오지 않는다.
  "어떤 자료형의 변수에 어떤 객체를 담을 수 있는가"를
  컴파일 오류 없이 통과하는지로 확인하는 예제다.

[2] 업캐스팅 규칙

  부모 자료형의 변수에는 자식 객체를 그대로 담을 수 있다.
  괄호로 자료형을 적지 않아도 자동으로 처리된다.

      부모자료형 변수명 = new 자식클래스생성자();

  여기서 부모는 두 가지 모두 해당된다.
    - extends 로 상속한 부모 클래스
    - implements 로 구현한 부모 인터페이스

  직접 부모뿐 아니라, 위로 이어지는 조상이면 모두 가능하다.

[3] 이 파일의 상속 관계

        A (인터페이스)
        │
    ┌───┴───┐
    B       C        B, C 는 A 를 implements 한 클래스
    │       │
    D       E        D 는 B 를, E 는 C 를 extends 한 클래스

  따라서 B, C, D, E 는 모두 A부모인터페이스 자료형 참조변수에 담을 수 있다.
  D 는 B 를 거쳐 A 와 연결되고, E 는 C 를 거쳐 A 와 연결된다.
===============================================================
*/
//최상위 부모 인터페이스 A  만들기 
interface  A {}

//A 부모인터페이스를 구현한 클래스
class B implements A {}

//A 부모인터페이스를 구현한 클래스
class C implements A {}

//B 부모클래스를 상속한 클래스 
class D extends B {}     // 부모 클래스는 B, 그 위의 부모 인터페이스는 A 다.

//C 부모클래스를 상속한 클래스
class E extends C {}     // 부모 클래스는 C, 그 위의 부모 인터페이스는 A 다.


public class PromtionExample {
	public static void main(String[] args) {
	/*		
		이 파일의 상속 관계
	
	        A (인터페이스)
	        │
	    ┌───┴───┐
	    B       C        B, C 는 A 를 implements 한 클래스
	    │       │
	    D       E        D 는 B 를, E 는 C 를 extends 한 클래스
	
	  따라서 B, C, D, E 는 모두 A부모인터페이스 자료형 참조변수에 담을 수 있다.
	  D 는 B 를 거쳐 A 와 연결되고, E 는 C 를 거쳐 A 와 연결된다.
	===============================================================
	*/	
		//[1] 자식 객체 4개를 각각 자기 클래스자료형의 참조변수를 만들어 담는다.
		B  b = new B();
		C  c = new C();	   
		D  d = new D();
		E  e = new E();
		
		//[2] 부모인터페이스 자료형의 참조변수를 만들자.
		// 아직 아무 객체도 담지 않은 상태다.
		A a;
		
		//[3] 업캐스팅 :  부모A인터페이스 자료형 참조변수에  자식 객체들을 담아 본다.
		// 대입할 때마다 a 가 가리키는 객체가 바뀐다.
		// 객체가 새로 만들어지는 것은 아니다.
		a = b;   //B클래스 A인터페이스를 구현했으므로 가능하다.	
		
		a = c;   //C클래스도 A인터페이스를 구현했으므로 가능하다.
				 //(A) 를 붙여도 되지만, 자동으로 되므로 적지 않는다.
		
		a = d;   //D클래스는 B클래스를 상속했고, B클래스는 A인터페이스를 구현했으므로 업캐스팅 가능하다.
		
		a = e;  //E클래스는 C클래스를 상속했고, C클래스는 A인터페이스를 구현했으므로 업캐스팅 가능하다.
		
		
		//[4] 반대로 업캐스팅 안되는 경우
		
			//(1) 부모 자료형의 값을 자식 자료형 변수에 그냥 담을 수 없다
			//B  b2 = a;
			
			//이때는 다운캐스팅을 개발자가 직접 적어야 한다.
			B  b2 = (B)a;
			
			//(2) 상속 관계 아닌 클래스끼리는 담을 수 없다
			//B클래스와 C클래스는 둘다  A인터페이스를 각각 구현 할 뿐
			//B클래스와 C클래스는 서로 부모자식 상속관계가 아니다.
			//b = c;
		
			/*
			 -------------------------------------------------------
			  대입 가능 여부 정리

			  코드              결과      이유
			  A a = new B();   가능      B 가 A 를 구현함
			  A a = new D();   가능      D → B → A 로 연결됨
			  B b = new D();   가능      D 가 B 를 상속함
			  B b = new C();   불가능    B 와 C 는 상속 관계가 아님
			  D d = new B();   불가능    부모 객체를 자식 자료형에 담을 수 없음
			 -------------------------------------------------------

			  참고
			  변수 a 의 자료형은 A 이므로, a 로는 A 에 선언된 멤버만 호출할 수 있다.
			  A 에는 멤버가 하나도 없으므로 a 로 호출할 수 있는 메소드도 없다.
			  자식의 메소드를 쓰려면 다운캐스팅이 필요하다.
			 -------------------------------------------------------
			*/	
			
		
		
	}

}



















