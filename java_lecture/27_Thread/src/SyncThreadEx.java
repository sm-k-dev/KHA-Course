/*
 ============================================================
 📌 스레드 동기화 + wait / notify 완전 이해용 예제 (자판기 시나리오)
 ============================================================

 🎯 이 예제의 핵심 목적
 ------------------------------------------------------------
 1. 여러 스레드가 "하나의 자원(자판기)"을 동시에 사용하려고 할 때
 2. 데이터가 꼬이지 않도록 막는 방법을 이해한다
 3. wait() / notify()가 왜 필요한지 감으로 이해한다

 👤 등장인물 (현실 비유)
 ------------------------------------------------------------
 - AutoMachine : 자판기 (공유 자원)
 - Producer    : 음료를 넣는 사람 (공급자 스레드)
 - Consumer    : 음료를 사는 사람 (소비자 스레드)
 - synchronized: 자판기 문 잠그기
 - wait()      : "음료 없네… 기다릴게"
 - notify()    : "음료 들어왔어요!"
 ============================================================
 
 
 wait()란?
 👉 synchronized 상태에서
 👉 스레드 작업을 완전히 멈추고
 👉 락을 다른 스레드에게 반납하며
 👉 다른스레드에서 notify()메소드 호출을 기다리는 메소드
 ==============================================================
 
 notify() 메소드란?
 👉 synchronized 상태에서만 호출 가능
 👉 wait()로 잠들어 있는 스레드 중 하나를 선택
 👉 그 스레드를 깨워서 실행 "준비 상태"로 만듦
 👉 ❗ 즉시 실행시키지는 않음
 👉 ❗ 락을 바로 주지 않음
 👉 synchronized 블록/메소드 내부의 코드 실행이 끝날 때까지  다른스레드 대기 !
 ==============================================================
*/

//음료를 공급해서 쌓아 두기 위한 비커 모양의 메모리를 만들기 위해 사용할 Stack클래스 import
import java.util.Stack;

/*
=======================================================================
자판기 역할을 하는 설계도(클래스) -> 공유자원 : 여러 스레드가 동시에 사용하는 "공유 메모리"
========================================================================
*/
class AutoMachine { // 자판기

	//---------------------------------------------------
	//자판기 안에 들어있는 음료 보관함
	//Stack클래스의 객체  = 위에 쌓고(push()), 위에서 꺼냄(pop())
	//----------------------------------------------------
	Stack store = new Stack();
	/*
		|		|
		|		|
		|		|
		|_______|
	*/
	/*
		-----------------------------------------------
		 소비자 스레드가 음료를 뽑아 먹는 행동 메소드로 만들기 
		------------------------------------------------
	*/
	public synchronized String getDrink() {
		
		// 자판기 (AutoMachine) 객체 안의 Stack 객체 메모리 공간이 비어있을 수도 있으므로
		// 일단 소비자 스레드가 "기다리는 행동"부터 수행 하기 위해 this.wait(); 메소드 호출
		try {
	       	/*       	 
	       	 [this.wait(); 이 코드가 실행되는 정확한 상황]
	       	 --------------------------------------------------------------
	       	 - 지금 이 코드는 소비자 스레드가 실행 중이다
	       	 - 소비자 스레드는 자판기(AutoMachine)의 synchronized 메소드에 들어와 있다
	       	 - 즉, 소비자스레드는 현재 "자판기 문(락)"을 잡고 있는 상태이다
	       	 - 하지만 자판기 안에 아직 음료가 없을 수 있다
	       	 
	       	 --------------------------------------------------------------
	       	 [this.wait(); 가 호출되는 순간 무슨 일이 일어날까?]
	       	 --------------------------------------------------------------
	       	 
	       	 ① 현재 실행 중인 스레드(소비자 스레드)가
	       	    "나는 지금 할 일이 없으니 잠시 기다릴게" 라고 선언함
	       	 
	       	 ② JVM은 이 스레드를 즉시 실행 중단시킴
	       	    → run() 메소드의 실행이 멈춘다
	       	 
	       	 ③ 스레드 상태 변화
	       	    RUNNING  →  WAITING (무한 대기 상태)
	       	    
	       	    ※ WAITING 상태란?
	       	    - 누군가 깨워줄 때까지 절대 깨어나지 않음
	       	    - 시간이 지나도 자동으로 깨어나지 않음
	       	    - notify() 또는 notifyAll() 이 필요함
	       	 
	       	 ④ CPU 사용 여부
	       	    ❌ CPU를 전혀 사용하지 않음
	       	    ❌ while문처럼 계속 도는 "바쁜 대기"가 아님
	       	    ✔ 완전히 멈춰 있는 상태 (효율적)
	       	 
	       	 --------------------------------------------------------------
	       	 [🔥 가장 중요한 핵심 포인트 🔥]
	       	 --------------------------------------------------------------
	       	 
	       	 ⑤ wait()를 호출하면
	       	    ✔ 지금까지 잡고 있던 "자판기 문(락)"을 즉시 다른 공급자 스레드에게 반납한다
	       	 
	       	    즉,
	       	    - synchronized 영역 안에 있었지만
	       	    - 락을 놓고 문을 열어준다
	       	 
	       	    💡 이게 없으면?
	       	       공급자 스레드가 자판기에 들어올 수 없음
	       	       → 프로그램 멈춤(데드락 위험)
	       	 
	       	 --------------------------------------------------------------
	       	 [이후 다른 공급자 스레드는 어떻게 될까?]
	       	 --------------------------------------------------------------
	       	 
	       	 ⑥ 소비자스레드가 락을 반납했기 때문에
	       	    → 공급자 스레드가 자판기(synchronized putDrink()메소드 사용)에 들어올 수 있음
	       	 
	       	 ⑦ 공급자 스레드는
	       	    - 음료를 자판기에 공급하고 
	       	    - notify() 를 호출함
	       	 
	       	 --------------------------------------------------------------
	       	 [wait()에서 깨어나는 순간]
	       	 --------------------------------------------------------------
	       	 
	       	 ⑧ notify()가 호출되면
	       	    - WAITING 상태였던 소비자 스레드는
	       	      RUNNABLE 상태로 이동
	       	 
	       	    ⚠ 하지만!
	       	    - 즉시 실행되는 것은 아님
	       	    - synchronized 락을 다시 얻어야 실행 가능
	       	 
	       	 ⑨ 공급자 스레드가 synchronized 영역을 빠져나가면
	       	    → 락이 풀림
	       	    → 소비자 스레드가 락을 다시 획득
	       	 
	       	 ⑩ 소비자 스레드는
	       	    wait() 다음 줄부터 실행을 재개함
	       	    → store.pop() 실행
	       	 
	       	 --------------------------------------------------------------
	       	 [현실 세계 자판기 비유]
	       	 --------------------------------------------------------------
	       	 
	       	 - 소비자:
	       	   "음료가 없네… 문 열어두고 밖에서 기다릴게"
	       	 
	       	 - 자판기:
	       	   문이 열려 있음
	       	 
	       	 - 공급자:
	       	   "음료 넣고, 기다리는 사람 깨워야지!"
	       	 
	       	 - notify():
	       	   "이제 음료 있어요!"
	       	 
	       	 - 소비자:
	       	   다시 문을 열고 들어와 음료를 꺼냄
	       	 
	       	 --------------------------------------------------------------
	       	 [정리 핵심 한 줄]
	       	 --------------------------------------------------------------
		 	 wait()란?
		   	 👉 synchronized String getDrink() 내부에서 
		   	 👉 소비자 스레드 작업을 완전히 멈추고
		   	 👉 락을 다른 공급자 스레드에게 반납하며
		   	 👉 다른 공급자 스레드에서 notify()메소드 호출을 기다리는 메소드
	       	 ==============================================================
	       	*/
			this.wait();
			
		} catch (InterruptedException e) {
			e.printStackTrace();
		}
		
		// 자판기의 음료 보관함 (Stack 메모리) 에서 음료 하나를 꺼내서 문자열 형태로 반환
		return store.pop().toString();
	}
	
	/*
	-----------------------------------------------
	공급자 스레드가 음료를 넣는 행동을 메소드로 만들기
	--------------------------------------------
	synchronized:
	- 자판기 문 잠금
	- 소비자와 동시에 접근 못하게 함

	*/
	public synchronized void putDrink( String drink ) {
		
		// 자판기의 음료 보관함(Stack 메모리)에 음료를 하나 넣음
		store.push(drink);
		
		// 바로 윗줄에서 음료 보관함 (Stack 메모리) 에 음료 하나 공급했으니 소비자 스레드에게 wait() 그만하고 pop() 하라고 알려줌
		this.notify();
		/*
			 notify() 메소드란?
			 👉 synchronized 상태에서만 호출 가능
			 👉 wait()로 잠들어 있는 소비자 스레드 하나를 선택
			 👉 그 소비자 스레드를 깨워서 실행 "준비 상태"로 만듦
			 👉 ❗ 즉시 실행시키지는 않음
			 👉 ❗ 락을 바로 주지 않음
			 👉 synchronized 블록/메소드 내부의 코드 실행이 끝날 때까지  다른 소비자 스레드 대기 !
		*/
	}
}

/*
------------------------------------------------
공급자 스레드 (음료를 넣는 사람)
------------------------------------------------
*/
class Producer implements Runnable {
	
	// 자판기 객체의 주소 저장 (공유 자원)
	private AutoMachine machine;
	
	// 생성자 - 자판기 객체의 주소를 매개변수로 받아 위 machine에 저장
	public Producer ( AutoMachine machine ) {
		this.machine = machine;
	}
	
	@Override
	public void run() {
		// 음료 1번 ~ 9번까지 AutoMachine 객체 내부의 Stack 음료 보관함에 공급
		for ( int i = 1 ; i < 10 ; i++ ) {
			
			// 공급자 스레드가 음료보관함에 음료 공급 중이라는 모습 출력
			System.out.println( Thread.currentThread().getName() + " : 음료수 No." + i + " 공급");
			
			// 자판기의 음료보관함에 음료 공급(넣기)
			machine.putDrink( "음료수 No." + i );
			
			// 공급자 스레드가 잠깐 0.1초 휴식 후 위 음료 공급을 하게 하기 위해 0.1초 휴식
			try {
				Thread.sleep(100);
			} catch ( InterruptedException e) {
				e.printStackTrace();
			}
			
		}
	}
}

/*
-----------------------------------------------------
소비자 스레드 클래스 (음료를 자판기의 Stack 에서 꺼내서 뽑아먹는 사람)
----------------------------------------------------
*/
class Consumer implements Runnable {
	
	// 자판기 객체의 주소 저장 (공유 자원)
	private AutoMachine machine;
	
	// 생성자 - 자판기 객체의 주소를 매개변수로 받아 위 machine에 저장
	public Consumer ( AutoMachine machine ) {
		this.machine = machine;
	}
	
	// 소비자 스레드가 할일을 run 메소드에 오버라이딩(재구현)
	@Override
	public void run() {
		// 음료 1번 ~ 9번까지 AutoMachine 객체 내부의 Stack 음료 보관함에서 꺼내오자 (뽑아 먹자)
		for ( int i = 1 ; i < 10 ; i++ ) {
			
			// 음료 하나를 뽑아 먹을때마다 모습 묘사
			System.out.println( Thread.currentThread().getName() + " : " + machine.getDrink() + " 구입해서 뽑아먹고 있다." );
			
			// 소비자 스레드가 음료 하나를 뽑아 먹는 시간 간격을 적용하기 위해서 0.1초 휴식 후 위 .getDrink() 메소드 호출되게 하자
			try {
				Thread.sleep(100);
			} catch (InterruptedException e) {
				e.printStackTrace();
			}
		}
	}
}

public class SyncThreadEx {

	public static void main(String[] args) {
		
		// 1. 자판기 객체 생성
		AutoMachine autoMachine = new AutoMachine();
        /*
	        Heap 메모리 상태
	        ---------------------------------
	        AutoMachine
	         └ Stack store = []
       */
		
		// 2. 공급자 스레드 객체 생성 및 일 시작 (공급 시작)
		new Thread ( new Producer(autoMachine), "정우 공급자 스레드" ).start(); // run()  실행 될것임
		// new Thread( run() 메소가 작성된 클래스의 객체,"저장할 스레드명").start();
		
		// 3. 소비자 스레드 객체 생성 및 일 시작 (소비 시작)
		new Thread ( new Consumer(autoMachine), "길동 소비자 스레드" ).start(); // run() 실행 될것임
		// new Thread( run() 메소가 작성된 클래스의 객체,"저장할 스레드명").start();
	}

}
