//==================================================================
// [클래스 1] 방법 1 - Thread 클래스를 상속해서 만드는 스레드
//
//   TODO 1 : 클래스 선언부를 완성하시오
//     조각 : class SmsThread extends Thread {
//       class      : 클래스를 만든다는 예약어
//       SmsThread  : 클래스 이름
//       extends Thread : Thread 클래스를 상속한다는 표시.
//                        이 표시가 있어야 이 클래스가 스레드가 된다
//==================================================================
class SmsThread extends Thread {

    //----------------------------------------------------------
    // TODO 2 : run 메소드를 완성하시오
    //
    //   선언부 (아래에 미리 작성해 둠)
    //     @Override        : 부모(Thread)의 run 을 다시 정의한다는 표시
    //     public void run() { ... }
    //     start() 가 호출되면 새 스레드가 이 run 안의 코드를 실행한다
    //
    //   몸통에 쓸 문장
    //     줄 1 : for 문으로 i 를 1부터 3까지 반복한다
    //            --> for (int i = 1; i <= 3; i++) {
    //     줄 2 :   스레드 이름과 번호를 출력한다
    //            getName() : 이 스레드의 이름을 돌려주는 메소드.
    //                        Thread 를 상속했으므로 그냥 쓸 수 있다
    //            --> System.out.println(getName() + " : " + i);
    //     줄 3 : } (for 의 끝)
    //----------------------------------------------------------

    @Override
    public void run() {

        //여기에 TODO 2 의 for 문을 작성하시오
    	for ( int i = 1 ; i <= 3 ; i++ ) {
    		System.out.println( getName() + " : " + i );
    	}
    }   //run 메소드의 끝

}   //SmsThread 클래스의 끝

//==================================================================
// [클래스 2] 방법 2 - Runnable 인터페이스를 구현해서 만드는 작업
//
//   TODO 3 : 클래스 선언부를 완성하시오
//     조각 : class EmailTask implements Runnable {
//       implements Runnable : Runnable 인터페이스를 구현한다는 표시.
//                             구현하면 run 메소드를 반드시 만들어야 한다
//==================================================================
class EmailTask implements Runnable {

    //----------------------------------------------------------
    // TODO 4 : run 메소드의 몸통을 완성하시오
    //
    //   줄 1 : for 문으로 i 를 1부터 3까지 반복
    //   줄 2 :   스레드 이름과 번호 출력
    //            주의! 여기서는 getName() 을 쓸 수 없다.
    //            Runnable 은 Thread 를 상속한 것이 아니라 이름 기능이 없다.
    //            대신 아래 방법으로 지금 실행 중인 스레드의 이름을 얻는다
    //            --> Thread.currentThread().getName()
    //              1단계 Thread.currentThread() : 지금 실행 중인 스레드 객체를 얻음
    //              2단계 .getName()             : 그 객체의 이름을 얻음
    //            --> System.out.println(Thread.currentThread().getName() + " : " + i);
    //   줄 3 : }
    //----------------------------------------------------------

    @Override
    public void run() {

        //여기에 TODO 4 의 for 문을 작성하시오
    	for ( int i = 1 ; i <= 3 ; i++ ) {
    		System.out.println( Thread.currentThread().getName() + " : " + i );
    	}
    }   //run 메소드의 끝

}   //EmailTask 클래스의 끝

//==================================================================
// [클래스 3] 실행 클래스
//==================================================================
public class ThreadEx01_Student {

    public static void main(String[] args) {

        //------------------------------------------------------
        // TODO 5 : 방법 1로 스레드를 만들고 시작하시오
        //
        //   줄 1 : 객체 생성   --> SmsThread t1 = new SmsThread();
        //          (Thread 를 상속했으므로 이 객체 자체가 스레드다)
        //   줄 2 : 이름 지정   --> t1.setName("문자발송");
        //          setName : 스레드 이름을 정하는 메소드.
        //                    지정하지 않으면 Thread-0 같은 기본 이름이 된다
        //   줄 3 : 시작       --> t1.start();
        //          start : 새 스레드를 만들고 그 스레드가 run 을 실행하게 한다
        //------------------------------------------------------

        //여기에 TODO 5 의 세 줄을 작성하시오
    	SmsThread t1 = new SmsThread();
    	t1.setName("문자발송");
    	t1.start();

        //------------------------------------------------------
        // TODO 6 : 방법 2로 스레드를 만들고 시작하시오
        //
        //   줄 1 : 작업 객체 생성 --> EmailTask task = new EmailTask();
        //          (이것은 "작업" 일 뿐 아직 스레드가 아니다)
        //   줄 2 : 스레드 객체 생성 --> Thread t2 = new Thread(task, "이메일발송");
        //          new Thread(작업, 이름) : 재료 2개를 전달한다
        //            첫 재료 : 실행할 작업 객체
        //            둘째 재료 : 스레드 이름
        //   줄 3 : 시작 --> t2.start();
        //------------------------------------------------------

        //여기에 TODO 6 의 세 줄을 작성하시오
    	EmailTask task = new EmailTask();
    	Thread t2 = new Thread(task, "이메일발송");
    	t2.start();

        //------------------------------------------------------
        // TODO 7 : main 스레드의 메시지를 출력하시오
        //   --> System.out.println("main : 알림 발송을 요청했다");
        //   이 줄은 위 두 스레드가 실행되는 동안 동시에 실행된다
        //------------------------------------------------------

        //여기에 TODO 7 을 작성하시오
    	System.out.println("main: 알림 발송을 요청했다");
    	
    }   //main 의 끝

}   //ThreadEx01_Student 클래스의 끝
