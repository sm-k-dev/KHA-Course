//==================================================================
// [클래스 1] 조회수 합계를 계산하는 작업
//==================================================================
class ViewCountTask implements Runnable {

    //----------------------------------------------------------
    // TODO 1 : 멤버 변수 2개를 선언하시오
    //
    //   줄 1 : 계산 범위의 끝 값을 담을 변수
    //          --> 자료형 int, 이름 max
    //   줄 2 : 계산 결과를 담을 변수. 처음 값은 0
    //          --> 자료형 long, 이름 result, 시작값 0
    //          long 을 쓰는 이유 : 합계가 int 로 담을 수 있는 범위
    //          (약 21억)를 넘어갈 수 있기 때문이다
    //
    //   이 멤버 변수가 안전한 이유 : 작업 객체를 스레드마다 따로 만들기 때문이다
    //----------------------------------------------------------

    //여기에 TODO 1 의 멤버 변수 2개를 선언하시오
	int max;
	long result = 0;
	
    //----------------------------------------------------------
    // TODO 2 : 생성자를 완성하시오
    //
    //   생성자란 : 객체를 만드는 순간(new 할 때) 딱 한 번 실행되는 특별한 메소드.
    //             이름이 클래스 이름과 같고, 반환 타입(void 등)을 쓰지 않는다
    //
    //   선언부 : public ViewCountTask(int max) {
    //   몸통   : this.max = max;
    //            this.max : "이 객체의" 멤버 변수 max
    //            max      : 전달받은 매개변수
    //            이름이 같을 때 구분하려고 this. 를 붙인다
    //   닫기   : }
    //----------------------------------------------------------

    //여기에 TODO 2 의 생성자를 작성하시오
	public ViewCountTask(int max) {
		this.max = max;
	}


    //----------------------------------------------------------
    // TODO 3 : run 메소드의 몸통을 완성하시오
    //
    //   줄 1 : for 문으로 i 를 1부터 max 까지 반복
    //          --> for (int i = 1; i <= max; i++) {
    //   줄 2 :   result 에 i 를 더해서 다시 result 에 담는다
    //          --> result = result + i;
    //   줄 3 : }
    //   줄 4 : 계산 완료 메시지 출력
    //          --> System.out.println(Thread.currentThread().getName() + " 계산 완료");
    //----------------------------------------------------------

    @Override
    public void run() {
    	
        //여기에 TODO 3 을 작성하시오
    	for(int i=1;  i<=max;  i++) {
    		result += i;
    	}
    	
    	System.out.println(Thread.currentThread().getName() + " 계산 완료");
    	
    }   //run 메소드의 끝

}   //ViewCountTask 클래스의 끝

