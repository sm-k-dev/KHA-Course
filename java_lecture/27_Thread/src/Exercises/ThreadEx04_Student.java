package Exercises;

/*
 * ==================================================================
 * [연습문제 4] 좋아요 수 사고 재현 - 공유 변수 문제      난이도 ★★☆
 * (Thread04_SharedField 학습 내용)  학생용 - TODO 를 완성하시오
 * ==================================================================
 *
 * ■ 상황
 *   게시글의 좋아요 수를 올리는 서비스가 있다.
 *   사용자 2명이 각각 100만 번씩 좋아요를 누르면 결과는 200만이어야 한다.
 *   그런데 실제로 실행해 보면 그보다 작은 값이 나온다.
 *   이 연습문제의 목적은 "그 사고를 직접 재현해서 눈으로 확인하는 것" 이다.
 *   (고치는 방법은 연습문제 5에서 배운다)
 *
 * ■ 왜 값이 사라지는가 - like++ 의 3단계 모델
 *
 *   like++ 는 한 줄이지만 실제로는 3단계로 실행된다
 *     1단계 : like 의 값을 읽는다
 *     2단계 : 읽은 값에 1을 더한다
 *     3단계 : 더한 값을 like 에 저장한다
 *
 *   like 가 10 일 때 두 스레드가 겹치면
 *
 *   시각 | 사용자A 의 동작   | 사용자B 의 동작   | like 값
 *   -----+-------------------+-------------------+--------
 *   1    | 1단계 : 10 을 읽음 |                   | 10
 *   2    |                   | 1단계 : 10 을 읽음 | 10   <- A가 저장하기 전에 끼어듦
 *   3    | 2,3단계 : 11 저장  |                   | 11
 *   4    |                   | 2,3단계 : 11 저장  | 11   <- 2번 눌렀는데 1만 올랐다!
 *
 *   이런 겹침이 수십만 번 일어나므로 결과가 200만보다 작아진다.
 *
 * ■ 메모리 공유 구조 모델 (무엇이 공유되는가)
 *
 *   [Heap]
 *     LikeService 객체 1개   like = 0     <- 스레드 2개가 "같은" 객체를 본다
 *                                            --> 공유됨 --> 사고의 원인
 *
 *   서블릿과 스프링 빈은 객체가 1개만 만들어지므로 실제 서비스에서
 *   이 구조가 그대로 발생한다. 그래서 이 실습이 중요하다.
 *
 * ■ 예상 출력 (실제값은 실행할 때마다 다르다)
 *   기대값 : 2000000
 *   실제값 : 1362481      <- 200만보다 작으면 사고가 재현된 것이다
 *
 *   만약 정확히 2000000 이 나오면 컴퓨터가 빨라 겹침이 안 생긴 경우다.
 *   반복 횟수를 10000000(1000만)으로 늘려서 다시 실행해 보자.
 *   그래도 계속 2000000 이 나온다면 CPU 코어가 1개인 환경일 수 있다.
 *   코어가 1개면 두 스레드가 정말로 동시에 실행되지 못해 겹침이 드물다.
 *   (요즘 PC 는 대부분 코어가 여러 개이므로 사고가 재현된다)
 *
 * ■ 서술형 문제 (완성 후 주석으로 답을 적으시오)
 *   문제 A. 이 프로그램에서 사고가 나는 변수는 무엇이고, 왜 위험한가?
 *           답:
 * ==================================================================
 */

//==================================================================
// [클래스 1] 좋아요 서비스 (서블릿/스프링 빈 1개를 흉내 낸 클래스)
//==================================================================
class LikeService {

    //----------------------------------------------------------
    // TODO 1 : 좋아요 수를 담을 멤버 변수를 선언하시오
    //   --> 자료형 int, 이름 like, 시작값 0
    //
    //   이 변수가 "공유 변수" 다.
    //   객체가 1개뿐이므로 이 변수도 1개이고, 모든 스레드가 같이 쓴다
    //----------------------------------------------------------

    //여기에 TODO 1 을 작성하시오
	int like = 0;
	

    //----------------------------------------------------------
    // TODO 2 : 좋아요 수를 1 올리는 메소드를 완성하시오
    //
    //   선언부 : public void increase() {
    //     public : 밖(Task)에서 호출하므로 공개
    //     void   : 돌려줄 값 없음
    //     ()     : 전달받을 재료 없음
    //
    //   몸통 : like++;
    //     ++ : 값을 1 늘리는 연산. like = like + 1; 과 같다
    //     이번 문제에서는 일부러 보호 장치를 넣지 않는다 (사고 재현이 목적)
    //
    //   닫기 : }
    //----------------------------------------------------------

    //여기에 TODO 2 의 메소드를 작성하시오
	public void increase() {
		like++;
	}

}   //LikeService 클래스의 끝

//==================================================================
// [클래스 2] 좋아요를 반복해서 누르는 작업
//==================================================================
class LikeTask implements Runnable {

    //----------------------------------------------------------
    // TODO 3 : 사용할 서비스 객체를 가리킬 멤버 변수를 선언하시오
    //   --> 자료형 LikeService, 이름 service
    //----------------------------------------------------------

    //여기에 TODO 3 을 작성하시오
	LikeService service;


    //----------------------------------------------------------
    // TODO 4 : 생성자를 완성하시오
    //   선언부 : public LikeTask(LikeService service) {
    //   몸통   : this.service = service;
    //   닫기   : }
    //
    //   이렇게 밖에서 만든 객체를 전달받는 이유
    //     여기서 new LikeService() 를 하면 스레드마다 서비스가 따로 생겨
    //     공유 상황이 만들어지지 않는다. 그러면 사고가 재현되지 않는다
    //----------------------------------------------------------

    //여기에 TODO 4 의 생성자를 작성하시오
	public LikeTask(LikeService service) {		
		this.service = service;
	}

    //----------------------------------------------------------
    // TODO 5 : run 메소드의 몸통을 완성하시오
    //   줄 1 : for 문으로 i 를 0부터 1000000 미만까지 반복
    //          --> for (int i = 0; i < 1000000; i++) {
    //          (0 부터 시작해 999999 까지이므로 정확히 100만 번 반복된다)
    //   줄 2 :   service.increase();  <- 좋아요 1 증가 호출
    //   줄 3 : }
    //----------------------------------------------------------

    @Override
    public void run() {

        //여기에 TODO 5 를 작성하시오
    	for(int i=0;  i<1000000;  i++) {  //100만번 반복
    		
    		service.increase(); //공유 서비스의 increase() 호출  -> like 멤버변수 값 1증가 시도 
    	}
    	

    }   //run 메소드의 끝

}   //LikeTask 클래스의 끝

//==================================================================
// [클래스 3] 실행 클래스
//==================================================================
public class ThreadEx04_Student {

    public static void main(String[] args) throws InterruptedException {

        //------------------------------------------------------
        // TODO 6 : 서비스 객체를 "딱 1개" 만드시오
        //   --> LikeService service = new LikeService();
        //   1개만 만드는 것이 이 문제의 핵심이다.
        //   객체가 1개여야 like 변수도 1개이고, 그래야 공유 상황이 된다
        //------------------------------------------------------

        //여기에 TODO 6 을 작성하시오
    	LikeService service = new LikeService();


        //------------------------------------------------------
        // TODO 7 : 그 서비스를 사용하는 작업 객체를 1개 만드시오
        //   --> LikeTask task = new LikeTask(service);
        //------------------------------------------------------

        //여기에 TODO 7 을 작성하시오
    	LikeTask task = new LikeTask(service);
    	
    	
        //------------------------------------------------------
        // TODO 8 : 스레드 2개를 만들고 시작한 뒤, 끝날 때까지 기다리시오
        //   줄 1 : Thread t1 = new Thread(task, "사용자A");
        //   줄 2 : Thread t2 = new Thread(task, "사용자B");
        //   줄 3 : t1.start();
        //   줄 4 : t2.start();
        //   줄 5 : t1.join();     <- 결과를 보려면 계산이 끝나야 하므로 필수
        //   줄 6 : t2.join();
        //------------------------------------------------------

        //여기에 TODO 8 의 여섯 줄을 작성하시오
    	Thread t1  = new Thread(task, "사용자A");
    	Thread t2 = new Thread(task, "사용자B");
    	
    	//두 스레드를 동시에 일 시작 시키기 
    	t1.start();  t2.start();

    	//위 두 스레드가 작업이 모두 끝날떄 까지 main스레드를 대기 시킨다
    	t1.join();   t1.join();

   
        //------------------------------------------------------
        // TODO 9 : 기대값과 실제값을 출력하시오
        //   --> System.out.println("기대값 : 2000000");
        //   --> System.out.println("실제값 : " + service.like);
        //   실제값이 200만보다 작으면 사고가 재현된 것이다
        //------------------------------------------------------

        //여기에 TODO 9 의 두 줄을 작성하시오
    	System.out.println("기대값 : 2000000");
    	System.out.println("실제값 : " + service.like);

    }   //main 의 끝

}   //ThreadEx04_Student 클래스의 끝
