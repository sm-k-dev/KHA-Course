/*
 * ==================================================================
 * [Thread04] 공유 변수 문제 - JSP/Spring 에서 가장 중요한 내용 ★★★
 *            
 *            주제 : 여러 스레드가 같은 변수값을 "동시에 수정" 하면 값이 깨진다.
 * ==================================================================
 *
 * ------------------------------------------------------------------
 * 1. 이 예제가 보여 주는 핵심 사실
 * ------------------------------------------------------------------
 *
 *   사실 1. 서블릿 객체와 Spring 의 컨트롤러/서비스(빈)는
 *           서버가 시작될 때 "딱 1개만" 만들어진다. (싱글톤이라고 부른다)
 *
 *   사실 2. 그런데 요청이 올 때마다 스레드가 배정되므로
 *           "객체 1개" 를 "스레드 여러 개" 가 동시에 사용한다.
 *
 *   사실 3. 객체가 1개이므로 그 안의 멤버 변수(필드)도 1개다.
 *           --> 모든 스레드가 같은 변수를 공유한다.
 *
 *   사실 4. 여러 스레드가 같은 변수를 "동시에 수정" 하면 값이 깨진다.
 *
 *   이 파일은 사실 4 의 사고를 직접 눈으로 확인하는 예제다.
 *
 * ------------------------------------------------------------------
 * 2. 값이 깨지는 원리 - count++ 의 3단계 동작 방식 (이 예제의 심장)
 * ------------------------------------------------------------------
 *
 *   count++ 는 코드로는 한 줄이지만, CPU 는 3단계로 나눠 실행한다
 *
 *     1단계 : count 의 현재 값을 "읽는다"
 *     2단계 : 읽은 값에 1 을 "더한다"
 *     3단계 : 더한 값을 count 에 "저장한다"
 *
 *   [사고 발생 타임라인] count 가 10 일 때 두 스레드가 겹치면
 *
 *     시각 | 사용자A 의 동작        | 사용자B 의 동작        | count
 *     -----+------------------------+------------------------+------
 *     1    | 1단계 : 10 을 읽음     |                        | 10
 *     2    |                        | 1단계 : 10 을 읽음     | 10
 *          |                        |   (A가 저장하기 전에   |
 *          |                        |    끼어들었다!)        |
 *     3    | 2,3단계 : 11 저장      |                        | 11
 *     4    |                        | 2,3단계 : 11 저장      | 11
 *
 *     두 번 증가시켰는데 결과는 11. 증가 1회가 사라졌다.
 *     이 겹침이 수십만 번 반복되면 결과가 기대값보다 크게 작아진다.
 *
 * ------------------------------------------------------------------
 * 3. 메모리 공유 구조 모델 - 무엇이 공유되는가
 * ------------------------------------------------------------------
 *
 *   [Stack - 사용자A 스레드]     [Heap]                  [Stack - 사용자B 스레드]
 *     i (자기 것, 안전)            CountService 객체 1개     i (자기 것, 안전)
 *     service (참조) --------->      count = 0        <--------- service (참조)
 *                                    ^^^^^^^^
 *                                    변수가 1개뿐이라 둘이 같이 쓴다 (공유!)
 *
 *   지역변수 i 는 스레드마다 Stack 에 따로 만들어져 안전하고,
 *   멤버 변수 count 는 Heap 의 객체 안에 1개뿐이라 공유되어 위험하다.
 * ==================================================================
 */

// ===========================================================
// 서블릿 / 컨트롤러 1개를 흉내 낸 클래스
// ===========================================================
class CountService {
	// 변수: 이 CountService 객체를 쓰는 모든 스레드가 이 변수값을 공유 한다
	int count = 0;
	
	// 사이트 방문자 수를 1 올리는 기능의 메소드
	public void increase() {
		count++;
	}
}

// ===========================================================
// increase() 메소드를 반복 호출하는 작업 ( 사용자 1명의 요청을 흉내 냄)
// ===========================================================
class IncreaseTask implements Runnable {
	
	// 어떤 서비스 객체를 사용할지 전달 받아 저장한다.
	CountService service;
	
	public IncreaseTask ( CountService service ) {
		this.service = service;
	}
	
	@Override
	public void run() {
		// increase() 메소드를 1,000,000 번 호출 한다
		for ( int i = 0 ; i < 1000000 ; i++ ) {
			service.increase();
		}
	}
}

public class Thread04_SharedField {

	public static void main(String[] args) throws InterruptedException {
		
		// 서비스 객체를 딱 1개만 만든다 ( 서블릿 / 스프링 빈이 싱글톤인 것과 동일)
		CountService service = new CountService();
		
		// 바로 위 서비스 객체를 사용하는 run() 메소드가 작성된 작업 객체를 만든다
		IncreaseTask task = new IncreaseTask(service);
		
		// 스레드 2개가 같은 작업을 실행하게 만들자 ( 사용자 2명이 동시에 하나의 홈페이지에 접속 요청하는 상황 )
		Thread t1 = new Thread(task, "사용자A");
		Thread t2 = new Thread(task, "사용자B");
		
		// 두 스레드 동시에 시작 시키기
		t1.start();	t2.start();
		
		// 두 스레드가 모두 작업을 마칠때 까지 main 스레드에게 프로그램을 종료하지 말고 대기 하게 한다.
		t1.join();	t2.join();
		
		// main 스레드의 출력
		System.out.println("기대값 : 2000000");
		System.out.println("실제값 : " + service.count);
		
        /*
         * ■ 실행 결과 (매번 다름)
         *   기대값: 2000000
         *   실제값: 1362481   ← 증가 연산 수십만 번이 사라졌다!
         *
         * ※ 만약 정확히 2000000이 나온다면 (PC 환경에 따라 가능)
         *   반복 횟수를 100000000(1억)으로 늘려서 다시 실행해 볼 것.
         *
         * ■ 핵심 정리
         *   1. 이 현상을 "레이스 컨디션(경쟁 상태)"이라고 한다.
         *   2. 원인: 멤버 변수 공유 + 동시 수정
         *   3. 서블릿/컨트롤러의 멤버 변수에 요청 데이터를 저장하면
         *      실제 서비스에서 이 버그가 그대로 발생한다.
         *      예) 로그인한 사용자 ID를 멤버 변수에 저장
         *          → 내 화면에 다른 사람의 정보가 보이는 대형 사고
         *   4. 해결 방법은 Thread05, Thread06에서 배운다.
         */
	}

}
