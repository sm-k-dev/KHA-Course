/*
 * ==================================================================
 * [Thread03] join() - 스레드가 끝날 때까지 기다리기
 * ==================================================================
 *
 * ------------------------------------------------------------------
 * 1. 이 예제의 핵심 메소드 : 스레드변수.join()
 * ------------------------------------------------------------------
 *
 *   기능   : "그 스레드가 종료될 때까지, join 을 호출한 스레드를 재운다"
 *   매개변수: 없음 (밀리초를 넣는 형태도 있지만 여기서는 기본형만 배운다)
 *   반환값 : 없음(void)
 *
 *   동작 방식 (누가 기다리는지가 가장 헷갈리는 부분이다)
 *
 *     main 스레드가 t1.join(); 을 실행하는 순간
 *       1. main 스레드는 "대기 상태" 로 바뀌어 그 줄에서 멈춘다
 *          (t1 이 멈추는 것이 아니다! t1 은 계속 달린다)
 *       2. t1 의 run 이 끝나서 t1 이 종료되면
 *       3. JVM 이 main 을 깨워 준다 --> main 이 다음 줄부터 다시 실행된다
 *
 *     한 줄 요약 : "join 을 부른 쪽이 기다리고, 붙은 대상은 계속 달린다"
 *
 *   주의   : join 은 InterruptedException 을 발생시킬 수 있는 메소드다.
 *            (대기 중에 외부에서 깨워질 수 있기 때문)
 *            그래서 main 선언부에 throws InterruptedException 이 붙어 있다
 *
 * ------------------------------------------------------------------
 * 2. join 이 왜 필요한가 - start() 의 성질 때문이다
 * ------------------------------------------------------------------
 *
 *   start() 는 "시작만" 시키고 곧바로 다음 줄로 넘어간다.
 *   시작된 스레드가 언제 끝날지는 아무도 모른다.
 *
 *   [join 이 없을 때의 시간표 - 사고 상황]
 *
 *     시각  | main 스레드              | 계산기 스레드
 *     ------+--------------------------+--------------------
 *     0.0초 | start() 호출 후 곧바로   | 계산 시작
 *           | result 를 출력해 버림!   | 아직 계산 중...
 *           | --> 0 이나 중간값 출력   |
 *     0.1초 | (이미 잘못된 값 출력됨)  | 계산 완료 (너무 늦음)
 *
 *   [join 이 있을 때의 시간표 - 올바른 순서]
 *
 *     시각  | main 스레드              | 계산기 스레드
 *     ------+--------------------------+--------------------
 *     0.0초 | start() 호출             | 계산 시작
 *           | t1.join() 에서 대기...   | 계산 중...
 *     0.1초 | (아직 대기 중)           | 계산 완료, 종료
 *           | 깨어남! 다음 줄 실행     |
 *           | result 출력 --> 정확한 값|
 *
 * ------------------------------------------------------------------
 * 3. JSP/Spring 연결
 * ------------------------------------------------------------------
 *   Spring 의 @Async(비동기 처리), 병렬 데이터 조회 등에서
 *   "여러 작업을 동시에 시작하고 -> 전부 끝나길 기다렸다가 -> 합친다"
 *   라는 패턴을 쓰는데, 그 "기다렸다가" 의 기본 원리가 join 이다.
 * ==================================================================
 */

// ===========================================================
// [클래스 1] 1부터 max 변수 값 까지의 합계를 구하는 작업
// ===========================================================
class SumTask implements Runnable {
	
	int max; // 계산 범위의 끝 값. 생성자로 전달 받는다.
	long result = 0; // 계산 결과 값. 스레드가 끝난 뒤 main 메소드에서 꺼내 쓴다.
	
	// 생성자
	public SumTask(int max) {
		this.max = max;
	}
	
	// 스레드가 작업할 코드 작성하는 run메소드 오버라이딩
	@Override
	public void run() { // 작업: 1 부터 max 변수 값 까지의 합계 구하기
		
		for ( int i = 1 ; i <= max ; i++ ) {
			result += i ;
		}
		
		// 계산이 다 끝난 뒤 실행되는 코드 줄
		// Thread.currentThread() : 지금 이 코드를 실행 중인 스레드 객체를 얻고 (1단계)
		// .getName()				: 그 스레드의 이름을 얻는다. (2단계)
		System.out.println( Thread.currentThread().getName() + " 계산 완료");
	}
}

public class Thread03_Join {
	
	// main 스레드
	public static void main(String[] args) throws InterruptedException {
		
		// 작업 객체 (run 메소드가 작성된 클래스의 객체) 2개를 따로 만든다.
		SumTask task1 = new SumTask(100);	// 1부터 100까지의 합계를 구할 작업을 run 메소드 내부에서 코드에 의해 한다.
		SumTask task2 = new SumTask(1000);	// 1부터 1000까지의 합계를 구할 작업을 run 메소드 내부에서 코드에 의해 한다.
		
		// 실제 스레드 2개 만든다.
		// 방법
		// new Thread(작업객체, 스레드이름);
		Thread t1 = new Thread (task1, "계산기-1");
		Thread t2 = new Thread (task2, "계산기-2");
		
		// start() 의 동작 방식
		// 1. JVM 에 새 스레드를 하나 만들어 달라고 요청하고
		// 2. 그 새 스레드가 작업의 run()을 실행하게 한 뒤
		// 3. 자신(main 스레드)는 기다리지 않고, "곧바로" 다음 줄로 넘어간다
		// 4. 이 줄 이후 main 스레드 작업, 계산기-1 스레드, 계산기-2 스레드 세 스레드가 서로 동시에 일을 한다.
		t1.start();
		t2.start();
		
		// ── join() 이 없다면? ──
		// 아래 출력 코드가 계산이 끝나기 전에 실행되어
		// result가 0이거나 계산 중인 값이 출력될 수 있다 (헤더의 사고 시간표)
		
		// t1.join(); 의 동작 방식 (이 예제의 핵심!)
		//	1. 이 줄을 실행한 스레드(main)가 "대기 상태"로 바뀐다
		//		--> main은 이 줄에서 멈춰 있는다. CPU 도 안 쓴다
		//	2. t1 (계산기-1) 은 멈추지 않고 계속 계산한다.
		//	3. t1 의 run 이 끝나 t1 이 종료되면 JVM 이 main 을 깨운다
		//	4. main 이 다음 줄부터 다시 실행된다.
		//	만약 이 시점에 t1 이 이미 끝나 있으면? 기다릴 것이 없으므로
		//	멈추지 않고 즉시 다음 줄로 넘어간다.
		t1.join();
		
		// t2 도 같은 방식으로 종료를 기다린다.
		// t1 을 기다리는 동안  t2도 함께 작업하고 있었으므로
		// 이 줄에 왔을 때 t2 는 이미 작업이 끝나 있는 경우가 많다.
		t2.join();
		
		// main 스레드가 출력
		// 여기서 부터는 "두 계산이 모두 끝났다" 가 보장된 시점입니다.
		System.out.println("1~100 합계: " + task1.result );
		System.out.println("1~1000 합계: " + task2.result );
		
        /*
         * ==========================================================
         * 실행 결과 (앞의 두 줄 순서만 바뀔 수 있고 숫자는 항상 같다)
         * ----------------------------------------------------------
         *   계산기-1 계산 완료
         *   계산기-2 계산 완료
         *   1~100 합계   : 5050
         *   1~1000 합계  : 500500
         * ----------------------------------------------------------
         * [main 의 상태 변화 시간표]
         *
         *   구간               | main 의 상태
         *   ------------------+--------------------------------
         *   start() 두 번      | 실행 중 (시작만 시키고 통과)
         *   t1.join()         | 대기 (t1 종료를 기다림)
         *   t1 종료 순간         | 깨어나서 다음 줄로
         *   t2.join()         | t2 가 이미 끝났으면 즉시 통과,
         *                     | 아직이면 대기
         *   출력 두 줄           | 실행 중 (값이 확정된 뒤라 안전)
         *
         * ■ 핵심 정리
         *   1. start() 는 "시작만" 시킨다. 끝나는 시점은 알 수 없다.
         *   2. join() 은 "부른 쪽이 기다리고, 붙은 대상은 계속 달린다".
         *   3. 스레드의 계산 결과를 쓰려면 join() 으로
         *      종료를 보장한 후에 꺼내 써야 한다.
         * ==========================================================
         */	

	}

}
