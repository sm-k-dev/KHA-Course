//부모 클래스
class Tv{
	boolean power;   //전원켜짐 true,  전원꺼짐 false 저장
	int     channel; //현재 채널 번호 저장
	
	public void power() { //전원을 켜거나 끄는 기능을 의미하는 메소드
		this.power = !power;
	}
	
	//현재 채널 번호를 1증가 시키는 기능의 메소드 
	public void channelUp() {
		++channel; //만약 channel변수의 값이 10일때 이메소드를 호출하면 ++ 1증가 되어 저장시킨다
	}
	
	//현재 채널 번호를 1감소 시키는 기능의 메소드
	public void channelDown() {
		--channel; //만약 channel변수의 값이 10일때  이메소드를 호출하면 -- 1감소 되어 저장 시킨다.
	}	
}

//자식 클래스 (기본 Tv기능 + 자막 내용 출력하는 기능)
