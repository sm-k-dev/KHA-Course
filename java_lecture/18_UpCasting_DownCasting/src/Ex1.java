class CaptionTv extends Tv {
	
	String text; //자막 내용을 보여주기 위해 자막내용을 문자열로 저장할 변수 
	
	public void caption() {   //자막 내용을 화면에 출력하는 기능의 메소드 
		System.out.println("자막 내용을 출력 기능이 추가된 CaptionTv 자식 클래스의 기능");
	}
}
