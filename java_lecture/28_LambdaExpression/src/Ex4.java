


//주제  Stream API 에서 제공하는 메소드들 살펴 보기 2 - distinct() / sorted()


import  java.util.ArrayList;      	//클래스.     asList() 메소드로 고정 크기 배열을 만들떄 사용
import java.util.Arrays;
import  java.util.Comparator;     	//인터페이스.  정렬 기준을 담는 함수형 인터페이스
import  java.util.List;           	//인터페이스.  목록의 공통 규격 (추상메소드들)
import  java.util.stream.Collectors;//클래스.   스트림 통로의 결과를 컬렉션 배열에 수집할때 사용 


public class Ex4 {
	public static void main(String[] args) {
		/*
		 중간연산 사용 메소드들

			distinct() 메소드
			- 스트림 통로에서 중복된 요소(객체)를 제거합니다.
			  이는 equals() 메소드를 기준으로 중복을 판별하므로,
			  객체의 경우 equals 메소드를 적절히 구현해야 정확하게 중복이 제거됩니다.
			- 내부 동작
			   Stream API 는 모든 객체(요소)들을 Set 구조와 유사하게 관리하여
			   중복을 제거합니다. Set 은 내부적으로 해시 기반이므로 성능이 좋습니다.

			   중복 제거 과정에서 기존 순서가 유지됩니다.

			- 매개변수가 없다는 점에 주의!
			   filter 나 map 과 달리 람다식을 전달하지 않는다.
			   "이미 지나간 값들" 을 스스로 기억했다가 비교하기 때문이다.
	*/		
		//1. 데이터들 준비 
		List<String> items = Arrays.asList("apple", "banana", "apple", "orange");
		/*
		  items 고정 크기 배열
		  ["apple", "banana", "apple", "orange"]  <- String 객체들이 각 칸에 저장된 고정 칸의 배열
		      0        1         2         3        index

		  주의 : 0번 칸과 2번 칸에 내용이 같은 "apple" 이 두 번 들어 있다
		*/
		
		//순서1. 준비된 items 고정 배열의  String 객체를 읽어들이기 위한 Stream 입력스트림 통로를 만들어 반환받자
		//      요약 : Stream<String> 통로 준비
		List<String> distinctItems = items.stream()		
									/*
																Stream<String> 객체 입력스트림 통로 ------> 읽어들이는 방향
																--------------------------------------------
									items 고정배열
									["apple","banana",          -> "orange" -> "apple" -> "banana" -> "apple"
									"apple","orange"]          --------------------------------------------
									          					(배열의 0번 칸부터 차례로 통로에 실린다)
									*/		
									//순서2. Stream 통로 객체의 distinct 메소드를 호출하면
									//		통로를 지나가는 문자열들을  equals 메소드로 비교하여 
									//		앞에서 이미 지나간 값과 내용이 같은 것을 제외한 Stream 통로 객체를 반환 
									     .distinct()
							       /*
															Stream<String> 통로 객체 ->
															------------------------------------
															  -> "orange" -> "banana" -> "apple"
															------------------------------------
											빠진 것 : 2번 칸의 "apple" (0번 칸의 "apple" 과 내용이 같아서 제외)
																					
											[distinct 의 중복 판정 과정]
											
											회차 | 값       | 이미 지나간 값 명단   | 판정        | 결과
											-----+----------+-----------------------+-------------+--------
											1    | "apple"  | (비어 있음)           | 처음 보는 값 | 통과
											2    | "banana" | apple                 | 처음 보는 값 | 통과
											3    | "apple"  | apple, banana         | 이미 있음!   | 빠진다
											4    | "orange" | apple, banana         | 처음 보는 값 | 통과
											
											※ 처음 나온 것이 남으므로 원래 순서가 그대로 유지된다
							*/
									//순서3. 위 Stream<String> 통로에 흘러가는 모든 문자열데이터들을 ArrayList 배열에 담아 반환 (종료 연산)
									       .collect(Collectors.toList());		
												/*
													["apple", "banana", "orange"]  <- ArrayList 가변 배열(컬렉션)
													    0         1         2         index
												 */
			//순서4. 최종 결과 ArrayList 배열 데이터 출력
			System.out.println(distinctItems);    //[apple, banana, orange]

			//----------------------------------------------------------------------
			//  최종 결과 상태
			//----------------------------------------------------------------------
			//  items         : ["apple", "banana", "apple", "orange"]  (변경 없음)
			//  distinctItems : ["apple", "banana", "orange"]           (새로 생성된 리스트)
			//
			//  ※ 스트림은 원본 배열을 절대 건드리지 않는다. 항상 새 배열을 만들어 준다
			//----------------------------------------------------------------------	
		
			
			 /*
			 sorted() 메소드

			 - 스트림 통로에 있는 객체(요소)들을 오름차순 또는 지정된 Comparator 에 따라 정렬합니다.
			   기본적으로 Comparable 인터페이스를 구현한 클래스(예: String, Integer 등) 들이
			   오름차순으로 정렬됩니다. 정렬 기준을 변경하려면
			   Comparator 인터페이스의 자식 구현 객체를 전달할 수 있습니다.

			 - 사용하는 2가지 형태
			     형태 1 : sorted()              <- 괄호가 빈다. 기본 오름차순
			     형태 2 : sorted( 비교기준 )    <- 기준을 직접 전달한다

			 - 주의 : sorted 는 정렬을 하려면 통로의 값을 "전부" 모아야 한다.
			          그래서 앞의 값이 다 지나갈 때까지 기다렸다가 한꺼번에 정렬한 뒤
			          다시 앞에서부터 흘려보낸다.
			  */
			//1. 데이터 준비
			List<Integer> numbers  = Arrays.asList(3, 5, 1, 4, 2);
			   /*
			     numbers 고정 크기 배열
			     [3, 5, 1, 4, 2]  <- Integer 객체들이 각 칸에 저장된 고정 칸의 배열
			      0  1  2  3  4      index
			   */
			//====================================================
			// [형태 1] sorted() -  기본 오름 차순 정렬
			//====================================================
			
			//순서1. numbers 고정칸 배열의 Integer 객체를 읽어들이기 위한 Stream 통로 준비
			List<Integer> sortedNumbers =  numbers.stream()
/*
												Stream<Integer> 통로 객체 ------> 읽어들이는 방향
												------------------------------
							numbers 고정배열
							[3, 5, 1, 4, 2]           -> 2 -> 4 -> 1 -> 5 -> 3
												------------------------------
*/			
		   //순서2. 괄호가 빈 sorted 를 호출하면 기본 오름차순(작은 값이 앞)으로
		   //      정렬된 Stream 통로 객체를 반환
		   //      Integer 클래스에 이미 "숫자는 작은 것이 먼저" 라는 기준이 만들어져 있어서
		   //      기준을 따로 주지 않아도 정렬이 된다									  
											       .sorted()
  /*
													Stream<Integer> 통로 객체 -> (오름차순 정렬 후)
													------------------------------
													  -> 5 -> 4 -> 3 -> 2 -> 1
													------------------------------
													 (통로 맨 앞에서 1 부터 꺼내진다)
*/			
	      //순서3. 통로의 모든 데이터를 ArrayList 배열에 담아 반환	
											       .collect(Collectors.toList());
			
			System.out.println(sortedNumbers);  // [1, 2, 3, 4, 5]  <- ArrayList
			
			
			   //================================================================
			   // [형태 2] sorted( Comparator.reverseOrder() ) - 내림차순 정렬
			   //================================================================

			   //순서1. 같은 numbers 배열로 Stream 통로를 "새로" 준비한다
			   //      (스트림 통로는 1회용이라 위에서 쓴 통로를 다시 쓸 수 없다)
			   List<Integer>  newNumbers = numbers.stream()
	/*
										Stream<Integer> 통로 객체 ->
										------------------------------
										  -> 2 -> 4 -> 1 -> 5 -> 3
										------------------------------
	*/
			   //순서2. Comparator.reverseOrder() 는 "기본 순서를 뒤집은 정렬 기준" 객체를 만들어 준다.
			   //      그 기준을 sorted 에 전달하면 내림차순(큰 값이 앞)으로 정렬된 통로 객체를 반환
			                                      .sorted( Comparator.reverseOrder() )
	/*
										Stream<Integer> 통로 객체 -> (내림차순 정렬 후)
										------------------------------
										  -> 1 -> 2 -> 3 -> 4 -> 5
										------------------------------
										 (통로 맨 앞에서 5 부터 꺼내진다)
	*/
			   //순서3. 통로의 모든 데이터를 ArrayList 배열에 담아 반환
			                                      .collect(Collectors.toList());
			   //[5, 4, 3, 2, 1]

			   System.out.println(newNumbers);   //[5, 4, 3, 2, 1]  <-- ArrayList

			   //----------------------------------------------------------------------
			   //  최종 결과 상태
			   //----------------------------------------------------------------------
			   //  numbers       : [3, 5, 1, 4, 2]   (변경 없음. 원본은 그대로다)
			   //  sortedNumbers : [1, 2, 3, 4, 5]   (새로 생성된 리스트)
			   //  newNumbers    : [5, 4, 3, 2, 1]   (새로 생성된 리스트)
			   //----------------------------------------------------------------------

			   /*
			   참고.
			   Comparator 란?

			   Comparator 는 객체를 비교하기 위한 함수형 인터페이스입니다.

			   특정 기준에 따라 두 객체를 비교하고, 그 결과에 따라 정렬 순서를 결정합니다.

			   이 인터페이스는 compare(T o1, T o2) 메소드를 구현하여 두 객체의 크기를 비교합니다.

			   이 compare 메소드는 다음과 같은 값을 반환합니다:
			   		0   : 두 객체가 동일함
			   		양수 : 첫 번째 객체가 두 번째 객체보다 큼
			   		음수 : 첫 번째 객체가 두 번째 객체보다 작음

			   [정렬이 정해지는 과정 - 값 3 과 5 를 비교할 때]

			     기본 오름차순 sorted()
			       compare(3, 5) 호출 --> 3 이 5 보다 작으므로 음수 반환
			       --> 첫 번째 값(3)을 앞에 둔다 --> 작은 값이 앞 (오름차순)

			     reverseOrder() 를 준 sorted()
			       기본 결과의 부호를 뒤집는다 --> 양수로 바뀜
			       --> 두 번째 값(5)을 앞에 둔다 --> 큰 값이 앞 (내림차순)

			   Comparator.reverseOrder() 의 사용

			   Comparator.reverseOrder() 는 기본 정렬 순서(오름차순)를 반전시켜
			   내림차순 정렬을 위한 Comparator 객체를 생성합니다.

			   이 메소드는 숫자, 문자열 등 Comparable 인터페이스를 구현한 클래스의 객체를
			   내림차순으로 정렬하는 데 유용합니다.

			   [참고] 직접 람다식으로 기준을 만들 수도 있다
			     .sorted( (a, b) -> a - b )   <- 오름차순 (reverseOrder 없이 sorted() 와 같은 결과)
			     .sorted( (a, b) -> b - a )   <- 내림차순 (reverseOrder() 와 같은 결과)
			     외우는 법 : "앞에 오길 원하는 쪽을 뒤에 빼면 된다"
			    */

		}   //main 의 끝

	}   //Ex4 클래스의 끝

	/*
	 ==================================================================
	 전체 예상 출력
	 ------------------------------------------------------------------
	 [apple, banana, orange]
	 [1, 2, 3, 4, 5]
	 [5, 4, 3, 2, 1]
	 ==================================================================
	 핵심 정리

	 1. distinct()
	      - 괄호가 비어 있다. 람다식을 전달하지 않는다.
	      - equals 로 내용을 비교해 "처음 나온 값" 만 남긴다.
	      - 원래 순서는 그대로 유지된다.

	 2. sorted()
	      - 괄호가 비면 기본 오름차순 (Integer, String 등에 미리 기준이 있다).
	      - 괄호에 기준을 주면 그 기준대로 정렬한다.
	      - Comparator.reverseOrder() 를 주면 내림차순이 된다.

	 3. 두 메소드 모두 "중간 연산" 이므로 통로 객체를 반환한다.
	    따라서 . 으로 계속 이어 붙일 수 있고,
	    종료 연산(collect)이 호출되어야 비로소 데이터가 흐른다.

	 4. 원본 고정배열(items, numbers)은 절대 변하지 않는다.
	    스트림은 항상 새 ArrayList 를 만들어 돌려준다.

	 5. 스트림 통로는 1회용이다.
	    같은 배열이라도 조회할 때마다 stream() 을 새로 호출해야 한다.
	 ==================================================================
	*/








