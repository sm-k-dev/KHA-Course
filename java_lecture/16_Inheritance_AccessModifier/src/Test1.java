/*
 [문제3] 다음 중 this에 대한 설명으로
        맞지 않은 것은 무엇인가? (모두 고르시오)
        
 정답 : 4
 이유 : 

	1. 객체 자신을 가리키는 참조변수이다.
	
	2. 클래스 내에서라면 어디서든 사용할 수 있다. - '현재 생성된 인스턴스 자기 자신'을 가리키는 참조변수
										- 인스턴스가 존재하지 않을 수도 있는 static 메서드(클래스 메서드) 내에서는 사용할 수 없습니다.
	
	3. 지역변수와 인스턴스변수를 구별할 때 사용한다.
	
	4. 클래스 메서드 내에서는 사용할 수 없다. - static 메서드 안에서는 this를 쓸 수 없다.
	
static 영역에서 this를 사용할 수 없는 이유는 간단히 말해 "메모리에 만들어지는 시점이 서로 다르기 때문"이에요.
이유를 조금 더 쉽게 세 가지 단계로 나누어 설명해 드릴게요.

1. static은 "건물 설계도", this는 "실제 완성된 집"
static (클래스 멤버): 프로그램이 시작되자마자 딱 한 번 메모리에 즉시 생성됩니다. 객체를 만들지(new 하지) 않고도 언제든 가져다 쓸 수 있어요.
this: new 키워드를 통해 실제로 생성된 자기 자신(인스턴스)을 가리키는 참조변수입니다.

2. 존재하지 않는 것을 가리킬 수 없어요
static 메서드가 실행되는 시점에는 객체(this)가 메모리에 아직 하나도 만들어지지 않았을 가능성이 높습니다.

3. 결론 요약
static은 객체가 없어도 호출할 수 있는데, this는 반드시 객체가 있어야만 존재할 수 있다.
따라서 static 메서드 안에서는 this를 사용할 수 없습니다.

static은 '공용 공간', this는 '개인 소유물'이라고 생각하시면 이해하시기 훨씬 편할 거예요. 공용 공간에서는 개개인의 소유물을 특정해서 부를 수 없으니까요!
*/

