package sec08.exam02;
/*
================================================================================
 정적 중첩 인터페이스 + 익명 구현 객체 - 웹 로그인 처리
================================================================================

 1. 이 예제의 목표
    - 웹사이트의 로그인 처리를 Button 예제와 똑같은 구조로 만든다.
    - 웹 개발에서 로그인 요청이 오면 서버는 두 갈래 중 하나로 응답한다.
        성공 -> 메인 페이지로 이동시킨다.
        실패 -> 로그인 페이지에 실패 이유를 표시한다.
    - "성공했을 때 할 일 / 실패했을 때 할 일"을 익명 구현 객체로 등록해 둔다.

 2. Button 예제와의 구조 비교 (구조가 완전히 같다)

    Button 예제                          이 예제
    ------------------------------      -----------------------------------
    Button (바깥 클래스)                 LoginController (바깥 클래스)
    ClickListener (중첩 인터페이스)      LoginListener (중첩 인터페이스)
    onClick() 추상메소드 1개             onSuccess(), onFail() 추상메소드 2개
    setClickListener() 로 등록           setLoginListener() 로 등록
    click() 이 이벤트 발생               login() 이 요청 도착
    클릭 -> onClick() 실행               검사 결과에 따라 onSuccess()/onFail() 실행

 3. 왜 이렇게 만드는가?
    - LoginController 는 "아이디와 비밀번호를 검사한다"는 판단만 담당한다.
    - 성공/실패 후에 무엇을 할지(어느 페이지로 보낼지, 무슨 문구를 띄울지)는
      회사·화면마다 달라지므로, 컨트롤러에 고정하지 않고
      사용하는 쪽이 익명 구현 객체로 등록하게 만든다.
    - 그래서 이후 응답 화면이 바뀌어도 LoginController 코드는 수정할 필요가 없다.
    - 실제 스프링 시큐리티의 로그인 성공/실패 핸들러 등록 방식이 이 구조다.

 4. 전체 동작 순서 (요청 1건 기준)
    순서1. LoginController 객체 생성
    순서2. setLoginListener() 로 익명 구현 객체(성공/실패 시 할 일)를 등록
           -> 컨트롤러 내부의 loginListener 변수에 주소가 저장됨
    순서3. login(아이디, 비밀번호) 호출(로그인 요청 도착)
           -> 검사 통과   : 등록된 객체의 오버라이딩된 onSuccess() 실행
           -> 검사 불통과 : 등록된 객체의 오버라이딩된 onFail() 실행

 [전체 실행 결과]
 [요청] POST /login  id=hong
 [응답 200] 로그인 성공! hong님, 메인 페이지(/main)로 이동합니다.
 [요청] POST /login  id=hong
 [응답 401] 로그인 실패 - 비밀번호가 일치하지 않습니다. 로그인 페이지를 다시 표시합니다.
 [요청] POST /login  id=park
 [응답 401] 로그인 실패 - 존재하지 않는 아이디입니다. 로그인 페이지를 다시 표시합니다.
================================================================================
*/

//--------------------------------------------------
//바깥(외부) 클래스 : LoginController
//실무에서 로그인 요청을 받아 처리하는 자리를 컨트롤러라고 부른다.
//--------------------------------------------------
class LoginController {
	
	//======================================================================
	//정적 중첩 인터페이스 : 로그인 결과 규칙 추상메소드 제공
	//----------------------------------------------------------------------
	//"로그인 성공하면 onSuccess() 를, 실패하면 onFail() 을 실행한다" 는 규칙만 정한다.
	// 실제 구현 내용은 이 인터페이스를 구현하는 쪽(main 메소드의 익명 구현 객체) 이 정한다.
	//======================================================================
	public static interface LoginListener {
		
		//추상 메소드 1  : 로그인 성공시 실행할 동작. 매개변수로 성공한 아이디 전달 받는다.
		void onSuccess(String userId);
		
		//추상 메소드 2  : 로그인 실패시 실행할 동작. 매개변수로 실패 이유를 메세지로 전달 받는다.
		void onFail(String reason);	
	}
	//====================================================================
	//회원 정보 (검사 기준값 정하자)
	//--------------------------------------------------------------------
	//이 예제에서 가입된 회원이 1명이라고 가정하고 상수로 둔다.
	//실무에서는 이 값을 데이터베이스에서 조회한다.
	//=====================================================================
	private static final String SAVED_ID = "hong";
	private static final String SAVED_PASSWORD = "1234";
	
	
	//==================================================================
	//인스턴스 변수  :  등록된 로그인 결과 처리 객체의 주소를 저장
	//--------------------------------------------------------------------
	//자료형이 인터페이스(LoginListener)이므로,
	//이 인터페이스를 구현한 어떤 객체든(익명 구현 객체 포함) 저장할 수 있다.
	//===================================================================
	private LoginListener loginListener;
	
	//====================================================================
	//setter :  로그인 결과 처리 등록
	//====================================================================
	public void setLoginListener(LoginListener loginListener) {
		this.loginListener = loginListener;
	}
	
	//====================================================================
	//login() 메소드 :  로그인 요청 처리 
	//-------------------------------------------------------------------
	//아이디와 비밀번호를 검사하고, 결과에 따라 등록된 익명 구현 객체의 onSuccess() 또는 onFail() 을 실행한다
	//
	public void login(String id,  String password) {
						//"hong",        "1234"
						//"hong",        "9999"
		
		//웹브라우저가 로그인 폼을 전송하면 서버에 이런 요청이 도착합니다.
		//"POST 는  데이터를 담아 보내는 요청 방식 의 이름이다."
		System.out.println("[요청] POST /login id=" + id);
		
		//검사1  : 아이디가 가입된 회원의 아이디인지 확인
		// 문자열 비교는 == 이 아니라 equals() 를 사용한다.
		// 상수를 앞에 두면(SAVED_ID.equals(id)) id 가 null 이어도 오류가 나지 않는다.
		if(SAVED_ID.equals(id) == false) {
		  
			//실패 이유를 담아 onFail() 실행 -> 실제 내용은 등록된 익명 구현 객체가 결정
			this.loginListener.onFail("존재하지 않는 아이디 입니다.");
			return; // 아래 검사를 하지 않고 즉시 login 메소드 종료 		
		}
		//검사2  : 비밀번호가 일치하는지 확인
		//-> 비밀번호를 제대로 입력하지 않았다면?
		if(SAVED_PASSWORD.equals(password)  ==  false) {
			     
			this.loginListener.onFail("비밀번호가 일치하지 않습니다.");
			return;
		}
		
		//두 검사를 모두 통과 ( DB의 아이디, 비번 과  로그인요청시 입력한 아이디, 비번이 모두 일치하면 )
		//-> 로그인 입력한 아이디를 onSucces메소드 호출할때 매개변수로 전달 
		this.loginListener.onSuccess(id);
		
	}// <============================================= login메소드 끝
	
} // <========== LoginController 클래스 끝 



public class LoginExample {

	public static void main(String[] args) {
		
		//순서1. 로그인 컨트롤러 객체 생성
		LoginController  controller = new LoginController();
		
		//--------------------------------------------------------
		//순서2. 로그인 결과 처리 를 하는 익명 구현 객체 등록
		//---------------------------------------------------------
		controller.setLoginListener(new  LoginController.LoginListener() {		
			@Override
			public void onSuccess(String userId) {
				//성공 응답 : 실무에서는 메인 페이지로 이동시키는 응답을 보낸다.
				//200 은 "요청 성공"을 뜻하는 HTTP 상태 코드이다.
				System.out.println("[응답 200] 로그인 성공! " + userId + "님, 메인 페이지로 이동합니다.");				
			}			
			@Override
			public void onFail(String reason) { //<----"비밀번호가 일치하지 않습니다."
				//실패 응답 : 실패 이유를 붙여 로그인 요청하는 페이지를 다시 보여 준다.
				//401 은 "인증 실패"를  뜻하는 HTTP 상태 코드이다.
				System.out.println("[응답 401] 로그인 실패 - " + reason + " 로그인 요청하는 페이지를 다시 표시합니다.");			
			}
		});
		
		//------------------------------------------------
		//순서3. 로그인 요청 3건 처리 
		//-----------------------------------------------
		
		//로그인 요청1. 아이디와 비밀번호가 모두 DB(상수 2개의 값)아 모두 일치  -> onSuccess() 실행
		controller.login("hong", "1234");
		
		//로그인 요청2. 아이디는 맞지만 비밀번호 틀림   ->  onFail() 실행
		controller.login("hong", "9999");
		
		//로그인 요청3. 가입 되지 않은 아이디 , 비밀번호 맞음 -> onFail() 실행
		controller.login("park", "1234");
		
		// --------------------------------------------------------------
		// 정리
		// --------------------------------------------------------------
		// LoginController 는 "검사"만 하고,
		// 성공/실패 후의 실제 응답 내용은 등록된 익명 구현 객체가 결정했다.
		// 응답 문구나 이동할 페이지가 바뀌어도 익명 객체 내부만 다시 쓰면 되고,
		// LoginController 코드는 한 줄도 고치지 않는다.
		// Button 예제의 클릭 이벤트 구조가 웹 로그인에 그대로 적용된 것이다.
	}

}










