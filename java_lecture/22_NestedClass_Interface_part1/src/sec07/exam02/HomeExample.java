package sec07.exam02;
/*
================================================================================
 익명 구현 객체 (Anonymous Implementation Object)
================================================================================

 1. 익명 구현 객체란?
    - 인터페이스를 구현해서 만든, 이름이 없는 자식 객체.
    - 익명 자식 객체(부모가 클래스)와 만드는 방식은 같고, 부모가 인터페이스라는 점만 다르다.

 2. 익명 자식 객체와의 차이 한 가지
    - 부모가 클래스면 : 오버라이딩은 선택이다. (안 하면 부모 원본이 실행됨)
    - 부모가 인터페이스면 : 추상메소드에는 실행 내용이 없으므로
      모든 추상메소드를 "강제로" 오버라이딩해야 한다. 하나라도 빠지면 컴파일 에러다.

 3. 익명 구현 객체 작성 문법

        new 부모인터페이스명() {
            // 인터페이스의 추상메소드 전부를 강제로 오버라이딩
        };

    이 한 문장의 의미는 두 가지다.
    의미1. 부모 인터페이스를 구현한 이름 없는 자식 클래스를 만든다.
    의미2. 동시에 그 자식 클래스의 객체 1개를 JVM의 힙 메모리에 생성한다.

    참고. 인터페이스는 원래 new 로 객체를 만들 수 없다.
         위 문장에서 new 뒤에 인터페이스명이 오지만, 실제로 생성되는 것은
         인터페이스가 아니라 "그 인터페이스를 구현한 이름 없는 자식 클래스"의 객체다.

 4. 이 파일에서 익명 구현 객체를 사용하는 위치 3곳
    ① 인스턴스 변수(rc)에 저장            -> use1() 에서 사용 (TV)
    ② 메소드 안 지역 변수(rc)에 저장       -> use2() 에서 사용 (에어컨)
    ③ 메소드 호출 시 매개변수로 바로 전달  -> use3() 에서 사용 (난방)

 [전체 실행 결과]
 Tv의 전원을 켭니다.
 Tv의 전원을 끕니다.
 에어컨의 전원을 켭니다.
 에어컨의 전원을 끕니다.
 난방을 켭니다.
 난방을 끕니다.
================================================================================
*/

//-----------------------------------------------
//부모 인터페이스  : RemoteControl
//----------------------------------------------
interface RemoteControl {

	// 추상메소드 : 몸통 { } 구현부가 없이 세미콜론 ; 으로 끝나는 메소드.

	void turnOn(); // 전원을 켠다

	void turnOff(); // 전원을 끈다
}

//----------------------------------------------------------
//Home 클래스 : 익명 구현 객체를 3가지 위치에서 사용해 보기 위해 만든다
//----------------------------------------------------------
class Home {

	// ==================================================
	// 사용위치1 : 인스턴스변수에 익명 구현 객체 생성해서 저장
	// 변수의 자료형은 부모 인터페이스(RemoteControl)이고,
	// 저장되는 것은 그 인터페이스를 구현한 익명 구현객체의 주소다.
	// (부모 타입 변수 = 자식 객체 : 자동 타입 변환) <=== 업캐스팅
	// ==========================================================================

	// 해석1. new 부모인터페이스명() { 메소드오버라이딩 };
	// => 부모인터페이스 내부에 만들어 놓은 모든 추상메소드를 강제로 오버라이딩 시킨 익명구현클래스와 익명구현객체 생성

	// 해석2. private RemoteControl rc = new 부모인터페이스명() { 메소드오버라이딩 };
	// => rc참조변수에 업캐스팅해서 익명구현객체의 주소 저장

	private RemoteControl rc = new RemoteControl() {

		// 부모 RemoteControl 인터페이스 내부에 작성된 추상메소드들 모두 강제 메소드 오버라이딩
		@Override
		public void turnOn() {
			System.out.println("TV의 전원을 켭니다.");
		}

		@Override
		public void turnOff() {
			System.out.println("TV의 전원을 끕니다.");
		}
	};

	// ===================================================
	// use1() 메소드 : 인스턴스 변수 rc에 저장된 익명 구현 객체 사용
	// ===================================================
	public void use1() {

		// rc 인스턴스변수에 저장된 익명구현 객체 안의, 메소드 오버라이딩된 메소드가 최종 실행된다.
		this.rc.turnOn();
		this.rc.turnOff();
	}

	// =================================================================
	// 사용 위치 2 : 메소드 안 지역 변수에 익명 구현 객체 생성해서 저장
	// -----------------------------------------------------------------
	// 이 rc 는 use2() 안에서만 쓰이는 지역 변수다.
	// 위의 인스턴스 변수 rc 와 이름이 같지만 서로 다른 변수이며,
	// 메소드 안에서는 지역 변수 rc 가 우선한다.
	// ==========================================================================
	public void use2() {

		RemoteControl rc = new RemoteControl() {

			@Override
			public void turnOn() {
				System.out.println("에어컨의 전원을 켭니다.");
			}

			@Override
			public void turnOff() {
				System.out.println("에어컨의 전원을 끕니다.");
			}
		};

		// 지역변수 rc 에 저장된 익명구현객체의 오버라이딩된 메소드 실행
		rc.turnOn(); // "에어컨의 전원을 켭니다."
		rc.turnOff(); // "에어컨의 전원을 끕니다."

	} // <========== use2 () 메소드 끝

	// =======================================================================
	// 사용 위치 3 : 메소드의 매개변수로 익명 구현객체 전달 받기
	// -----------------------------------------------------------------------
	// 매개변수 자료형이 인터페이스(RemoteControl)이므로,
	// 호출하는 쪽(main 메소드 쪽)에서 익명 구현 객체를 만들어 바로 전달할 수 있다.
	// =======================================================================
	public void use3(RemoteControl rc) {

		// 매개변수 rc에는 use3 메소드를 호출하는 쪽(main 메소드 쪽)이 만들어 보낸 익명구현객체의 주소가 전달된다.
		rc.turnOn();
		rc.turnOff();
	}

} // <=================== class Home 끝

public class HomeExample {
	public static void main(String[] args) {
		// Home 클래스의 객체 생성
		// 이 순간 인스턴스 변수 rc 의 초기값 문장도 실행되어 TV용 익명 구현객체가 함께 만들어진다.
		Home home = new Home();

		// --------------------------------------------------------
		// [1] Home객체의 인스턴스 변수 rc에 저장된 익명 구현객체 사용(TV용)
		// --------------------------------------------------------
		// 출력:
		// TV의 전원을 켭니다.
		// TV의 전원을 끕니다.
		home.use1();

		// ---------------------------------------------------------------------------------
		// [2] Home클래스에 포함된 use2()메소드 내부에 만들어진 지역변수 rc 의 익명구현객체 사용 (에어컨 용)
		// ----------------------------------------------------------------------------------
		// 출력:
		// 에어컨의 전원을 켭니다.
		// 에어컨의 전원을 끕니다.
		home.use2();

		// ---------------------------------------------------------------------------------
		// [3] use3(RemoteControl rc) 메소드의 매개변수로 익명구현객체 생성해서 전달해 사용 (난방 용)
		// ----------------------------------------------------------------------------------
		// use3 의 매개변수 자리에서 익명 구현 객체를 만들어 바로 넘긴다.
		// 변수에 저장하지 않으므로, 이 익명 구현 객체는 이 호출 한 번에만 쓰고 버려진다.
		
		// 출력:
		//난방을 켭니다.
		//난방을 끕니다.
		home.use3(new RemoteControl() {

			@Override
			public void turnOn() {
				System.out.println("난방을 켭니다.");
			}

			@Override
			public void turnOff() {
				System.out.println("난방을 끕니다.");
			}

		});

	} // <================= main 메소드 끝

}// <================= class HomeExample 끝
