package sec07.exam01;
/*
================================================================================
 익명 자식 객체 (Anonymous Child Object)
================================================================================

 1. 익명 클래스란?
    - 이름이 없는 클래스.
    - 클래스 선언과 객체 생성을 한 문장에서 동시에 처리한다.

 2. 익명 객체란?
    - 이름이 없는 클래스로 만든, 이름이 없는 객체.

 3. 익명 객체의 두 종류
    ① 익명 자식 객체 : 클래스를 상속받아 만든 이름 없는 자식 객체. (이 파일의 주제)
    ② 익명 구현 객체 : 인터페이스를 구현해 만든 이름 없는 자식 객체.

 4. 익명 자식 객체 작성 문법

        new 부모클래스생성자() {
            // 오버라이딩 코드 작성 위치
        };

    이 한 문장의 의미는 두 가지다.
    의미1. 부모클래스를 상속받은 이름 없는 자식 클래스를 만든다.
    의미2. 동시에 그 자식 클래스의 객체 1개를 힙 메모리에 생성한다.

    끝의 세미콜론(;)까지가 하나의 문장이므로 반드시 붙여야 한다.

 5. 언제 쓰는가?
    - 자식 클래스가 한 번만 필요할 때.
    - 자식 클래스 파일(.java)을 따로 만들지 않아도 되므로 코드가 짧아진다.

 6. 이 파일에서 익명 자식 객체를 사용하는 위치 3곳
    ① 인스턴스 변수(tire2)에 저장         -> run1() 에서 사용
    ② 메소드 안 지역 변수(tire)에 저장    -> run2() 에서 사용
    ③ 메소드 호출 시 매개변수로 바로 전달 -> run3() 에서 사용

 [전체 실행 결과]
 일반 타이어가 굴러 갑니다.
 익명자식 클래스의 객체1이 굴러갑니다.
 익명 자식클래스의 객체2가 굴러 갑니다.
 Tire부모클래스의 익명 자식 객체 3이 굴러갑니다.
================================================================================
*/
//------------------------------------------------
//부모 클래스  : Tire
//------------------------------------------------
class Tire {
	
	// 생성자를 직접 작성하지 않았다.
	// 이 경우 컴파일러(javac)가 기본생성자 public Tire() {} 를 자동으로 만들어 준다.
	// 아래에서 new Tire() 를 호출할 수 있는 이유가 이 기본생성자 덕분이다.
	
	//일반 메소드 : 자식 쪽에서 오버라이딩 하지 않으면  이 내용이 상속되어 실행된다.
	public void roll() {
		System.out.println("일반 타이어가 굴러 값니다.");
	}
}

//--------------------------------------------------------
// Car 클래스  : 익명 자식 객체를 3가지 위치에서 사용해 본다.
//--------------------------------------------------------
class Car {
	
	//=========================================================
	//[비교용] 일반 객체 생성
	//----------------------------------------
	//Tire 클래스로 평범하게 객체를 만들어 주소를 저장한다
	//tire1.roll(); 을 호출하면  부모 Tire의 원본 roll() 이 실행된다.
	//========================================================
	private Tire tire1 = new Tire();
	
	//=======================================================
	//사용 위치 1 :  인스턴스 변수에 익명 자식 객체 저장
	//-----------------------------------------------------
	// new Tire() { ... } 는
	//  - Tire 를 상속받은 이름 없는 자식 클래스를 만드는 동시에
	//  - 그 자식 객체 1개를 생성한다.
	// 변수의 자료형이 부모(Tire)인데 자식 객체를 저장할 수 있는 이유는
	// 자동 타입 변환(부모 타입 변수 = 자식 객체) 때문이다.
	//=========================================================
	private Tire tire2 = new Tire() {
		
			//부모 Tire클래스에 만들어 놓은 roll() 을 메소드 오버라이딩(재정의)한다
			@Override
			public void roll() {
				System.out.println("익명자식 클래스의 익명객체1 타이어가 굴러갑니다.");
			}		
	 };
	 
	//=========================================================================================
	//run1() 메소드  : 위 두 인스턴스 변수 tire1, tire2에 저장된 각 객체의 roll()을 호출해 차이를 확인한다.
	//=======================================================================================
	public void run1() {
		
		//1.tire1 인스턴스변수에 저장된 new Tire(); 객체의 roll()메소드 호출해서 실행!
		// -> 부모 원본 roll() 실행 : "일반 타이어가 굴러 갑니다."
		this.tire1.roll();
		
		//2. tire2 인스턴스변수에 저장된  이름이 없는 익명자식객체의 메소드 오버라이딩 시켜 놓은 roll()메소드 호출해서 실행!
		// -> 메소드 오버라이딩된 roll() 실행 : "익명자식 클래스의 익명객체1 타이어가 굴러갑니다."
		this.tire2.roll();

	}
	//======================================================
	//사용위치 2 : 메소드 안 지역 변수에 익명 자식 객체 저장
	//------------------------------------------------------
	// 익명 자식 객체는 메소드 내부의 지역 변수에도 저장할 수 있다.
	// 이 객체는 run2() 실행 중에만 사용된다.
	// =====================================================
	public void run2() {
		
		Tire tire = new Tire() {
					
			@Override
			public void roll() { //roll()메소드 오버라이딩 
				System.out.println("익명 자식클래스의 익명자식객체2의 타이어가 굴러갑니다.");
			}
		};
		
		//익명객체 내부에 포함한 메소드 오버라이딩 된  roll() 실행
		tire.roll();
		
	} //<========= run2() 메소드 끝
	
	
	//=============================================================
	// 사용위치 3  :  매개변수로 익명 자식 객체 전달 받기 
	//------------------------------------------------------------
	//매개변수 자료형이 부모(Tire)클래스 이므로,
	//호출하는 쪽에서 익명 자식 객체를 만들어  매개변수로 전달할 수 있다.
	//===========================================================
	public void run3(Tire  tire) {
		
		//tire 매개변수에는 호출하는 쪽(main 메소드 쪽)에서 만들어 보낸 익명 자식객체의 주소가 들어 있다.
		//-> 그 익명자식객체 안의 오버라이딩된 roll()메소드가 실행된다.
		tire.roll();
	}
} //<================= class Car  클래스 끝 

public class CarExample {
	public static void main(String[] args) {
		
		// Car 클래스의 객체 생성 (자동차 만들기)
		Car  car = new Car();
		
		//--------------------------------------------
		//[1] 인스턴스 변수 tire1 과  tire2에  저장된 익명자식 객체 사용
		//-------------------------------------------
		// 출력 : 
		//"일반 타이어가 굴러 갑니다."
		//"익명자식 클래스의 익명객체1 타이어가 굴러갑니다."
		car.run1();
		
		//-----------------------------------------------------
		//[2] run2() 메소드의  지역 변수 tire에  저장된 익명자식객체 사용
		//----------------------------------------------------
		//출력 : 
		//"익명 자식클래스의 익명자식객체2의 타이어가 굴러갑니다."
		car.run2();
		
		//----------------------------------------------------------------
		//[3] run3(Tire tire) 메소드의 매개변수로  익명 자식객체를 만들어 전달해 사용 
		//---------------------------------------------------------------
		car.run3(new Tire() {
			
				@Override
				public void roll() {
					System.out.println("Tire부모클래스의 익명자식객체3의 타이어가 굴러갑니다.");
				}
			
			} //<- 익명 클래스 닫기
		
		); //<- run3(); 중에서 );
		
		//출력:
		//Tire 부모클래스의 익명자식객체3의 타이어가 굴러갑니다.
		
		
	} //======> main() 메소드 끝

} //==============> class CarExample 클래스 끝









