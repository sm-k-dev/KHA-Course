
/*
========================================================
 Stack 클래스 (스택 자료구조)
========================================================

■ Stack이란?

- Stack은 여러 개의 데이터를 차곡차곡 쌓아 두는 자료구조입니다.
- 실제 생활의 "접시 쌓기", "책 쌓기"와 같은 구조입니다.
- 데이터를 넣고 꺼낼 수 있는 방향이 오직 한 곳(맨 위)뿐입니다.

--------------------------------------------------------
■ Stack의 가장 중요한 특징 : LIFO 구조
--------------------------------------------------------

- LIFO : Last In First Out (후입선출)
- 마지막에 들어간 데이터가 가장 먼저 나옵니다.

예)
  A → 먼저 넣음
  B → 나중에 넣음

  꺼낼 때 순서
  B → A

--------------------------------------------------------
■ Stack 메모리 구조 (텍스트 모델링)
--------------------------------------------------------

[아무것도 없는 상태]

┌───────────┐
│           │  ← top (없음)
└───────────┘


[push("A") 실행 후]

┌───────────┐
│     A     │  ← top
└───────────┘


[push("B") 실행 후]

┌───────────┐
│     B     │  ← top (맨 위)
├───────────┤
│     A     │
└───────────┘


[push("C") 실행 후]

┌───────────┐
│     C     │  ← top
├───────────┤
│     B     │
├───────────┤
│     A     │
└───────────┘

※ 항상 맨 위(top)만 접근 가능
※ 중간(A, B)은 직접 접근 불가

--------------------------------------------------------
■ Stack 클래스의 주요 메소드 설명
--------------------------------------------------------

1) push(E item)
----------------
- 스택의 맨 위(top)에 데이터를 추가하는 메소드
- 데이터를 "쌓는다"고 생각하면 된다.

예)
  stack.push("D");

[push 후 메모리]

┌───────────┐
│     D     │  ← top
├───────────┤
│     C     │
├───────────┤
│     B     │
├───────────┤
│     A     │
└───────────┘


2) pop()
---------
- 스택의 맨 위(top)에 있는 데이터를 꺼내면서
  동시에 스택에서 제거하는 메소드
- 제거된 데이터는 반환값으로 돌려준다.

예)
  stack.pop();   → "D" 반환

[pop 후 메모리]

┌───────────┐
│     C     │  ← top
├───────────┤
│     B     │
├───────────┤
│     A     │
└───────────┘


3) peek()
----------
- 스택의 맨 위(top)에 있는 데이터를 반환하지만
  스택에서 제거하지는 않는 메소드
- "몰래 보기" 용도

예)
  stack.peek();  → "C" 반환

[peek 후 메모리 변화 없음]

┌───────────┐
│     C     │  ← top (그대로)
├───────────┤
│     B     │
├───────────┤
│     A     │
└───────────┘


4) boolean empty()
------------------
- 스택이 비어 있는지 묻는 메소드
- 비어 있으면 true
- 하나라도 있으면 false

예)
  stack.empty();   → false


5) boolean isEmpty()
--------------------
- empty()와 완전히 같은 기능
- 이름만 다르고 역할은 동일

--------------------------------------------------------
■ empty() / isEmpty() 텍스트 모델링
--------------------------------------------------------

[스택이 비어 있는 상태]

┌───────────┐
│           │
└───────────┘

empty()   → true
isEmpty() → true


[스택에 데이터가 있는 상태]

┌───────────┐
│     A     │
└───────────┘

empty()   → false
isEmpty() → false

--------------------------------------------------------
■ Stack의 제한 사항 (중요)
--------------------------------------------------------

- Stack은 반드시 "맨 위(top)"에서만
  데이터를 추가(push) / 제거(pop) / 확인(peek) 가능
- 중간에 있는 데이터는 직접 접근 불가능
- 이 제약 덕분에 구조가 단순하고 예측 가능

--------------------------------------------------------
■ Stack이 실제로 사용되는 곳
--------------------------------------------------------

1) 프로그램 실행 구조 (Call Stack)
   - 메소드 호출 → push
   - 메소드 종료 → pop

2) 실행 취소(Undo / Redo)
   - 최근 작업부터 되돌리기

3) 웹 브라우저 뒤로 가기
   - 방문한 페이지를 순서대로 저장

4) 괄호 검사, 수식 계산
   - (, {, [ 처리

--------------------------------------------------------
■ Stack 한 줄 요약
--------------------------------------------------------

- Stack은 "위에서만 넣고, 위에서만 꺼내는 상자"
- 나중에 넣은 것이 먼저 나온다 (LIFO)
- push : 넣기
- pop  : 꺼내면서 제거
- peek : 꺼내지 않고 보기
- empty / isEmpty : 비어 있는지 확인

========================================================
*/

import java.util.Stack;

