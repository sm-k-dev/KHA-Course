/*

 패키지 : .class 자바 실행파일을 압축해 놓은 폴더 경로

 라이브러리 : 관련 있는 패키지들을 압축해 놓은 .jar파일

 프레임워크 : 라이브러리 파일들을 압축해 놓은 큰단위의 폴더

 API : 특정 자바프로그램과 특정 MySQL데이터베이스프로그램 등의 플랫폼을
       연결하는 중간 프로그램(JDBC API)

 컬렉션 라이브러리
 - 데이터를 저장할 가변으로 늘어나는 배열메모리를 만들때 사용되는 클래스들을 제공하는
   패키지들의 모음

 컬렉션 라이브러리 내부에 만들어서 제공하는 최상위 Collection이라는 이름의 인터페이스

 	하위 Set인터페이스
 	- Set인터페이스를 구현한 자식 가변길이 배열을 만들때 사용되는 클래스들은
 	  가변길이 배열을 만들어 객체(데이터)를 중복 저장을 허용하지 않고,
 	  또한 배열에 추가된 순서대로 객체를 저장하지 않고 랜덤으로 저장합니다.

 	하위 List인터페이스
 	- List인터페이스를 구현한 자식 가변길이 배열을 만들때 사용되는 클래스들은
 	  가변길이 배열을 만들어 객체(데이터)를 중복 저장을 허용하고,
 	  또한 배열에 추가된 순서대로 객체를 저장합니다.

 	하위 Map인터페이스
 	- Map인터페이스를 구현한 자식 가변길이 배열을 만들때 사용되는 클래스들은
 	  가변길이 배열을 만들어 객체(데이터)를 단독으로 저장하지 않고,
 	  (key-객체)를 한쌍으로 묶어 한쌍의 형태로 배열에 저장합니다.
 	  배열에 저장된 객체(데이터)를 얻으려면 key를 이용해서 객체(데이터)를 얻을수 있다


  주제: Set부모인터페이스를 구현한(추상메소드를 오버라이딩한)
       자식클래스 HashSet클래스를 사용하여 가변으로 칸이 늘어나는 가변길이 배열 만들기

  Set의 2대 특성 (이 파일에서 눈으로 확인할 것)
       특성 1. 중복 저장 금지  : 같은 객체(데이터)를 두 번 추가하면 두 번째는 거부된다.
       특성 2. 저장 순서 없음  : add한 순서대로 저장되지 않고 뒤섞여 저장된다.

*/

import java.util.Set;  		//부모 Set 인터페이스 사용을 위한 import
import java.util.HashSet;	//Set 부모인터페이스를 구현한 자식 HashSet클래스 사용을 위한 import

public class Collections01 {
	public static void main(String[] args) {
		
		//업캐스팅을 이용하여 부모 Set인터페이스 자료형의 참조변수를 만들고
		//자식 클래스인 HashSet클래스의 객체 메모리 생성후 주소번지 저장!
		//(부모 자료형으로 받아 두면 나중에 HashSet을 TreeSet 등 다른 자식으로
		// 교체할 때 이 한 줄만 고치면 되므로 실무에서는 부모 자료형을 사용한다)
		  Set set = new HashSet();
			/*
			 new HashSet(); 생성 직후의 가변길이 배열 메모리 (아직 비어 있음)

								-----         ------
									|         |
									|         |
									|_________|
			 */
		  //HashSet 가변길이 배열에 저장된 객체(데이터)의 갯수를 반환하는 size()메소드 호출
		  System.out.println("HashSet 가변 배열 메모리에 저장된 객체의 갯수 얻자 -> " + set.size()); //0
		  
		  //HashSet 가변길이 배열에 객체를 추가하기 위해 add(Object obj) 메소드 사용!
		  set.add("하나");   //String 객체 ("하나")의 주소번지가 배열에 추가됨
		  set.add(2);       //기본자료형 int 2는 객체가 아니므로 배열에 바로 저장할수 없다!
		  					//컴파일러가 Integer.valueOf(2) 를 자동으로 호출해
		  					//Integer 래퍼 객체로 포장한 후 저장한다.  = 자동(오토) 박싱
		  
		  set.add(3.42);    //자동(오토) 박싱이 일어나 Double.valueOf(3.42); 래퍼 객체가 추가되어 저장됨
		  set.add("넷");
		  set.add("five");
		  set.add( Integer.valueOf(6) );  //수동 박싱을 직접 작성해 new Integer(6); 레퍼 객체를 추가함
			/*
			 [수동 박싱 문법 변경 안내]
			 - 예전 문법: new Integer(6);
			 - 자바 9부터 new Integer(숫자)는 사용 자제(deprecated) 대상으로 지정되어
			   이클립스에서 노란 취소선(경고)이 표시된다. (컴파일과 실행은 아직 가능하다)
			 - 이유: new는 호출할 때마다 새 객체를 만들지만,
			         Integer.valueOf는 -128~127 범위의 Integer 객체를 미리 만들어 두고
			         재사용하므로 메모리를 절약한다. 그래서 valueOf 사용이 권장 문법이다.
			 - 자동 박싱도 내부적으로 Integer.valueOf를 호출한다.
			*/
		  
		  //HashSet 가변길이 배열에 저장된 객체(데이터)의 갯수를 반환하는 size()메소드 호출
		  System.out.println("HashSet 가변 배열 메모리에 저장된 객체의 갯수 얻자 -> " + set.size()); // 6
		  
			/*
			 add 6회 후의 가변길이 배열 메모리 (저장 순서는 add한 순서와 다름)

			-----         				 ------
				|   Integer.valueOf(2)   |
				|   "하나" 				 |
				|   Double.valueOf(3.42) |
				|   "five" 				 |
				|   "넷" 				 |
				|   Integer.valueOf(6)   |
				|________________________|
			*/
		  //====================================================================
		  // Set 인터페이스를 구현한 자식 클래스의 배열 특성 1  확인  :  객체 중복 저장 금지
		  //=====================================================================
		  
		  //add 메소드는 추가 성공 여부를 boolean(true/false)으로 반환한다.
		  // - 배열에 없던 객체를 추가하면 ->  저장하고 true 반환
		  // - 배열에 이미 있는 객체를 추가하면 -> 저장을 거부하고 false 반환
		  boolean result1 = set.add("여섯"); //"여섯" 은 배열에 없으므로 -> 저장 성공 true 반환
		  boolean result2 = set.add("하나"); //"하나" 는 이미 배열에 있으므로 -> 저장 거부  false 반환
		  boolean result3 = set.add(2);     // 2가 저장된 Integer래퍼객체가 이미 배열에 있으므로 -> 저장 거부 false 반환
		  
		  System.out.println("처음 추가하는 \"여섯\"  add 결과 ->  " + result1); //true  <- 배열에 추가 성공
		  System.out.println("이미 존재하는 \"하나\"  add 결과 ->  " + result2); //false <- 배열에 추가 실패 
		  System.out.println("이미 존재하는 2가 저장된 Integer래퍼객체  add 결과 -> " + result3); //false				
		  
		  //HashSet 가변길이 배열에 저장된 객체(데이터)의 갯수를 반환하는 size()메소드 호출
		  //중복 add 3회를 시도했지만 실제로 저장된 것은 "여섯" 1개뿐이므로 갯수는 6 -> 7
		  System.out.println("HashSet 가변 배열 메모리에 저장된 객체의 갯수 얻자 -> " + set.size());  // 7 
			/*
			 중복 add 시도 후의 가변길이 배열 메모리
			 ("하나"와 2는 거부되어 그대로 1개씩만 존재한다)

			-----         				 ------
				|   Integer.valueOf(2)   |
				|   "하나" 				 |
				|   Double.valueOf(3.42) |
				|   "five" 				 |
				|   "넷" 				 |
				|   Integer.valueOf(6)   |
				|   "여섯"               |
				|________________________|
			*/		  
		  //====================================================================
		  // Set 인터페이스를 구현한 자식 클래스의 배열 특성 2  확인  :  배열에 저장되는 순서 랜덤 
		  //=====================================================================
		  
		  //HashSet 가변 배열 메모리 내부에 저장된 객체들이 어떤것이 있는지 확인 하기 위해 
		  //toString() 메소드를 호출해 전체 배열 모습을 문자열로 변환해서 반환받아 출력
		  System.out.println( set.toString()  );
		  //HashSet배열에 랜덤으로 저장된 모습 문자열로 출력 :  "[2, 6, 넷, 하나, 여섯, 3.42, five]"
		  //add(Object obj) 메소드로  HashSet배열에 추가한 순서 : "하나"-> 2 -> 3.42 -> "넷" -> "five" -> 6 -> "여섯"
		  //결론 :  출력 순서가 추가한 순서와 전혀 다르다는 것을 확인 할수 있다.
		  
			
		/*
			결론 1 : HashSet 가변 길이 배열은 중복 저장을 허용하지 않는다.
			         이미 있는 객체를 add하면 저장을 거부하고 false를 반환한다.
			         (활용 예: 회원 아이디 중복 검사, 로또 번호처럼 중복이 없어야 하는 데이터)

			결론 2 : HashSet 가변 길이 배열에는 add메소드를 이용하여 추가된 객체들의
			         순서대로 저장되지 않고 랜덤으로 뒤섞여 저장됨.

			결론 3 : 수동 박싱은 new Integer(숫자) 대신 Integer.valueOf(숫자)를 사용한다.
			         (new Integer는 자바 9부터 deprecated - 경고 취소선 표시됨)
		*/
		

	}

}
